-- Optional output links do not require the request/action to point back to their output.
-- from_assignment and old_manager_assignment identify the BEFORE source, not the output row.
CREATE FUNCTION validate_personnel_assignment_link(kind TEXT,assignment_id BIGINT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE owner_id BIGINT; source_id BIGINT; action_id BIGINT; a personnel_change_actions; p personnel_change_requests;
        workflow_owner BIGINT; d BIGINT; t BIGINT;
BEGIN
 IF kind='EMPLOYEE' THEN
   SELECT employee_id,source_request_id,personnel_action_id INTO owner_id,source_id,action_id FROM employee_assignments WHERE id=assignment_id FOR SHARE;
 ELSE
   SELECT manager_id,source_request_id,personnel_action_id,department_id,team_id INTO owner_id,source_id,action_id,d,t FROM manager_assignments WHERE id=assignment_id FOR SHARE;
 END IF;
 IF action_id IS NULL THEN RETURN; END IF;
 SELECT * INTO a FROM personnel_change_actions WHERE id=action_id FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Assignment action source does not exist'; END IF;
 SELECT * INTO p FROM personnel_change_requests WHERE id=a.request_id FOR SHARE;
 SELECT target_employee_id INTO workflow_owner FROM workflow_requests WHERE id=p.workflow_request_id FOR SHARE;
 IF owner_id IS DISTINCT FROM workflow_owner OR source_id IS DISTINCT FROM p.workflow_request_id THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Assignment action must have same Employee and workflow source';
 END IF;
 IF kind='EMPLOYEE' AND assignment_id=p.from_assignment_id THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Before assignment cannot be its own personnel action output';
 END IF;
 IF kind='MANAGER' AND (assignment_id=a.old_manager_assignment_id OR owner_id IS DISTINCT FROM a.new_manager_employee_id OR
     d IS DISTINCT FROM a.target_department_id OR t IS DISTINCT FROM a.target_team_id) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Manager output must match explicit action target, not old manager source';
 END IF;
END $$;

CREATE FUNCTION validate_lifecycle_payload(wid BIGINT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE w workflow_requests; p personnel_change_requests; s employee_assignments; a personnel_change_actions;
        tmp temporary_inactive_requests; source_manager BIGINT; team_department BIGINT; outrow RECORD;
        destination_department BIGINT; destination_team BIGINT; destination_level VARCHAR(30); submitted BOOLEAN;
BEGIN
 SELECT * INTO w FROM workflow_requests WHERE id=wid FOR NO KEY UPDATE;
 IF NOT FOUND THEN RETURN; END IF;
 submitted:=w.status NOT IN('DRAFT','CANCELLED');
 IF w.request_type='PERSONNEL_CHANGE' THEN
   SELECT * INTO p FROM personnel_change_requests WHERE workflow_request_id=w.id;
   IF NOT FOUND THEN RETURN; END IF; -- main identity validator enforces existence
   IF p.from_assignment_id IS NOT NULL THEN
     SELECT * INTO s FROM employee_assignments WHERE id=p.from_assignment_id FOR SHARE;
     IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Personnel source assignment does not exist'; END IF;
     IF s.employee_id IS DISTINCT FROM w.target_employee_id THEN
       RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Personnel source belongs to another Employee';
     END IF;
   END IF;
   IF submitted AND (p.from_assignment_id IS NULL OR p.proposed_effective_date IS NULL OR p.reason IS NULL OR btrim(p.reason)='' OR
       NOT EXISTS(SELECT 1 FROM personnel_change_actions WHERE request_id=p.id)) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Submitted personnel change needs source, date, reason and actions';
   END IF;
   IF w.status IN('APPROVED','COMPLETED') AND p.approved_effective_date IS NULL THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Approved personnel change needs approved effective date';
   END IF;
   IF submitted AND NOT p.major_change AND EXISTS(SELECT 1 FROM personnel_change_actions WHERE request_id=p.id AND
       (action_type='DEPARTMENT_TRANSFER' OR (action_type IN('PROMOTION','DEMOTION') AND
        (old_management_level='DEPARTMENT_MANAGER' OR new_management_level='DEPARTMENT_MANAGER')))) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Known major action requires explicit major classification';
   END IF;
   destination_department:=s.department_id; destination_team:=s.team_id; destination_level:=s.management_level;
   -- Final typed destination metadata only, not an execution of actions or a projection update.
   FOR a IN SELECT * FROM personnel_change_actions WHERE request_id=p.id ORDER BY sequence_no LOOP
     IF a.action_type IN('TEAM_TRANSFER','DEPARTMENT_TRANSFER') THEN
       IF a.new_department_id IS NOT NULL THEN destination_department:=a.new_department_id; END IF;
       IF a.new_team_id IS NOT NULL THEN destination_team:=a.new_team_id; END IF;
     END IF;
     IF a.action_type IN('PROMOTION','DEMOTION') AND a.new_management_level IS NOT NULL THEN destination_level:=a.new_management_level; END IF;
   END LOOP;
   FOR a IN SELECT * FROM personnel_change_actions WHERE request_id=p.id ORDER BY sequence_no LOOP
     IF a.old_team_id IS NOT NULL THEN
       SELECT department_id INTO team_department FROM teams WHERE id=a.old_team_id FOR SHARE;
       IF a.old_department_id IS NOT NULL AND team_department IS DISTINCT FROM a.old_department_id THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Old Team must belong to old Department'; END IF;
     END IF;
     IF a.new_team_id IS NOT NULL THEN
       SELECT department_id INTO team_department FROM teams WHERE id=a.new_team_id FOR SHARE;
       IF a.new_department_id IS NOT NULL AND team_department IS DISTINCT FROM a.new_department_id THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='New Team must belong to new Department'; END IF;
     END IF;
     IF a.old_manager_assignment_id IS NOT NULL THEN
       SELECT manager_id INTO source_manager FROM manager_assignments WHERE id=a.old_manager_assignment_id FOR SHARE;
       IF source_manager IS DISTINCT FROM w.target_employee_id THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Old manager assignment belongs to another Employee'; END IF;
     END IF;
     IF a.new_manager_employee_id IS NOT NULL AND a.new_manager_employee_id IS DISTINCT FROM w.target_employee_id THEN
       RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Manager action must concern workflow target Employee'; END IF;
     IF submitted THEN
       IF (a.old_team_id IS NOT NULL AND a.old_department_id IS NULL) OR (a.new_team_id IS NOT NULL AND a.new_department_id IS NULL) THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Team snapshots need their typed Department'; END IF;
       IF a.action_type IN('PROMOTION','DEMOTION') AND (a.old_management_level IS NULL OR a.new_management_level IS NULL) THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Promotion/demotion needs explicit old and new level'; END IF;
       IF a.action_type='TEAM_TRANSFER' AND (a.old_department_id IS NULL OR a.new_department_id IS NULL OR
           a.old_department_id<>a.new_department_id OR a.old_team_id IS NULL OR a.new_team_id IS NULL OR a.old_team_id=a.new_team_id) THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Team transfer needs distinct Teams in same Department'; END IF;
       IF a.action_type='DEPARTMENT_TRANSFER' AND (a.old_department_id IS NULL OR a.new_department_id IS NULL OR
           a.old_department_id=a.new_department_id OR a.new_team_id IS NULL) THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Department transfer needs distinct Departments and destination Team'; END IF;
       IF a.action_type='MANAGER_ASSIGNMENT' AND a.old_manager_assignment_id IS NULL AND a.new_manager_employee_id IS NULL THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Manager action needs explicit assign or remove source'; END IF;
       IF a.new_manager_employee_id IS NOT NULL THEN
         IF (a.target_department_id IS NULL)=(a.target_team_id IS NULL) OR
             (a.new_management_level IS NOT NULL AND destination_level IS NOT NULL AND a.new_management_level<>destination_level) OR
             COALESCE(a.new_management_level,destination_level) IS NULL OR
             (a.target_team_id IS NOT NULL AND (COALESCE(a.new_management_level,destination_level)<>'TEAM_MANAGER' OR a.target_team_id IS DISTINCT FROM destination_team)) OR
             (a.target_department_id IS NOT NULL AND (COALESCE(a.new_management_level,destination_level)<>'DEPARTMENT_MANAGER' OR a.target_department_id IS DISTINCT FROM destination_department)) THEN
           RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Manager target must match typed destination unit and management level'; END IF;
         IF a.target_team_id IS NOT NULL THEN
           SELECT department_id INTO team_department FROM teams WHERE id=a.target_team_id FOR SHARE;
           IF team_department IS DISTINCT FROM destination_department THEN
             RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Manager target Team must match destination Department'; END IF;
         END IF;
       ELSIF a.target_department_id IS NOT NULL OR a.target_team_id IS NOT NULL THEN
         RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Unassigned manager cannot have a new target unit';
       END IF;
     END IF;
     FOR outrow IN SELECT id FROM employee_assignments WHERE personnel_action_id=a.id LOOP
       PERFORM validate_personnel_assignment_link('EMPLOYEE',outrow.id); END LOOP;
     FOR outrow IN SELECT id FROM manager_assignments WHERE personnel_action_id=a.id LOOP
       PERFORM validate_personnel_assignment_link('MANAGER',outrow.id); END LOOP;
   END LOOP;
 ELSIF w.request_type='TEMPORARY_INACTIVE' THEN
   SELECT * INTO tmp FROM temporary_inactive_requests WHERE workflow_request_id=w.id;
   IF FOUND AND submitted AND (tmp.start_date IS NULL OR tmp.end_date IS NULL OR tmp.reason IS NULL OR btrim(tmp.reason)='') THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Submitted Temporary Inactive needs reason and dates'; END IF;
 ELSIF w.request_type='RESIGNATION' THEN
   IF w.status='COMPLETED' AND EXISTS(SELECT 1 FROM resignation_requests WHERE workflow_request_id=w.id AND record_mode='V1' AND
       (reconciliation_completed_at IS NULL OR contract_basis_confirmed_by_id IS NULL)) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='V1 completed resignation needs explicit reconciliation evidence'; END IF;
 END IF;
END $$;

-- Serialize new aggregate edits with submit and deferred identity checks.
CREATE FUNCTION lifecycle_aggregate_lock() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE old_id BIGINT; new_id BIGINT; row_id BIGINT;
BEGIN
 IF TG_TABLE_NAME='personnel_change_actions' THEN
   IF TG_OP<>'INSERT' THEN SELECT workflow_request_id INTO old_id FROM personnel_change_requests WHERE id=OLD.request_id; END IF;
   IF TG_OP<>'DELETE' THEN SELECT workflow_request_id INTO new_id FROM personnel_change_requests WHERE id=NEW.request_id; END IF;
 ELSE
   IF TG_OP<>'INSERT' THEN old_id:=OLD.workflow_request_id; END IF;
   IF TG_OP<>'DELETE' THEN new_id:=NEW.workflow_request_id; END IF;
 END IF;
 FOR row_id IN SELECT id FROM workflow_requests WHERE id=old_id OR id=new_id ORDER BY id FOR NO KEY UPDATE LOOP NULL; END LOOP;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW;
END $$;
CREATE TRIGGER personnel_aggregate_lock BEFORE INSERT OR UPDATE OR DELETE ON personnel_change_requests FOR EACH ROW EXECUTE FUNCTION lifecycle_aggregate_lock();
CREATE TRIGGER personnel_action_lock BEFORE INSERT OR UPDATE OR DELETE ON personnel_change_actions FOR EACH ROW EXECUTE FUNCTION lifecycle_aggregate_lock();
CREATE TRIGGER temporary_aggregate_lock BEFORE INSERT OR UPDATE OR DELETE ON temporary_inactive_requests FOR EACH ROW EXECUTE FUNCTION lifecycle_aggregate_lock();

CREATE FUNCTION lifecycle_reference_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE ref RECORD;
BEGIN
 IF TG_TABLE_NAME='personnel_change_actions' THEN
   IF TG_OP<>'INSERT' THEN FOR ref IN SELECT workflow_request_id wid FROM personnel_change_requests WHERE id=OLD.request_id LOOP PERFORM validate_workflow_identity(ref.wid); END LOOP; END IF;
   IF TG_OP<>'DELETE' THEN FOR ref IN SELECT workflow_request_id wid FROM personnel_change_requests WHERE id=NEW.request_id LOOP PERFORM validate_workflow_identity(ref.wid); END LOOP; END IF;
 ELSIF TG_TABLE_NAME='teams' THEN
   FOR ref IN SELECT DISTINCT p.workflow_request_id wid FROM personnel_change_requests p JOIN personnel_change_actions a ON a.request_id=p.id
     WHERE NEW.id IN(a.old_team_id,a.new_team_id,a.target_team_id) LOOP PERFORM validate_workflow_identity(ref.wid); END LOOP;
 ELSE
   IF TG_TABLE_NAME='employee_assignments' THEN
     PERFORM validate_personnel_assignment_link('EMPLOYEE',NEW.id);
     FOR ref IN SELECT workflow_request_id wid FROM personnel_change_requests WHERE from_assignment_id=NEW.id LOOP PERFORM validate_workflow_identity(ref.wid); END LOOP;
   ELSE
     PERFORM validate_personnel_assignment_link('MANAGER',NEW.id);
     FOR ref IN SELECT DISTINCT p.workflow_request_id wid FROM personnel_change_requests p JOIN personnel_change_actions a ON a.request_id=p.id WHERE a.old_manager_assignment_id=NEW.id LOOP PERFORM validate_workflow_identity(ref.wid); END LOOP;
   END IF;
 END IF;
 RETURN NULL;
END $$;
