-- Attendance Scheduling foundation. Additive; no application activation or seeds.
-- V1-V13 remain immutable. All dates use [effective_from,effective_to).
-- BR-ATT-SHF/SCH/ASG/HOL/TZ: validated source relationships, no matching engine.
-- The extra typed organization_settings_id pins the approved timezone source.

CREATE TABLE shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    code varchar(50) NOT NULL,
    revision integer NOT NULL,
    shift_kind varchar(30) NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    checkin_from time NOT NULL,
    checkin_to time NOT NULL,
    checkout_from time NOT NULL,
    checkout_to time NOT NULL,
    late_grace_minutes integer NOT NULL,
    early_grace_minutes integer NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    active boolean DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_shifts PRIMARY KEY (id),
    CONSTRAINT fk_shifts_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id)
);

CREATE TABLE work_schedule_day_shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    schedule_day_id bigint NOT NULL,
    shift_id bigint NOT NULL,
    ordinal smallint NOT NULL,
    CONSTRAINT pk_work_schedule_day_shifts PRIMARY KEY (id),
    CONSTRAINT fk_work_schedule_day_shifts_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_work_schedule_day_shifts_schedule_day FOREIGN KEY (schedule_day_id) REFERENCES work_schedule_days(id),
    CONSTRAINT fk_work_schedule_day_shifts_shift FOREIGN KEY (shift_id) REFERENCES shifts(id)
);

CREATE TABLE attendance_policy_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    code varchar(50) NOT NULL,
    revision integer NOT NULL,
    missing_cutoff_days integer NOT NULL,
    effective_from date NOT NULL,
    effective_to date,
    approved_by_id bigint NOT NULL,
    approved_at timestamptz NOT NULL,
    CONSTRAINT pk_attendance_policy_versions PRIMARY KEY (id),
    CONSTRAINT fk_attendance_policy_versions_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_attendance_policy_versions_approved_by FOREIGN KEY (approved_by_id) REFERENCES user_accounts(id)
);

CREATE TABLE scheduled_shifts (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    employee_id bigint NOT NULL,
    work_date date NOT NULL,
    slot varchar(30) NOT NULL,
    revision integer NOT NULL,
    schedule_assignment_id bigint NOT NULL,
    shift_id bigint NOT NULL,
    calendar_day_id bigint,
    planned_start timestamptz NOT NULL,
    planned_end timestamptz NOT NULL,
    scheduled_minutes integer NOT NULL,
    requirement varchar(30) NOT NULL,
    reason_code varchar(60),
    supersedes_id bigint,
    snapshot jsonb NOT NULL,
    organization_settings_id bigint NOT NULL,
    CONSTRAINT pk_scheduled_shifts PRIMARY KEY (id),
    CONSTRAINT fk_scheduled_shifts_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id),
    CONSTRAINT fk_scheduled_shifts_employee FOREIGN KEY (employee_id) REFERENCES employees(id),
    CONSTRAINT fk_scheduled_shifts_schedule_assignment FOREIGN KEY (schedule_assignment_id) REFERENCES employee_schedule_assignments(id),
    CONSTRAINT fk_scheduled_shifts_shift FOREIGN KEY (shift_id) REFERENCES shifts(id),
    CONSTRAINT fk_scheduled_shifts_calendar_day FOREIGN KEY (calendar_day_id) REFERENCES work_calendar_days(id),
    CONSTRAINT fk_scheduled_shifts_supersedes FOREIGN KEY (supersedes_id) REFERENCES scheduled_shifts(id),
    CONSTRAINT fk_scheduled_shifts_settings FOREIGN KEY (organization_settings_id) REFERENCES organization_settings(id)
);

