-- Configuration writes are rare and serialized as one integrity domain. This is
-- intentionally a coarse lock, not an attendance scheduler. READ COMMITTED is
-- required so validation after a lock wait sees the winning transaction's rows.
CREATE FUNCTION attendance_scheduling_write_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE used boolean:=false; oldj jsonb; newj jsonb; root_id bigint;
BEGIN
 IF current_setting('transaction_isolation')<>'read committed' THEN
  RAISE EXCEPTION 'Attendance scheduling source writes require READ COMMITTED' USING ERRCODE='0A000';
 END IF;
 PERFORM pg_advisory_xact_lock(724113,14);
 IF TG_OP='TRUNCATE' THEN
  IF TG_TABLE_NAME IN('scheduled_shifts','attendance_policy_versions') OR
    EXISTS(SELECT 1 FROM scheduled_shifts) OR EXISTS(SELECT 1 FROM work_schedule_day_shifts) THEN
   RAISE EXCEPTION 'Cannot truncate attendance scheduling history or sources' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
 END IF;
 IF TG_OP='INSERT' THEN
  IF TG_TABLE_NAME='work_schedule_days' THEN root_id:=NEW.schedule_id;
  ELSIF TG_TABLE_NAME='work_schedule_day_shifts' THEN SELECT schedule_id INTO root_id FROM work_schedule_days WHERE id=NEW.schedule_day_id;
  END IF;
  IF root_id IS NOT NULL AND EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=root_id) THEN
   RAISE EXCEPTION 'Used weekly pattern cannot gain new days/details; create a revision' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
 END IF;
 oldj:=to_jsonb(OLD);
 IF TG_OP='UPDATE' THEN newj:=to_jsonb(NEW); END IF;
 IF TG_TABLE_NAME IN('scheduled_shifts','attendance_policy_versions') THEN used:=true;
 ELSIF TG_TABLE_NAME='shifts' THEN
  used:=EXISTS(SELECT 1 FROM work_schedule_day_shifts WHERE shift_id=OLD.id) OR EXISTS(SELECT 1 FROM scheduled_shifts WHERE shift_id=OLD.id);
 ELSIF TG_TABLE_NAME='work_schedules' THEN
  used:=EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=OLD.id);
 ELSIF TG_TABLE_NAME='work_schedule_days' THEN
  used:=EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=OLD.schedule_id);
  IF TG_OP='UPDATE' THEN used:=used OR EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=NEW.schedule_id); END IF;
 ELSIF TG_TABLE_NAME='work_schedule_day_shifts' THEN
  SELECT schedule_id INTO root_id FROM work_schedule_days WHERE id=OLD.schedule_day_id;
  used:=EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=root_id);
  IF TG_OP='UPDATE' THEN
   SELECT schedule_id INTO root_id FROM work_schedule_days WHERE id=NEW.schedule_day_id;
   used:=used OR EXISTS(SELECT 1 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE a.schedule_id=root_id);
  END IF;
 ELSIF TG_TABLE_NAME='employee_schedule_assignments' THEN used:=EXISTS(SELECT 1 FROM scheduled_shifts WHERE schedule_assignment_id=OLD.id);
 ELSIF TG_TABLE_NAME='work_calendar_days' THEN used:=EXISTS(SELECT 1 FROM scheduled_shifts WHERE calendar_day_id=OLD.id);
 ELSIF TG_TABLE_NAME='organization_settings' THEN used:=EXISTS(SELECT 1 FROM scheduled_shifts WHERE organization_settings_id=OLD.id);
 END IF;
 IF used THEN
  IF TG_OP='UPDATE' AND TG_TABLE_NAME IN('shifts','work_schedules','employee_schedule_assignments','organization_settings')
   AND (oldj->>'effective_to') IS NULL AND (newj->>'effective_to') IS NOT NULL
   AND oldj-ARRAY['effective_to','updated_at','updated_by','version']=newj-ARRAY['effective_to','updated_at','updated_by','version'] THEN
   RETURN NEW; -- deferred checks prove all referenced dates remain covered
  END IF;
  IF TG_OP<>'UPDATE' OR oldj IS DISTINCT FROM newj THEN
   RAISE EXCEPTION 'Used % is immutable; create a new revision/correction',TG_TABLE_NAME USING ERRCODE='23514';
  END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;

-- Cross-row validation is deferred to permit a V1 day and its direct details
-- to be authored atomically. It never generates occurrences or classifies logs.
CREATE FUNCTION validate_attendance_scheduling() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM pg_advisory_xact_lock(724113,14);
 IF EXISTS(
  SELECT 1 FROM work_schedule_days d LEFT JOIN work_schedule_day_shifts l ON l.schedule_day_id=d.id
  WHERE d.record_mode='V1' GROUP BY d.id,d.working_day
  HAVING (d.working_day AND count(l.id)=0) OR (NOT d.working_day AND count(l.id)>0)
 ) OR EXISTS(
  SELECT 1 FROM work_schedule_day_shifts l JOIN work_schedule_days d ON d.id=l.schedule_day_id
  JOIN work_schedules w ON w.id=d.schedule_id JOIN shifts s ON s.id=l.shift_id
  WHERE d.record_mode<>'V1' OR NOT d.working_day OR d.day_of_week='SUNDAY' OR NOT s.active OR NOT w.active
   OR NOT (daterange(w.effective_from,w.effective_to,'[)') <@ daterange(s.effective_from,s.effective_to,'[)'))
 ) THEN RAISE EXCEPTION 'Invalid verified weekly pattern or shift effectivity' USING ERRCODE='23514'; END IF;
 IF EXISTS(
  SELECT 1 FROM work_schedule_day_shifts a JOIN work_schedule_day_shifts b ON b.schedule_day_id=a.schedule_day_id AND b.id>a.id
  JOIN shifts x ON x.id=a.shift_id JOIN shifts y ON y.id=b.shift_id
  WHERE x.shift_kind=y.shift_kind OR (x.start_time<y.end_time AND y.start_time<x.end_time)
   OR (x.checkin_from<=y.checkin_to AND y.checkin_from<=x.checkin_to)
   OR (x.checkout_from<=y.checkout_to AND y.checkout_from<=x.checkout_to)
   OR (a.ordinal<b.ordinal) IS DISTINCT FROM (x.shift_kind='MORNING_SHIFT')
 ) THEN RAISE EXCEPTION 'Ambiguous same-event windows, duplicate kinds or invalid shift order' USING ERRCODE='23514'; END IF;
 IF EXISTS(
  SELECT 1 FROM scheduled_shifts o
  JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id
  JOIN work_schedules w ON w.id=a.schedule_id JOIN shifts s ON s.id=o.shift_id
  JOIN organization_settings z ON z.id=o.organization_settings_id
  WHERE a.employee_id<>o.employee_id OR NOT w.active OR NOT s.active OR s.shift_kind<>o.slot
   OR NOT (o.work_date <@ daterange(a.effective_from,a.effective_to,'[)'))
   OR NOT (o.work_date <@ daterange(w.effective_from,w.effective_to,'[)'))
   OR NOT (o.work_date <@ daterange(s.effective_from,s.effective_to,'[)'))
   OR NOT (o.work_date <@ daterange(z.effective_from,z.effective_to,'[)'))
   OR z.approved_by_id IS NULL OR z.approved_at IS NULL OR extract(isodow FROM o.work_date)=7
   OR NOT EXISTS(SELECT 1 FROM work_schedule_days d JOIN work_schedule_day_shifts l ON l.schedule_day_id=d.id
    WHERE d.schedule_id=w.id AND d.record_mode='V1' AND d.working_day AND l.shift_id=s.id
     AND d.day_of_week=(ARRAY['MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY'])[extract(isodow FROM o.work_date)::integer])
   OR o.planned_start IS DISTINCT FROM ((o.work_date+s.start_time) AT TIME ZONE z.business_timezone)
   OR o.planned_end IS DISTINCT FROM ((o.work_date+s.end_time) AT TIME ZONE z.business_timezone)
 ) THEN RAISE EXCEPTION 'Occurrence owner, slot, date, timezone or verified pattern mismatch' USING ERRCODE='23514'; END IF;
 IF EXISTS(
  SELECT 1 FROM scheduled_shifts o LEFT JOIN work_calendar_days c ON c.id=o.calendar_day_id
  WHERE o.calendar_day_id IS NOT NULL AND (c.calendar_date<>o.work_date OR c.record_mode<>'V1'
    OR c.effective_revision IS NULL OR (c.day_type IN('PUBLIC_HOLIDAY','COMPANY_DAY_OFF') AND
      (o.requirement<>'NOT_REQUIRED' OR o.reason_code IS DISTINCT FROM 'HOLIDAY'))
    OR (c.override_working_day=FALSE AND o.requirement<>'NOT_REQUIRED')
    OR (c.override_start_time IS NOT NULL OR c.override_end_time IS NOT NULL OR c.override_break_start IS NOT NULL
        OR c.override_break_end IS NOT NULL OR COALESCE(c.override_minutes,0)>0))
 ) THEN RAISE EXCEPTION 'Calendar source mismatch, partial holiday or unsupported normal time override' USING ERRCODE='23514'; END IF;
 IF EXISTS(
  SELECT 1 FROM scheduled_shifts n JOIN scheduled_shifts p ON p.id=n.supersedes_id
  WHERE n.employee_id<>p.employee_id OR n.work_date<>p.work_date OR n.slot<>p.slot OR n.revision<=p.revision
 ) THEN RAISE EXCEPTION 'Supersedes must identify an earlier revision of the same employee/date/slot' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;

CREATE FUNCTION attendance_occurrence_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE z organization_settings%ROWTYPE; s shifts%ROWTYPE; w work_schedules%ROWTYPE; c work_calendar_days%ROWTYPE; expected jsonb;
BEGIN
 -- The common BEFORE guard has already acquired the serializing source lock.
 IF NEW.supersedes_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM scheduled_shifts WHERE id=NEW.supersedes_id) THEN
  RAISE EXCEPTION 'Supersedes must already exist; forward/cyclic references are forbidden' USING ERRCODE='23514';
 END IF;
 IF EXISTS(SELECT 1 FROM work_calendar_days WHERE calendar_date=NEW.work_date AND id IS DISTINCT FROM NEW.calendar_day_id) THEN
  RAISE EXCEPTION 'Existing calendar date must be referenced explicitly and verified' USING ERRCODE='23514';
 END IF;
 SELECT * INTO z FROM organization_settings WHERE id=NEW.organization_settings_id;
 SELECT * INTO s FROM shifts WHERE id=NEW.shift_id;
 SELECT ws.* INTO w FROM work_schedules ws JOIN employee_schedule_assignments a ON a.schedule_id=ws.id WHERE a.id=NEW.schedule_assignment_id;
 IF NEW.calendar_day_id IS NOT NULL THEN SELECT * INTO c FROM work_calendar_days WHERE id=NEW.calendar_day_id; END IF;
 -- Missing FK rows are left to their real FOREIGN KEY constraints.
 IF z.id IS NULL OR s.id IS NULL OR w.id IS NULL OR (NEW.calendar_day_id IS NOT NULL AND c.id IS NULL) THEN RETURN NEW; END IF;
 expected:=jsonb_build_object('schemaVersion',1,'businessTimezone',z.business_timezone,'settingsRevision',z.revision,
  'schedule',jsonb_build_object('code',w.code,'revision',w.revision),
  'shift',jsonb_build_object('code',s.code,'revision',s.revision,'kind',s.shift_kind,
   'startTime',s.start_time,'endTime',s.end_time,'checkinFrom',s.checkin_from,'checkinTo',s.checkin_to,
   'checkoutFrom',s.checkout_from,'checkoutTo',s.checkout_to,'lateGraceMinutes',s.late_grace_minutes,'earlyGraceMinutes',s.early_grace_minutes),
  'calendar',CASE WHEN c.id IS NULL THEN 'null'::jsonb ELSE jsonb_build_object('effectiveRevision',c.effective_revision,'dayType',c.day_type,'companyPaidHoliday',c.company_paid_holiday) END);
 IF NOT (NEW.snapshot @> expected) THEN
  RAISE EXCEPTION 'Snapshot must contain actual typed source parameters (schemaVersion 1)' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;

DO $$
DECLARE t text;
BEGIN
 FOREACH t IN ARRAY ARRAY['shifts','work_schedule_day_shifts','attendance_policy_versions','scheduled_shifts',
  'work_schedules','work_schedule_days','work_calendar_days','employee_schedule_assignments','organization_settings'] LOOP
  EXECUTE format('CREATE TRIGGER a_attendance_source_write BEFORE INSERT OR UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION attendance_scheduling_write_guard()',t);
  EXECUTE format('CREATE TRIGGER a_attendance_source_truncate BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION attendance_scheduling_write_guard()',t);
  EXECUTE format('CREATE CONSTRAINT TRIGGER ct_attendance_source_integrity AFTER INSERT OR UPDATE OR DELETE ON %I DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_attendance_scheduling()',t);
 END LOOP;
END $$;
CREATE TRIGGER b_attendance_occurrence_insert BEFORE INSERT ON scheduled_shifts FOR EACH ROW EXECUTE FUNCTION attendance_occurrence_insert_guard();

COMMENT ON COLUMN scheduled_shifts.organization_settings_id IS 'Typed approved Organization Settings revision; business timezone source, never inferred from server timezone.';
COMMENT ON TABLE attendance_policy_versions IS 'Explicit approved immutable versions. No default policy, no authorization or cutoff engine. Future usage FKs belong to Attendance Period/Result migrations.';
COMMENT ON FUNCTION validate_attendance_scheduling() IS 'Deferred source integrity only; no occurrence generation, matching, lifecycle eligibility or work-credit calculation.';
