CREATE FUNCTION require_attendance_logging_rc() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 IF current_setting('transaction_isolation')<>'read committed' THEN
  RAISE EXCEPTION 'Attendance logging writes require READ COMMITTED for fresh source snapshots' USING ERRCODE='0A000';
 END IF;
END $$;
CREATE FUNCTION attendance_logging_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION '% is append-only; retain raw evidence and append a business revision',TG_TABLE_NAME USING ERRCODE='23514';
END $$;

CREATE FUNCTION attendance_device_network_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE last_use timestamptz;
BEGIN
 PERFORM require_attendance_logging_rc();
 IF TG_OP IN('DELETE','TRUNCATE') THEN
  RAISE EXCEPTION 'Device/network history cannot be deleted; revoke/deactivate explicitly' USING ERRCODE='23514';
 END IF;
 IF TG_OP='INSERT' THEN RETURN NEW; END IF;
 IF TG_TABLE_NAME='registered_devices' THEN
  IF to_jsonb(NEW)-ARRAY['status','activated_at','revoked_at','version'] IS DISTINCT FROM to_jsonb(OLD)-ARRAY['status','activated_at','revoked_at','version']
   OR OLD.status='REVOKED' AND NEW IS DISTINCT FROM OLD
   OR OLD.activated_at IS NOT NULL AND NEW.activated_at IS DISTINCT FROM OLD.activated_at
   OR OLD.status='ACTIVE' AND NEW.status NOT IN('ACTIVE','REVOKED') THEN
   RAISE EXCEPTION 'Device identity and lifecycle history are immutable; register a new device' USING ERRCODE='23514';
  END IF;
  IF NEW.revoked_at IS NOT NULL THEN
   SELECT max(greatest(event_at,recorded_at)) INTO last_use FROM attendance_logs WHERE device_id=OLD.id;
   IF last_use IS NOT NULL AND NEW.revoked_at<last_use THEN
    RAISE EXCEPTION 'Revocation cannot invalidate stored device evidence' USING ERRCODE='23514';
   END IF;
  END IF;
 ELSE
  SELECT max(greatest(event_at,recorded_at)) INTO last_use FROM attendance_logs WHERE network_id=OLD.id;
  IF last_use IS NOT NULL AND (
   to_jsonb(NEW)-ARRAY['active','effective_to','version'] IS DISTINCT FROM to_jsonb(OLD)-ARRAY['active','effective_to','version']
   OR NOT OLD.active AND NEW.active
   OR NEW.effective_to IS DISTINCT FROM OLD.effective_to AND NOT (OLD.effective_to IS NULL AND NEW.effective_to IS NOT NULL AND NEW.effective_to>last_use)
  ) THEN RAISE EXCEPTION 'Used network configuration is immutable; use a new code/revision' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_device_guard BEFORE INSERT OR UPDATE OR DELETE ON registered_devices FOR EACH ROW EXECUTE FUNCTION attendance_device_network_guard();
CREATE TRIGGER attendance_network_guard BEFORE INSERT OR UPDATE OR DELETE ON allowed_company_networks FOR EACH ROW EXECUTE FUNCTION attendance_device_network_guard();
CREATE TRIGGER attendance_device_no_truncate BEFORE TRUNCATE ON registered_devices FOR EACH STATEMENT EXECUTE FUNCTION attendance_device_network_guard();
CREATE TRIGGER attendance_network_no_truncate BEFORE TRUNCATE ON allowed_company_networks FOR EACH STATEMENT EXECUTE FUNCTION attendance_device_network_guard();

-- Structural one-step approval proof, not a permission evaluator. Caller must
-- prove real authority/session/evidence and the Phase3C Period gate separately.
CREATE FUNCTION attendance_request_has_approval(wid bigint) RETURNS boolean LANGUAGE sql VOLATILE AS $$
 SELECT EXISTS(SELECT 1 FROM approval_tasks t JOIN approval_decisions d ON d.task_id=t.id
  WHERE t.request_id=wid AND t.step_no=1 AND t.status='APPROVED' AND d.decision='APPROVE')
$$;

CREATE FUNCTION validate_attendance_workflow_payload(wid bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE w workflow_requests; d device_change_requests; m missing_attendance_requests; o scheduled_shifts;
        tz text; submitter_employee bigint; logrow attendance_logs; submitted boolean;
BEGIN
 SELECT * INTO w FROM workflow_requests WHERE id=wid FOR NO KEY UPDATE;
 IF NOT FOUND OR w.request_type NOT IN('DEVICE_CHANGE','MISSING_ATTENDANCE') THEN RETURN; END IF;
 PERFORM require_attendance_logging_rc();
 submitted:=w.status NOT IN('DRAFT','CANCELLED');
 IF submitted AND w.submitted_at IS NOT NULL AND NOT isfinite(w.submitted_at) THEN
  RAISE EXCEPTION 'Submitted attendance workflow needs a finite explicit submission time' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM approval_tasks WHERE request_id=wid AND step_no<>1) THEN
  RAISE EXCEPTION 'Attendance request approval is one-step; no hardcoded manager/HR route' USING ERRCODE='23514'; END IF;
 IF w.status IN('APPROVED','COMPLETED') AND NOT attendance_request_has_approval(wid) THEN
  RAISE EXCEPTION 'Approved attendance request needs a stored APPROVE decision and approved step' USING ERRCODE='23514'; END IF;
 IF w.request_type='DEVICE_CHANGE' THEN
  SELECT * INTO d FROM device_change_requests WHERE workflow_request_id=wid;
  IF NOT FOUND THEN RETURN; END IF;
  IF EXISTS(SELECT 1 FROM registered_devices WHERE id IN(d.old_device_id,d.new_device_id) AND employee_id<>w.target_employee_id) THEN
   RAISE EXCEPTION 'Replacement devices must belong to workflow target Employee' USING ERRCODE='23514'; END IF;
  IF submitted AND (d.new_device_id IS NULL OR d.reason IS NULL OR d.created_by_id IS NULL) THEN
   RAISE EXCEPTION 'Submitted device change needs new device, reason and creator; old device may be absent' USING ERRCODE='23514'; END IF;
 ELSE
  SELECT * INTO m FROM missing_attendance_requests WHERE workflow_request_id=wid;
  IF NOT FOUND THEN RETURN; END IF;
  IF m.scheduled_shift_id IS NOT NULL THEN
   SELECT * INTO o FROM scheduled_shifts WHERE id=m.scheduled_shift_id;
   IF o.employee_id<>w.target_employee_id THEN RAISE EXCEPTION 'Missing request and occurrence must have same Employee' USING ERRCODE='23514'; END IF;
   SELECT business_timezone INTO tz FROM organization_settings WHERE id=o.organization_settings_id;
   IF m.proposed_event_at IS NOT NULL AND (m.proposed_event_at AT TIME ZONE tz)::date<>o.work_date THEN
    RAISE EXCEPTION 'Proposed event must have occurrence work_date in its pinned business timezone' USING ERRCODE='23514'; END IF;
  END IF;
  IF submitted THEN
   IF m.scheduled_shift_id IS NULL OR m.event_type IS NULL OR m.proposed_event_at IS NULL OR m.reason IS NULL OR m.received_at IS NULL OR m.created_by_id IS NULL THEN
    RAISE EXCEPTION 'Submitted missing attendance needs shift, event, proposed instant, reason, actual receipt and creator' USING ERRCODE='23514'; END IF;
   IF m.received_at>(w.submitted_at AT TIME ZONE tz) THEN
    RAISE EXCEPTION 'Receipt must not follow submission; legacy submit time is interpreted only in pinned business timezone' USING ERRCODE='23514'; END IF;
   SELECT employee_id INTO submitter_employee FROM user_accounts WHERE id=w.submitted_by_id FOR SHARE;
   IF submitter_employee IS DISTINCT FROM w.target_employee_id AND m.evidence_asset_id IS NULL THEN
    RAISE EXCEPTION 'Proxy/HR submission needs typed evidence; no employee impersonation' USING ERRCODE='23514'; END IF;
  END IF;
  SELECT * INTO logrow FROM attendance_logs WHERE missing_request_id=m.id;
  IF m.applied_at IS NOT NULL OR logrow.id IS NOT NULL THEN
   IF w.status NOT IN('APPROVED','COMPLETED') OR NOT attendance_request_has_approval(wid) OR logrow.id IS NULL
    OR m.applied_at IS DISTINCT FROM logrow.recorded_at THEN
    RAISE EXCEPTION 'Explicit apply marker and approved request-based MANUAL evidence must agree atomically' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
END $$;

CREATE FUNCTION attendance_request_write_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE wid bigint; w workflow_requests;
BEGIN
 PERFORM require_attendance_logging_rc();
 -- Serialize the two workflow roots in ID order for moves; V6 dispatcher will
 -- validate both OLD and NEW roots at the deferred boundary.
 IF TG_OP='INSERT' THEN wid:=NEW.workflow_request_id;
 ELSE wid:=OLD.workflow_request_id; END IF;
 IF TG_OP='UPDATE' THEN
  PERFORM id FROM workflow_requests WHERE id IN(OLD.workflow_request_id,NEW.workflow_request_id) ORDER BY id FOR NO KEY UPDATE;
 ELSE PERFORM id FROM workflow_requests WHERE id=wid FOR NO KEY UPDATE; END IF;
 SELECT * INTO w FROM workflow_requests WHERE id=wid;
 IF TG_OP='UPDATE' AND TG_TABLE_NAME='missing_attendance_requests' THEN
  IF OLD.received_at IS NOT NULL AND NEW.received_at IS DISTINCT FROM OLD.received_at THEN
   RAISE EXCEPTION 'Actual receipt cannot be backdated or rewritten' USING ERRCODE='23514'; END IF;
  IF OLD.applied_at IS NOT NULL AND NEW.applied_at IS DISTINCT FROM OLD.applied_at THEN
   RAISE EXCEPTION 'Applied marker is immutable once recorded' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP<>'INSERT' AND w.submitted_at IS NOT NULL THEN
  IF TG_OP='DELETE' OR
   (TG_TABLE_NAME='device_change_requests' AND to_jsonb(NEW)-'version' IS DISTINCT FROM to_jsonb(OLD)-'version') OR
   (TG_TABLE_NAME='missing_attendance_requests' AND to_jsonb(NEW)-ARRAY['applied_at','version'] IS DISTINCT FROM to_jsonb(OLD)-ARRAY['applied_at','version']) THEN
   RAISE EXCEPTION 'Submitted attendance request source is immutable; use an audited correction' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_device_request_guard BEFORE INSERT OR UPDATE OR DELETE ON device_change_requests FOR EACH ROW EXECUTE FUNCTION attendance_request_write_guard();
CREATE TRIGGER attendance_missing_request_guard BEFORE INSERT OR UPDATE OR DELETE ON missing_attendance_requests FOR EACH ROW EXECUTE FUNCTION attendance_request_write_guard();
CREATE TRIGGER attendance_device_request_no_truncate BEFORE TRUNCATE ON device_change_requests FOR EACH STATEMENT EXECUTE FUNCTION attendance_logging_immutable();
CREATE TRIGGER attendance_missing_request_no_truncate BEFORE TRUNCATE ON missing_attendance_requests FOR EACH STATEMENT EXECUTE FUNCTION attendance_logging_immutable();

CREATE FUNCTION attendance_workflow_header_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.request_type IN('DEVICE_CHANGE','MISSING_ATTENDANCE') OR TG_OP='UPDATE' AND OLD.request_type IN('DEVICE_CHANGE','MISSING_ATTENDANCE') THEN
  PERFORM require_attendance_logging_rc();
  IF TG_OP='UPDATE' AND OLD.submitted_at IS NOT NULL AND
   ROW(NEW.request_type,NEW.target_employee_id,NEW.submitted_by_id,NEW.submitted_at,NEW.routing_snapshot)
    IS DISTINCT FROM ROW(OLD.request_type,OLD.target_employee_id,OLD.submitted_by_id,OLD.submitted_at,OLD.routing_snapshot) THEN
   RAISE EXCEPTION 'Submitted attendance workflow identity/provenance is immutable' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_workflow_provenance BEFORE INSERT OR UPDATE ON workflow_requests FOR EACH ROW EXECUTE FUNCTION attendance_workflow_header_guard();

CREATE FUNCTION attendance_approval_source_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE wid bigint; is_attendance boolean;
BEGIN
 IF TG_OP='INSERT' THEN wid:=NEW.request_id; ELSE wid:=OLD.request_id; END IF;
 -- Parent-local locks cover old-type -> new-type conversion races too. These
 -- do not serialize independent requests or log ingestion. Old six payloads
 -- retain their rules; only the two new types require the new RC/step checks.
 IF TG_OP='UPDATE' THEN PERFORM id FROM workflow_requests WHERE id IN(OLD.request_id,NEW.request_id) ORDER BY id FOR NO KEY UPDATE;
 ELSE PERFORM id FROM workflow_requests WHERE id=wid FOR NO KEY UPDATE; END IF;
 SELECT request_type IN('DEVICE_CHANGE','MISSING_ATTENDANCE') INTO is_attendance FROM workflow_requests WHERE id=wid;
 IF TG_OP='UPDATE' THEN is_attendance:=COALESCE(is_attendance,false) OR EXISTS(SELECT 1 FROM workflow_requests WHERE id=NEW.request_id AND request_type IN('DEVICE_CHANGE','MISSING_ATTENDANCE')); END IF;
 IF is_attendance THEN
  PERFORM require_attendance_logging_rc();
  IF TG_OP<>'DELETE' AND NEW.step_no<>1 THEN RAISE EXCEPTION 'Attendance approval supports one permission-based step' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_approval_task_guard BEFORE INSERT OR UPDATE OR DELETE ON approval_tasks FOR EACH ROW EXECUTE FUNCTION attendance_approval_source_guard();
CREATE FUNCTION attendance_approval_recheck() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE wid bigint;
BEGIN
 IF TG_OP<>'INSERT' THEN PERFORM validate_attendance_workflow_payload(OLD.request_id); END IF;
 IF TG_OP<>'DELETE' THEN PERFORM validate_attendance_workflow_payload(NEW.request_id); END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER attendance_approval_payload AFTER INSERT OR UPDATE OR DELETE ON approval_tasks DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION attendance_approval_recheck();

CREATE FUNCTION attendance_log_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE d registered_devices; n allowed_company_networks; a user_accounts; m missing_attendance_requests; w workflow_requests; wid bigint;
BEGIN
 PERFORM require_attendance_logging_rc();
 IF NEW.source='SELF_CHECKIN' THEN
  SELECT * INTO d FROM registered_devices WHERE id=NEW.device_id FOR SHARE;
  SELECT * INTO n FROM allowed_company_networks WHERE id=NEW.network_id FOR SHARE;
  SELECT * INTO a FROM user_accounts WHERE id=NEW.entered_by_id FOR SHARE;
  IF d.id IS NOT NULL AND (d.employee_id<>NEW.employee_id OR d.status<>'ACTIVE' OR NEW.event_at<d.activated_at OR NEW.recorded_at<d.activated_at)
   OR n.id IS NOT NULL AND (NOT n.active OR NOT (NEW.event_at <@ tstzrange(n.effective_from,n.effective_to,'[)')) OR NOT (NEW.recorded_at <@ tstzrange(n.effective_from,n.effective_to,'[)')))
   OR a.id IS NOT NULL AND (a.employee_id IS DISTINCT FROM NEW.employee_id OR a.status<>'ACTIVE') THEN
   RAISE EXCEPTION 'SELF_CHECKIN device/network/account ownership or applicability is invalid; authentication remains Backend responsibility' USING ERRCODE='23514'; END IF;
 ELSIF NEW.source='MANUAL' AND NEW.missing_request_id IS NOT NULL THEN
  SELECT workflow_request_id INTO wid FROM missing_attendance_requests WHERE id=NEW.missing_request_id;
  SELECT * INTO w FROM workflow_requests WHERE id=wid FOR NO KEY UPDATE;
  SELECT * INTO m FROM missing_attendance_requests WHERE id=NEW.missing_request_id FOR SHARE;
  IF m.id IS NOT NULL AND (w.request_type<>'MISSING_ATTENDANCE' OR w.status NOT IN('APPROVED','COMPLETED') OR NOT attendance_request_has_approval(wid)
   OR w.target_employee_id<>NEW.employee_id OR m.event_type IS DISTINCT FROM NEW.event_type OR m.proposed_event_at IS DISTINCT FROM NEW.event_at
   OR NEW.recorded_at<m.received_at OR NOT EXISTS(
    SELECT 1 FROM approval_tasks t JOIN approval_decisions x ON x.task_id=t.id
    JOIN scheduled_shifts o ON o.id=m.scheduled_shift_id JOIN organization_settings z ON z.id=o.organization_settings_id
    WHERE t.request_id=wid AND t.step_no=1 AND t.status='APPROVED' AND x.decision='APPROVE'
     AND (x.decided_at AT TIME ZONE z.business_timezone)<=NEW.recorded_at)) THEN
   RAISE EXCEPTION 'Request-based MANUAL event requires approved matching Employee/event/source and actual receipt' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_log_source BEFORE INSERT ON attendance_logs FOR EACH ROW EXECUTE FUNCTION attendance_log_insert_guard();
