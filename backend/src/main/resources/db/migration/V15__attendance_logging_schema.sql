-- Attendance logging foundation. Seven real tables; no seeds or business engine.
-- V1-V14 remain unchanged. OT Detail column/FK is intentionally deferred together.

CREATE TABLE registered_devices (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    employee_id bigint NOT NULL,
    device_key_hash varchar(100) NOT NULL,
    status varchar(20) NOT NULL,
    activated_at timestamptz,
    revoked_at timestamptz,
    CONSTRAINT pk_registered_devices PRIMARY KEY(id),
    CONSTRAINT fk_registered_devices_created_by FOREIGN KEY(created_by_id) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_registered_devices_employee FOREIGN KEY(employee_id) REFERENCES employees(id) ON DELETE RESTRICT
);

CREATE TABLE allowed_company_networks (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    code varchar(50) NOT NULL,
    network cidr NOT NULL,
    effective_from timestamptz NOT NULL,
    effective_to timestamptz,
    active boolean DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_allowed_company_networks PRIMARY KEY(id),
    CONSTRAINT fk_allowed_company_networks_created_by FOREIGN KEY(created_by_id) REFERENCES user_accounts(id) ON DELETE RESTRICT
);

CREATE TABLE device_change_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    created_by_id bigint,
    version bigint DEFAULT 0 NOT NULL,
    workflow_request_id bigint NOT NULL,
    old_device_id bigint,
    new_device_id bigint,
    reason text,
    CONSTRAINT pk_device_change_requests PRIMARY KEY(id),
    CONSTRAINT fk_device_change_requests_created_by FOREIGN KEY(created_by_id) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_device_change_requests_workflow_request FOREIGN KEY(workflow_request_id) REFERENCES workflow_requests(id) ON DELETE RESTRICT,
    CONSTRAINT fk_device_change_requests_old_device FOREIGN KEY(old_device_id) REFERENCES registered_devices(id) ON DELETE RESTRICT,
    CONSTRAINT fk_device_change_requests_new_device FOREIGN KEY(new_device_id) REFERENCES registered_devices(id) ON DELETE RESTRICT
);

