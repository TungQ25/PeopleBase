CREATE FUNCTION attendance_revision_match_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE l attendance_logs; r attendance_log_revisions; latest_id bigint; latest_revision integer; latest_voided boolean; latest_recorded timestamptz;
        max_match integer; batch attendance_log_matches; owner_id bigint;
BEGIN
 PERFORM require_attendance_logging_rc();
 -- This row is immutable, but a per-log row lock serializes its revision and
 -- matching histories. No global lock and no V14 source write is acquired.
 SELECT * INTO l FROM attendance_logs WHERE id=NEW.log_id FOR NO KEY UPDATE;
 IF NOT FOUND THEN RETURN NEW; END IF; -- real FK reports missing parent
 SELECT id,revision,is_voided,recorded_at INTO latest_id,latest_revision,latest_voided,latest_recorded FROM attendance_log_revisions WHERE log_id=l.id ORDER BY revision DESC LIMIT 1;
 IF TG_TABLE_NAME='attendance_log_revisions' THEN
  IF l.source<>'MANUAL' OR NEW.recorded_at<COALESCE(latest_recorded,l.recorded_at) OR NEW.revision<=COALESCE(latest_revision,0) THEN
   RAISE EXCEPTION 'Only MANUAL may append increasing business revisions with retained chronology' USING ERRCODE='23514'; END IF;
 ELSE
  IF NEW.log_revision_id IS NOT NULL THEN
   SELECT * INTO r FROM attendance_log_revisions WHERE id=NEW.log_revision_id;
   IF r.id IS NOT NULL AND r.log_id<>l.id THEN
    RAISE EXCEPTION 'Revision must belong to the referenced raw log' USING ERRCODE='23514'; END IF;
  END IF;
  IF NEW.log_revision_id IS DISTINCT FROM latest_id OR NEW.match_status='MATCHED' AND COALESCE(latest_voided,false) THEN
   RAISE EXCEPTION 'New matching evidence must use current non-void source; VOID may only be recorded as UNMATCHED audit' USING ERRCODE='23514'; END IF;
  IF NEW.scheduled_shift_id IS NOT NULL THEN
   SELECT employee_id INTO owner_id FROM scheduled_shifts WHERE id=NEW.scheduled_shift_id;
   IF owner_id IS NOT NULL AND owner_id<>l.employee_id THEN
    RAISE EXCEPTION 'Matching occurrence must belong to log Employee' USING ERRCODE='23514'; END IF;
  END IF;
  SELECT max(matching_revision) INTO max_match FROM attendance_log_matches WHERE log_id=l.id;
  SELECT * INTO batch FROM attendance_log_matches WHERE log_id=l.id AND matching_revision=NEW.matching_revision LIMIT 1;
  IF NEW.matching_revision<COALESCE(max_match,0) OR
    batch.id IS NOT NULL AND (batch.log_revision_id IS DISTINCT FROM NEW.log_revision_id OR batch.match_status<>NEW.match_status OR batch.matched_at IS DISTINCT FROM NEW.matched_at) OR
    NEW.matched_at<COALESCE(r.recorded_at,l.recorded_at) THEN
   RAISE EXCEPTION 'Matching batches must preserve source revision, disposition, chronology and increasing history' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_revision_source BEFORE INSERT ON attendance_log_revisions FOR EACH ROW EXECUTE FUNCTION attendance_revision_match_guard();
CREATE TRIGGER attendance_match_source BEFORE INSERT ON attendance_log_matches FOR EACH ROW EXECUTE FUNCTION attendance_revision_match_guard();
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['attendance_logs','attendance_log_revisions','attendance_log_matches'] LOOP
  EXECUTE format('CREATE TRIGGER attendance_evidence_immutable BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION attendance_logging_immutable()',t);
  EXECUTE format('CREATE TRIGGER attendance_evidence_no_truncate BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION attendance_logging_immutable()',t);
 END LOOP;
END $$;

-- Read-only version projections. These select stored revisions, never generate
-- matching, choose earliest CHECK_IN/latest CHECK_OUT or calculate Attendance.
CREATE VIEW attendance_effective_logs AS
 SELECT l.id AS log_id,l.employee_id,l.event_type,l.source,l.event_at AS original_event_at,
  r.id AS effective_revision_id,COALESCE(r.revision,0) AS business_revision,
  COALESCE(r.event_at,l.event_at) AS effective_event_at,COALESCE(r.is_voided,false) AS is_voided,
  l.recorded_at AS original_recorded_at,r.recorded_at AS correction_recorded_at
 FROM attendance_logs l LEFT JOIN LATERAL(SELECT v.* FROM attendance_log_revisions v WHERE v.log_id=l.id ORDER BY v.revision DESC LIMIT 1)r ON true;
CREATE VIEW attendance_current_log_matches AS
 SELECT m.* FROM attendance_log_matches m JOIN attendance_effective_logs e ON e.log_id=m.log_id
 WHERE NOT e.is_voided AND m.log_revision_id IS NOT DISTINCT FROM e.effective_revision_id
  AND m.matching_revision=(SELECT max(h.matching_revision) FROM attendance_log_matches h WHERE h.log_id=m.log_id);

COMMENT ON VIEW attendance_effective_logs IS 'Stored latest MANUAL revision, including VOID flag; not effective CHECK_IN/CHECK_OUT selection or a Period gate. Consumers must exclude is_voided.';
COMMENT ON VIEW attendance_current_log_matches IS 'Latest stored matching batch for current non-void raw/revision source. No matching algorithm, OT credit or finalized Attendance Result.';
COMMENT ON TABLE attendance_logs IS 'Immutable raw evidence. FK/shape checks never prove session authentication, device proof, trusted client IP, permission or actual receipt time.';
COMMENT ON COLUMN missing_attendance_requests.applied_at IS 'Explicit marker only; no approval auto-apply. PHASE_3C_DEPENDENCY: actual Period FINALIZED/REOPENED gate is required before writer activation.';

CREATE OR REPLACE FUNCTION validate_workflow_identity(request_id BIGINT) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE w workflow_requests; subtype_count INTEGER; legacy BOOLEAN; l leave_requests;
BEGIN
 SELECT * INTO w FROM workflow_requests WHERE id=request_id FOR NO KEY UPDATE;
 IF NOT FOUND THEN RETURN; END IF;
 SELECT (SELECT count(*) FROM leave_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM transfer_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM appointment_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM resignation_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM personnel_change_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM temporary_inactive_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM device_change_requests WHERE workflow_request_id=w.id)
      + (SELECT count(*) FROM missing_attendance_requests WHERE workflow_request_id=w.id) INTO subtype_count;
 IF subtype_count<>1 OR
   (w.request_type='LEAVE' AND NOT EXISTS(SELECT 1 FROM leave_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='TRANSFER' AND NOT EXISTS(SELECT 1 FROM transfer_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='APPOINTMENT' AND NOT EXISTS(SELECT 1 FROM appointment_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='RESIGNATION' AND NOT EXISTS(SELECT 1 FROM resignation_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='PERSONNEL_CHANGE' AND NOT EXISTS(SELECT 1 FROM personnel_change_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='TEMPORARY_INACTIVE' AND NOT EXISTS(SELECT 1 FROM temporary_inactive_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='DEVICE_CHANGE' AND NOT EXISTS(SELECT 1 FROM device_change_requests WHERE workflow_request_id=w.id)) OR
   (w.request_type='MISSING_ATTENDANCE' AND NOT EXISTS(SELECT 1 FROM missing_attendance_requests WHERE workflow_request_id=w.id))
 THEN RAISE EXCEPTION 'Workflow % requires exactly one matching subtype',w.id; END IF;
 SELECT * INTO l FROM leave_requests WHERE workflow_request_id=w.id;
 legacy := FOUND AND l.legacy_status IS NOT NULL;
 IF w.status NOT IN ('DRAFT','CANCELLED') AND NOT legacy AND
   (w.submitted_by_id IS NULL OR w.submitted_at IS NULL OR w.routing_snapshot IS NULL)
 THEN RAISE EXCEPTION 'Submitted workflow needs account, time and routing snapshot'; END IF;
 IF w.request_type='LEAVE' AND w.status NOT IN ('DRAFT','CANCELLED') AND NOT legacy AND
   (l.start_date IS NULL OR l.end_date IS NULL OR l.leave_type_id IS NULL OR l.reason IS NULL OR l.total_units IS NULL OR l.policy_snapshot IS NULL)
 THEN RAISE EXCEPTION 'Submitted leave is incomplete'; END IF;
 IF EXISTS(SELECT 1 FROM transfer_requests t LEFT JOIN employee_assignments a ON a.id=t.from_assignment_id
    WHERE t.workflow_request_id=w.id AND ((a.employee_id IS NOT NULL AND a.employee_id<>w.target_employee_id)
    OR (w.status NOT IN ('DRAFT','CANCELLED') AND (t.from_assignment_id IS NULL OR t.to_department_id IS NULL OR t.to_position_id IS NULL OR t.proposed_effective_date IS NULL OR t.reason IS NULL))))
 THEN RAISE EXCEPTION 'Invalid transfer source or submitted fields'; END IF;
 IF EXISTS(SELECT 1 FROM appointment_requests t LEFT JOIN employee_assignments a ON a.id=t.from_assignment_id
    WHERE t.workflow_request_id=w.id AND ((a.employee_id IS NOT NULL AND a.employee_id<>w.target_employee_id)
    OR (w.status NOT IN ('DRAFT','CANCELLED') AND (t.from_assignment_id IS NULL OR t.to_department_id IS NULL OR t.to_position_id IS NULL OR t.proposed_effective_date IS NULL OR t.reason IS NULL))))
 THEN RAISE EXCEPTION 'Invalid appointment source or submitted fields'; END IF;
 IF EXISTS(SELECT 1 FROM resignation_requests r WHERE r.workflow_request_id=w.id AND
    ((w.status NOT IN ('DRAFT','CANCELLED') AND (r.proposed_last_working_date IS NULL OR r.reason IS NULL)) OR
     (w.status IN ('APPROVED','COMPLETED') AND (r.approved_last_working_date IS NULL OR r.effective_date IS NULL))))
 THEN RAISE EXCEPTION 'Resignation dates and reason required by state'; END IF;
 PERFORM validate_lifecycle_payload(w.id);
 PERFORM validate_attendance_workflow_payload(w.id);
END $$;
