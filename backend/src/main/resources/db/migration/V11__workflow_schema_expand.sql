CREATE FUNCTION workflow_decision_grant_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE source_actor BIGINT;
BEGIN
    IF NEW.effective_role_grant_id IS NOT NULL THEN
        SELECT account_id INTO source_actor FROM v1_account_roles WHERE id=NEW.effective_role_grant_id FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Decision grant does not exist'; END IF;
        IF source_actor IS DISTINCT FROM NEW.actor_id THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Decision grant must belong to its actor';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER decision_grant_owner BEFORE INSERT ON approval_decisions
    FOR EACH ROW EXECUTE FUNCTION workflow_decision_grant_guard();
CREATE FUNCTION workflow_grant_source_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM approval_decisions WHERE effective_role_grant_id=NEW.id AND actor_id IS DISTINCT FROM NEW.account_id) THEN
        RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Decision evidence prevents grant account reassignment';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER decision_grant_source AFTER UPDATE OF account_id ON v1_account_roles
    FOR EACH ROW EXECUTE FUNCTION workflow_grant_source_guard();

CREATE FUNCTION validate_workflow_issue_sources(req BIGINT,contract_value BIGINT,leave_value BIGINT)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE owner_id BIGINT; source_owner BIGINT; leave_workflow BIGINT;
BEGIN
    SELECT target_employee_id INTO owner_id FROM workflow_requests WHERE id=req FOR SHARE;
    IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Issue request does not exist'; END IF;
    IF contract_value IS NOT NULL THEN
        SELECT employee_id INTO source_owner FROM contracts WHERE id=contract_value FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Issue contract source does not exist'; END IF;
        IF source_owner IS DISTINCT FROM owner_id THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Issue contract must belong to request employee';
        END IF;
    END IF;
    IF leave_value IS NOT NULL THEN
        SELECT workflow_request_id INTO leave_workflow FROM leave_requests WHERE id=leave_value FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Issue leave source does not exist'; END IF;
        SELECT target_employee_id INTO source_owner FROM workflow_requests WHERE id=leave_workflow FOR SHARE;
        IF source_owner IS DISTINCT FROM owner_id THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Issue leave must belong to request employee';
        END IF;
    END IF;
END $$;
CREATE FUNCTION workflow_issue_source_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE issue workflow_issues;
BEGIN
    IF TG_TABLE_NAME='workflow_issues' THEN
        PERFORM validate_workflow_issue_sources(NEW.request_id,NEW.contract_id,NEW.leave_request_id);
    ELSIF TG_TABLE_NAME='workflow_requests' THEN
        FOR issue IN SELECT wi.* FROM workflow_issues wi
            WHERE wi.request_id=NEW.id OR wi.leave_request_id IN
                (SELECT id FROM leave_requests WHERE workflow_request_id=NEW.id)
        LOOP PERFORM validate_workflow_issue_sources(issue.request_id,issue.contract_id,issue.leave_request_id); END LOOP;
    ELSIF TG_TABLE_NAME='contracts' THEN
        FOR issue IN SELECT * FROM workflow_issues WHERE contract_id=NEW.id
        LOOP PERFORM validate_workflow_issue_sources(issue.request_id,issue.contract_id,issue.leave_request_id); END LOOP;
    ELSE
        FOR issue IN SELECT * FROM workflow_issues WHERE leave_request_id=NEW.id
        LOOP PERFORM validate_workflow_issue_sources(issue.request_id,issue.contract_id,issue.leave_request_id); END LOOP;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER workflow_issue_sources BEFORE INSERT OR UPDATE ON workflow_issues
    FOR EACH ROW EXECUTE FUNCTION workflow_issue_source_guard();
