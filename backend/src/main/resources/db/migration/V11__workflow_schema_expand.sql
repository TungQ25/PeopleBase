    FOR EACH ROW EXECUTE FUNCTION workflow_issue_source_guard();
CREATE TRIGGER issue_leave_owner AFTER UPDATE OF workflow_request_id ON leave_requests
    FOR EACH ROW EXECUTE FUNCTION workflow_issue_source_guard();

