-- Structural provenance only. A normal FK proves existence, not source ownership.
-- Source SHARE locks prevent concurrent reassignment from invalidating a new link.
-- No permission, scope, SYSTEM_OWNER, protected-role or authentication evaluation here.
CREATE FUNCTION authorization_mapping_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE source_owner BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'v1_account_roles' THEN
        IF NEW.legacy_account_role_id IS NOT NULL THEN
            SELECT account_id INTO source_owner FROM account_roles WHERE id=NEW.legacy_account_role_id FOR SHARE;
            IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Legacy grant source does not exist'; END IF;
            IF source_owner IS DISTINCT FROM NEW.account_id THEN
                RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Legacy grant source must belong to the same account';
            END IF;
        END IF;
    ELSE
        IF NEW.legacy_role_permission_id IS NOT NULL THEN
            SELECT permission_id INTO source_owner FROM role_permissions WHERE id=NEW.legacy_role_permission_id FOR SHARE;
            IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Legacy role permission source does not exist'; END IF;
            IF source_owner IS DISTINCT FROM NEW.permission_id THEN
                RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Legacy role permission source must reference the same permission';
            END IF;
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER v1_grant_mapping_guard BEFORE INSERT OR UPDATE ON v1_account_roles
    FOR EACH ROW EXECUTE FUNCTION authorization_mapping_guard();
CREATE TRIGGER v1_permission_mapping_guard BEFORE INSERT OR UPDATE ON v1_role_permissions
    FOR EACH ROW EXECUTE FUNCTION authorization_mapping_guard();

CREATE FUNCTION authorization_source_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME='account_roles' THEN
        IF EXISTS (SELECT 1 FROM v1_account_roles WHERE legacy_account_role_id=NEW.id AND account_id IS DISTINCT FROM NEW.account_id) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Referenced legacy grant cannot change account ownership';
        END IF;
    ELSE
        IF EXISTS (SELECT 1 FROM v1_role_permissions WHERE legacy_role_permission_id=NEW.id AND permission_id IS DISTINCT FROM NEW.permission_id) THEN
            RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Referenced legacy role permission cannot change permission identity';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER legacy_grant_source_guard AFTER UPDATE OF account_id ON account_roles
    FOR EACH ROW EXECUTE FUNCTION authorization_source_guard();
CREATE TRIGGER legacy_permission_source_guard AFTER UPDATE OF permission_id ON role_permissions
    FOR EACH ROW EXECUTE FUNCTION authorization_source_guard();

