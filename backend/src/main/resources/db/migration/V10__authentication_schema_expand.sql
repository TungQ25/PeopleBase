-- Atomic expand + integrity: all referenced baseline tables already exist.
-- No seeds, credential/status/token_version changes, authority UNION or V1 cutover.

ALTER TABLE user_accounts
    ADD COLUMN account_type VARCHAR(30),
    ADD COLUMN activated_at TIMESTAMPTZ,
    ADD COLUMN disabled_reason TEXT,
    ADD COLUMN disabled_by_id BIGINT,
    ADD COLUMN record_mode VARCHAR(40) NOT NULL DEFAULT 'LEGACY',
    ADD COLUMN authorization_model VARCHAR(16) NOT NULL DEFAULT 'LEGACY',
    ADD CONSTRAINT fk_user_accounts_disabled_by FOREIGN KEY (disabled_by_id)
        REFERENCES user_accounts(id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_user_accounts_type CHECK (account_type IS NULL OR account_type IN ('SYSTEM_OWNER','MEMBER')),
    ADD CONSTRAINT ck_user_accounts_member CHECK (account_type IS DISTINCT FROM 'MEMBER' OR employee_id IS NOT NULL),
    ADD CONSTRAINT ck_user_accounts_reason CHECK (disabled_reason IS NULL OR btrim(disabled_reason) <> ''),
    ADD CONSTRAINT ck_user_accounts_record_hold CHECK (record_mode = 'LEGACY'),
    ADD CONSTRAINT ck_user_accounts_authority_hold CHECK (authorization_model = 'LEGACY');
CREATE INDEX idx_user_accounts_disabled_by ON user_accounts(disabled_by_id) WHERE disabled_by_id IS NOT NULL;

CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    default_scope VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    system_protected BOOLEAN NOT NULL,
    CONSTRAINT uk_roles_code UNIQUE (code),
    CONSTRAINT fk_roles_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_roles_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_roles_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_roles_scope CHECK (default_scope IN ('SELF','TEAM','DEPARTMENT','ORGANIZATION')),
    CONSTRAINT ck_roles_version CHECK (version >= 0)
);
CREATE INDEX idx_roles_created_by ON roles(created_by_id);

