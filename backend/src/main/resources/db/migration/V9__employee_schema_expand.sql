CREATE TABLE employee_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(150) NOT NULL,
    auto_create_account BOOLEAN NOT NULL,
    active BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_employee_types_code UNIQUE (code),
    CONSTRAINT fk_employee_types_created_by FOREIGN KEY (created_by_id)
        REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT ck_employee_types_code CHECK (btrim(code) <> ''),
    CONSTRAINT ck_employee_types_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_employee_types_version CHECK (version >= 0)
);
CREATE INDEX idx_employee_types_created_by ON employee_types(created_by_id);

