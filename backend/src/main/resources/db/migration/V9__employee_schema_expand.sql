    effective_from DATE NOT NULL,
    effective_to DATE,
    source_request_id BIGINT,
    onboarding_case_id BIGINT,
    reason TEXT NOT NULL,
    provenance VARCHAR(40) NOT NULL,
    source_kind VARCHAR(32) NOT NULL,
    actor_id BIGINT,
    evidence_asset_id BIGINT,
    CONSTRAINT fk_emp_status_created_by FOREIGN KEY (created_by_id) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emp_status_employee FOREIGN KEY (employee_id) REFERENCES employees(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emp_status_request FOREIGN KEY (source_request_id) REFERENCES workflow_requests(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emp_status_onboarding FOREIGN KEY (onboarding_case_id) REFERENCES lifecycle_cases(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emp_status_actor FOREIGN KEY (actor_id) REFERENCES user_accounts(id) ON DELETE RESTRICT,
    CONSTRAINT fk_emp_status_evidence FOREIGN KEY (evidence_asset_id) REFERENCES document_assets(id) ON DELETE RESTRICT,
    CONSTRAINT ck_emp_status_dates CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT ck_emp_status_version CHECK (version >= 0),
    CONSTRAINT ck_emp_status_reason CHECK (btrim(reason) <> ''),
    CONSTRAINT ck_emp_status_provenance CHECK (btrim(provenance) <> ''),
    CONSTRAINT ck_emp_status_kind CHECK
        (source_kind IN ('LEGACY_OBSERVATION','ONBOARDING','WORKFLOW','AUTHORIZED_MANUAL')),
    CONSTRAINT ck_emp_status_value CHECK
        (status IN ('PENDING_ONBOARDING','ACTIVE','TEMPORARILY_INACTIVE','RESIGNED')
         OR (status = 'INACTIVE' AND source_kind = 'LEGACY_OBSERVATION')),
    CONSTRAINT ck_emp_status_source_shape CHECK (
        (source_kind = 'LEGACY_OBSERVATION' AND source_request_id IS NULL AND onboarding_case_id IS NULL)
        OR (source_kind = 'ONBOARDING' AND onboarding_case_id IS NOT NULL AND source_request_id IS NULL)
        OR (source_kind = 'WORKFLOW' AND source_request_id IS NOT NULL AND onboarding_case_id IS NULL)
        OR (source_kind = 'AUTHORIZED_MANUAL' AND actor_id IS NOT NULL AND source_request_id IS NULL AND onboarding_case_id IS NULL)
    ),
    CONSTRAINT ex_emp_status_dates EXCLUDE USING gist
        (employee_id WITH =, daterange(effective_from,effective_to,'[)') WITH &&)
);
