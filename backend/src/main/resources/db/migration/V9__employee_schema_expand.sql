-- A simple FK proves existence, not matching employee/type. Lock the source parent
-- through commit so a concurrent owner change cannot invalidate a committed child.
-- Does not approve a workflow, prove an actor's permission, or change Employee.status.
CREATE FUNCTION phase1b_status_source_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE owner_id BIGINT; kind VARCHAR(40);
BEGIN
    IF NEW.source_kind = 'ONBOARDING' AND NEW.onboarding_case_id IS NOT NULL THEN
        SELECT employee_id, case_type INTO owner_id,kind FROM lifecycle_cases
            WHERE id = NEW.onboarding_case_id FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'Status source onboarding case does not exist';
        END IF;
        IF owner_id IS DISTINCT FROM NEW.employee_id OR kind <> 'ONBOARDING' THEN
            RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Status source must be an onboarding case for the same employee';
        END IF;
    ELSIF NEW.source_kind = 'WORKFLOW' AND NEW.source_request_id IS NOT NULL THEN
        SELECT target_employee_id INTO owner_id FROM workflow_requests
            WHERE id = NEW.source_request_id FOR SHARE;
        IF NOT FOUND THEN
            RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'Status source workflow does not exist';
        END IF;
        IF owner_id IS DISTINCT FROM NEW.employee_id THEN
            RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Status source workflow must target the same employee';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER phase1b_status_source_guard BEFORE INSERT OR UPDATE ON employee_status_periods
    FOR EACH ROW EXECUTE FUNCTION phase1b_status_source_guard();

CREATE FUNCTION phase1b_status_parent_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'workflow_requests' THEN
        IF EXISTS (SELECT 1 FROM employee_status_periods
            WHERE source_request_id = NEW.id AND employee_id IS DISTINCT FROM NEW.target_employee_id) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Referenced status workflow cannot change employee ownership';
        END IF;
    ELSE
        IF EXISTS (SELECT 1 FROM employee_status_periods
            WHERE onboarding_case_id = NEW.id
              AND (employee_id IS DISTINCT FROM NEW.employee_id OR NEW.case_type <> 'ONBOARDING')) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Referenced status onboarding case cannot change employee or type';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER phase1b_status_workflow_parent_guard AFTER UPDATE OF target_employee_id ON workflow_requests
    FOR EACH ROW EXECUTE FUNCTION phase1b_status_parent_guard();
CREATE TRIGGER phase1b_status_case_parent_guard AFTER UPDATE OF employee_id,case_type ON lifecycle_cases
    FOR EACH ROW EXECUTE FUNCTION phase1b_status_parent_guard();

