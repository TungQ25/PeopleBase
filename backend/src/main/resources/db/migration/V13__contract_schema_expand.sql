) WHERE(record_mode='V1' AND status IN('PENDING_EFFECTIVE','ACTIVE','EXPIRED','TERMINATED'));

CREATE FUNCTION contract_write_lock() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE old_owner BIGINT; new_owner BIGINT; locked_id BIGINT;
BEGIN
 -- Cross-mode guards need a fresh snapshot AFTER waiting for the Employee lock.
 -- Reject fixed-snapshot writes rather than claim an unsafe cross-mode guarantee.
 IF current_setting('transaction_isolation')<>'read committed' THEN
   RAISE EXCEPTION USING ERRCODE='0A000',MESSAGE='Contract writes require READ COMMITTED; fixed-snapshot writers need separate cutover review'; END IF;
 IF TG_OP<>'INSERT' THEN old_owner:=OLD.employee_id; END IF;
 IF TG_OP<>'DELETE' THEN new_owner:=NEW.employee_id; END IF;
 FOR locked_id IN SELECT id FROM employees WHERE id=old_owner OR id=new_owner ORDER BY id FOR NO KEY UPDATE LOOP NULL; END LOOP;
 IF TG_OP='DELETE' THEN
   IF OLD.record_mode='V1' AND OLD.status<>'DRAFT' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='V1 contract history cannot be deleted'; END IF;
   RETURN OLD;
 END IF;
 IF TG_OP='UPDATE' AND OLD.record_mode='V1' THEN
   IF NEW.record_mode<>'V1' THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='V1 evidence cannot be downgraded to LEGACY'; END IF;
   IF OLD.status<>'DRAFT' AND ROW(NEW.contract_number,NEW.employee_id,NEW.type,NEW.start_date,NEW.end_date,NEW.basic_salary,NEW.previous_contract_id,NEW.signed_date,NEW.note)
      IS DISTINCT FROM ROW(OLD.contract_number,OLD.employee_id,OLD.type,OLD.start_date,OLD.end_date,OLD.basic_salary,OLD.previous_contract_id,OLD.signed_date,OLD.note) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Finalized V1 business payload is immutable; Return-to-Draft history is HOLD'; END IF;
   IF OLD.status='PENDING_EFFECTIVE' AND NEW.status='DRAFT' THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Return-to-Draft requires separately reviewed immutable version/audit writer'; END IF;
   IF OLD.status IN('TERMINATED','CANCELLED','EXPIRED') AND NEW.status<>OLD.status THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Terminal V1 contract cannot be reactivated'; END IF;
   IF NEW.status='CANCELLED' AND OLD.status NOT IN('DRAFT','PENDING_EFFECTIVE','CANCELLED') THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Effective V1 contract cannot be cancelled'; END IF;
   IF OLD.finalized_at IS NOT NULL AND ROW(NEW.finalized_by_id,NEW.finalized_at) IS DISTINCT FROM ROW(OLD.finalized_by_id,OLD.finalized_at) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Finalize evidence is immutable'; END IF;
   IF OLD.status='TERMINATED' AND ROW(NEW.terminated_effective_date,NEW.termination_reason,NEW.terminated_by_id,NEW.terminated_at,NEW.termination_asset_id)
       IS DISTINCT FROM ROW(OLD.terminated_effective_date,OLD.termination_reason,OLD.terminated_by_id,OLD.terminated_at,OLD.termination_asset_id) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Termination evidence is immutable'; END IF;
   IF OLD.status='CANCELLED' AND ROW(NEW.cancelled_by_id,NEW.cancelled_at,NEW.cancellation_reason) IS DISTINCT FROM ROW(OLD.cancelled_by_id,OLD.cancelled_at,OLD.cancellation_reason) THEN
     RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Cancellation evidence is immutable'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER contract_write_lock BEFORE INSERT OR UPDATE OR DELETE ON contracts FOR EACH ROW EXECUTE FUNCTION contract_write_lock();

CREATE FUNCTION contract_integrity_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE ancestor BIGINT; prior contracts; visited BIGINT[]; other contracts; span DATERANGE; other_span DATERANGE;
BEGIN
 IF NEW.previous_contract_id IS NOT NULL THEN
   ancestor:=NEW.previous_contract_id; visited:=ARRAY[NEW.id];
   WHILE ancestor IS NOT NULL LOOP
     IF ancestor=ANY(visited) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Contract renewal cycle/self reference'; END IF;
     visited:=array_append(visited,ancestor);
     SELECT * INTO prior FROM contracts WHERE id=ancestor FOR SHARE;
     IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Previous Contract does not exist'; END IF;
     IF prior.employee_id<>NEW.employee_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Renewal must belong to same Employee'; END IF;
     ancestor:=prior.previous_contract_id;
   END LOOP;
 END IF;
 IF EXISTS(SELECT 1 FROM contracts WHERE previous_contract_id=NEW.id AND employee_id<>NEW.employee_id) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Referenced renewal source cannot change Employee'; END IF;
 IF TG_OP='UPDATE' AND NEW.employee_id<>OLD.employee_id AND EXISTS(SELECT 1 FROM contract_documents WHERE contract_id=NEW.id) THEN
   RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Document evidence pins Contract Employee ownership'; END IF;
 IF NEW.status IN('DRAFT','CANCELLED') THEN RETURN NULL; END IF;
 -- LEGACY/LEGACY is deliberately not retroactively constrained. Any pair involving
 -- a V1 finalized record is protected in BOTH write directions; unknown ranges BLOCK.
 FOR other IN SELECT * FROM contracts WHERE employee_id=NEW.employee_id AND id<>NEW.id AND status NOT IN('DRAFT','CANCELLED')
     AND (NEW.record_mode='V1' OR record_mode='V1') LOOP
   span:=contract_effective_span(NEW.type,NEW.status,NEW.start_date,NEW.end_date,NEW.terminated_effective_date,NEW.terminated_by_id,NEW.terminated_at,NEW.termination_reason);
   other_span:=contract_effective_span(other.type,other.status,other.start_date,other.end_date,other.terminated_effective_date,other.terminated_by_id,other.terminated_at,other.termination_reason);
   IF span IS NULL OR other_span IS NULL THEN RAISE EXCEPTION USING ERRCODE='23P01',MESSAGE='Unclassified LEGACY/V1 range needs evidence review before overlap clearance'; END IF;
   IF span && other_span THEN RAISE EXCEPTION USING ERRCODE='23P01',MESSAGE='Primary Contract overlap involving V1 record'; END IF;
 END LOOP;
 RETURN NULL;
END $$;
CREATE TRIGGER contract_integrity AFTER INSERT OR UPDATE ON contracts FOR EACH ROW EXECUTE FUNCTION contract_integrity_guard();

CREATE FUNCTION contract_document_guard() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE old_contract BIGINT; ancestor BIGINT; visited BIGINT[];
BEGIN
 PERFORM 1 FROM contracts WHERE id=NEW.contract_id FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Document Contract does not exist'; END IF;
 ancestor:=NEW.supersedes_id; visited:=ARRAY[NEW.id];
 WHILE ancestor IS NOT NULL LOOP
   IF ancestor=ANY(visited) THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Document replacement cycle/self reference'; END IF;
   visited:=array_append(visited,ancestor);
   SELECT contract_id,supersedes_id INTO old_contract,ancestor FROM contract_documents WHERE id=ancestor FOR SHARE;
   IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE='23503',MESSAGE='Replacement source must already exist; no forward references'; END IF;
   IF old_contract<>NEW.contract_id THEN RAISE EXCEPTION USING ERRCODE='23514',MESSAGE='Replacement source must belong to same Contract'; END IF;
 END LOOP;
 RETURN NEW;
END $$;
CREATE TRIGGER contract_document_sources BEFORE INSERT ON contract_documents FOR EACH ROW EXECUTE FUNCTION contract_document_guard();
