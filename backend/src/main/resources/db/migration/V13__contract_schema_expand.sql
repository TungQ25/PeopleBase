DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM contracts c JOIN contracts p ON p.id=c.previous_contract_id WHERE c.employee_id<>p.employee_id) OR
 EXISTS(WITH RECURSIVE chain(root,id,next_id,path,cycle) AS (
   SELECT id,id,previous_contract_id,ARRAY[id],false FROM contracts
   UNION ALL SELECT c.root,p.id,p.previous_contract_id,c.path||p.id,p.id=ANY(c.path)
   FROM chain c JOIN contracts p ON p.id=c.next_id WHERE NOT c.cycle
 ) SELECT 1 FROM chain WHERE cycle) THEN RAISE EXCEPTION 'Existing renewal chains require review; no data repaired'; END IF;
END $$;
