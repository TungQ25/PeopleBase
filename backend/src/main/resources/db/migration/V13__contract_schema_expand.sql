-- NULL denotes an unclassifiable legacy range; never silently treat it as safe.
-- The three Survey04 types are primary. INDEFINITE is the Java legacy spelling,
-- recognized only for evaluating existing ranges, never rewritten in storage.
CREATE FUNCTION contract_effective_span(kind TEXT,state TEXT,starts DATE,ends DATE,termination DATE,
 actor BIGINT,confirmed_at TIMESTAMPTZ,reason TEXT) RETURNS DATERANGE LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE effective_end DATE;
BEGIN
 IF kind NOT IN('PROBATION','FIXED_TERM','INDEFINITE','INDEFINITE_TERM') OR
    state NOT IN('PENDING_EFFECTIVE','ACTIVE','EXPIRED','TERMINATED') OR NOT isfinite(starts) THEN RETURN NULL; END IF;
 IF kind IN('PROBATION','FIXED_TERM') AND (ends IS NULL OR NOT isfinite(ends) OR ends<starts) THEN RETURN NULL; END IF;
 IF kind IN('INDEFINITE','INDEFINITE_TERM') AND ends IS NOT NULL THEN RETURN NULL; END IF;
 effective_end:=ends;
 IF state='TERMINATED' AND actor IS NOT NULL AND confirmed_at IS NOT NULL AND NULLIF(btrim(reason),'') IS NOT NULL AND
     termination IS NOT NULL AND isfinite(termination) AND termination>=starts AND (ends IS NULL OR termination<=ends) THEN
   effective_end:=termination;
 END IF;
 RETURN daterange(starts,effective_end,'[]');
END $$;
