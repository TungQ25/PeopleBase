CREATE FUNCTION leave_ledger_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE e leave_entitlements;src leave_balance_transactions;r leave_year_reservations;d leave_request_days;q leave_requests;w workflow_requests;
        a leave_accrual_runs;extended_source boolean;v numeric[];x numeric;delta numeric;zone text;
BEGIN
 PERFORM leave_require_rc();
 IF NEW.leave_day_id IS NOT NULL THEN
  SELECT * INTO d FROM leave_request_days WHERE id=NEW.leave_day_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Ledger Day must already be visible' USING ERRCODE='23503'; END IF;
  IF NEW.request_id IS DISTINCT FROM d.request_id THEN RAISE EXCEPTION 'Ledger Day must belong to declared real Request' USING ERRCODE='23514'; END IF;
 END IF;
 PERFORM leave_lock_request(NEW.request_id);
 IF NEW.year_reservation_id IS NOT NULL THEN
  SELECT * INTO r FROM leave_year_reservations WHERE id=NEW.year_reservation_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Ledger reservation must already be visible' USING ERRCODE='23503'; END IF;
  PERFORM leave_lock_entitlements(ARRAY[r.source_entitlement_id,r.destination_entitlement_id]);
  PERFORM id FROM leave_year_reservations WHERE id=r.id FOR NO KEY UPDATE;
 ELSE PERFORM leave_lock_entitlements(ARRAY[NEW.entitlement_id]);END IF;
 SELECT * INTO e FROM leave_entitlements WHERE id=NEW.entitlement_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Ledger needs real visible Entitlement' USING ERRCODE='23503'; END IF;
 extended_source:=NEW.record_mode='V1' OR num_nonnulls(NEW.leave_day_id,NEW.accrual_run_id,NEW.reversal_of_id,NEW.year_reservation_id)>0;
 FOREACH x IN ARRAY ARRAY[NEW.entitled_delta,NEW.carried_delta,NEW.adjusted_delta,NEW.used_delta,NEW.reserved_delta,NEW.prior_reserve_delta] LOOP
  IF x='NaN'::numeric THEN RAISE EXCEPTION 'Ledger amounts must be finite numbers' USING ERRCODE='23514'; END IF;
 END LOOP;
 IF NEW.prior_reserve_delta IS NOT NULL AND NEW.prior_reserve_delta<>0 AND (e.prior_year_reserved_units IS NULL OR NEW.year_reservation_id IS NULL) THEN
  RAISE EXCEPTION 'Prior reserve requires known opening state and actual Year Reservation FK; unknown legacy opening stays HOLD' USING ERRCODE='23514'; END IF;
 IF e.record_mode='V1' AND NEW.record_mode<>'V1' THEN RAISE EXCEPTION 'Legacy writer cannot bypass V1 fund source checks' USING ERRCODE='23514'; END IF;
 IF NEW.record_mode='V1' AND e.record_mode<>'V1' THEN RAISE EXCEPTION 'No implicit legacy fund conversion' USING ERRCODE='23514'; END IF;
 IF extended_source AND (NEW.actor_id IS NULL OR btrim(NEW.reason)='' OR btrim(NEW.idempotency_key)='' OR NOT isfinite(NEW.effective_date)) THEN
  RAISE EXCEPTION 'New typed operations need actual actor/reason/date/idempotency audit' USING ERRCODE='23514'; END IF;
 IF NEW.request_id IS NOT NULL THEN
  SELECT * INTO q FROM leave_requests WHERE id=NEW.request_id;SELECT * INTO w FROM workflow_requests WHERE id=q.workflow_request_id;
  IF extended_source AND (w.target_employee_id<>e.employee_id OR q.leave_type_id IS DISTINCT FROM e.leave_type_id) THEN
   RAISE EXCEPTION 'Ledger request source has different Employee/Leave Type' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.transaction_type='REVERSE' THEN
  IF NEW.reversal_of_id IS NULL THEN RAISE EXCEPTION 'REVERSAL_SOURCE_HOLD: every new reversal needs its actual parent FK' USING ERRCODE='0A000'; END IF;
  SELECT * INTO src FROM leave_balance_transactions WHERE id=NEW.reversal_of_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Reversal source must already be visible' USING ERRCODE='23503'; END IF;
  IF src.entitlement_id<>NEW.entitlement_id OR src.transaction_type='REVERSE' THEN RAISE EXCEPTION 'Reversal is same Entitlement, not a reversal chain' USING ERRCODE='23514'; END IF;
  IF src.year_reservation_id IS NOT NULL THEN RAISE EXCEPTION 'CROSS_YEAR_CORRECTION_HOLD: do not roll back historical reservation counters' USING ERRCODE='0A000'; END IF;
  IF ROW(NEW.entitled_delta,NEW.carried_delta,NEW.adjusted_delta,NEW.used_delta,NEW.reserved_delta,NEW.prior_reserve_delta)
   IS DISTINCT FROM ROW(-src.entitled_delta,-src.carried_delta,-src.adjusted_delta,-src.used_delta,-src.reserved_delta,-src.prior_reserve_delta)
   OR ROW(NEW.request_id,NEW.leave_day_id,NEW.accrual_run_id) IS DISTINCT FROM ROW(src.request_id,src.leave_day_id,src.accrual_run_id) THEN
   RAISE EXCEPTION 'Reversal exactly compensates recorded source deltas/references without guessed legacy reserve' USING ERRCODE='23514'; END IF;
  RETURN NEW;
 ELSIF NEW.reversal_of_id IS NOT NULL THEN RAISE EXCEPTION 'Only REVERSE may identify a reversal source' USING ERRCODE='23514'; END IF;
 IF NOT extended_source THEN RETURN NEW; END IF;
 IF NEW.year_reservation_id IS NOT NULL THEN
  IF NEW.leave_day_id IS DISTINCT FROM r.leave_day_id OR NEW.prior_reserve_delta IS NULL OR NEW.accrual_run_id IS NOT NULL THEN
   RAISE EXCEPTION 'Cross-year entry requires exact Day/reservation source and explicit reserve delta' USING ERRCODE='23514'; END IF;
  IF NEW.entitlement_id=r.source_entitlement_id THEN
   IF NEW.prior_reserve_delta<>0 OR NEW.entitled_delta<>0 OR NEW.carried_delta<>0 OR NEW.adjusted_delta<>0 OR NEW.reserved_delta>=0 OR
    NOT(NEW.transaction_type='APPROVE' AND NEW.used_delta=-NEW.reserved_delta AND w.status IN('APPROVED','COMPLETED') OR
        NEW.transaction_type='RELEASE' AND NEW.used_delta=0 AND w.status IN('REJECTED','CANCELLED')) THEN
    RAISE EXCEPTION 'Source year consumes/releases only its original Pending with actual outcome' USING ERRCODE='23514'; END IF;
  ELSIF NEW.entitlement_id=r.destination_entitlement_id THEN
   IF NEW.entitled_delta<>0 OR NEW.adjusted_delta<>0 OR NEW.used_delta<>0 OR NEW.reserved_delta<>0 OR
    NOT(NEW.transaction_type='RESERVE' AND NEW.prior_reserve_delta>0 AND NEW.carried_delta=0 AND w.status='PENDING' OR
        NEW.transaction_type='APPROVE' AND NEW.prior_reserve_delta<0 AND NEW.carried_delta=0 AND w.status IN('APPROVED','COMPLETED') OR
        NEW.transaction_type='RELEASE' AND NEW.prior_reserve_delta<0 AND NEW.carried_delta BETWEEN 0 AND -NEW.prior_reserve_delta AND w.status IN('REJECTED','CANCELLED')) THEN
    RAISE EXCEPTION 'Destination prior reserve stays separate; only actual release can credit capped carry' USING ERRCODE='23514'; END IF;
  ELSE RAISE EXCEPTION 'Ledger account is outside its reservation pair' USING ERRCODE='23514';END IF;
  RETURN NEW;
 END IF;
 IF NEW.prior_reserve_delta IS DISTINCT FROM 0 THEN RAISE EXCEPTION 'Ordinary typed entry has no prior-year reserve movement' USING ERRCODE='23514'; END IF;
 IF NEW.record_mode='V1' THEN
  zone:=leave_business_timezone(NEW.effective_date);
  IF NEW.effective_date>(CURRENT_TIMESTAMP AT TIME ZONE zone)::date THEN RAISE EXCEPTION 'No future forecast credits' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.transaction_type='ADJUST' THEN
  IF NEW.entitled_delta<>0 OR NEW.carried_delta<>0 OR NEW.used_delta<>0 OR NEW.reserved_delta<>0 OR NEW.adjusted_delta=0 OR NEW.accrual_run_id IS NOT NULL THEN
   RAISE EXCEPTION 'ADJUST is a signed explicit correction, not an invented grant or reservation' USING ERRCODE='23514'; END IF;
 ELSIF NEW.transaction_type='GRANT' THEN
  SELECT * INTO a FROM leave_accrual_runs WHERE id=NEW.accrual_run_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'V1 GRANT needs actual Accrual Run FK' USING ERRCODE='23514'; END IF;
  IF a.state<>'POSTED' THEN RAISE EXCEPTION 'POLICY_CUTOVER_HOLD: DRAFT evidence is not a grant' USING ERRCODE='0A000'; END IF;
  IF ROW(a.employee_id,a.leave_type_id,a.leave_year) IS DISTINCT FROM ROW(e.employee_id,e.leave_type_id,e.entitlement_year) OR NEW.entitled_delta IS DISTINCT FROM a.amount_days
   OR NEW.carried_delta<>0 OR NEW.adjusted_delta<>0 OR NEW.used_delta<>0 OR NEW.reserved_delta<>0 THEN RAISE EXCEPTION 'GRANT must equal exact posted monthly source and owner' USING ERRCODE='23514'; END IF;
 ELSIF NEW.transaction_type IN('RESERVE','APPROVE','RELEASE') THEN
  IF d.id IS NULL OR extract(year FROM d.leave_date)<>e.entitlement_year OR d.entitlement_id IS DISTINCT FROM e.id THEN
   RAISE EXCEPTION 'Normal reservation needs actual per-Day fund/year source' USING ERRCODE='23514'; END IF;
  IF NEW.entitled_delta<>0 OR NEW.carried_delta<>0 OR NEW.adjusted_delta<>0 OR NEW.accrual_run_id IS NOT NULL OR
   NOT(NEW.transaction_type='RESERVE' AND NEW.reserved_delta>0 AND NEW.used_delta=0 AND w.status='PENDING' OR
       NEW.transaction_type='APPROVE' AND NEW.reserved_delta<0 AND NEW.used_delta=-NEW.reserved_delta AND w.status IN('APPROVED','COMPLETED') OR
       NEW.transaction_type='RELEASE' AND NEW.reserved_delta<0 AND NEW.used_delta=0 AND w.status IN('REJECTED','CANCELLED')) THEN
   RAISE EXCEPTION 'Invalid normal pending/used delta or real Workflow outcome' USING ERRCODE='23514'; END IF;
 ELSE RAISE EXCEPTION 'CARRY_OR_EXPIRY_ENGINE_HOLD: no unsupported V1 transfer/expiry without its typed source' USING ERRCODE='0A000';END IF;
 RETURN NEW;
END $$;
