CREATE FUNCTION leave_require_rc() RETURNS void LANGUAGE plpgsql AS $$ BEGIN
 IF current_setting('transaction_isolation')<>'read committed' THEN RAISE EXCEPTION 'Leave foundation writes require READ COMMITTED' USING ERRCODE='0A000'; END IF;
END $$;
CREATE FUNCTION leave_begin_configuration_write() RETURNS void LANGUAGE plpgsql AS $$ BEGIN
 PERFORM leave_require_rc();PERFORM pg_advisory_xact_lock(724113,17);
END $$;
CREATE FUNCTION leave_business_timezone(day_value date) RETURNS text LANGUAGE plpgsql STABLE AS $$
DECLARE zone text;BEGIN
 SELECT business_timezone INTO zone FROM organization_settings WHERE day_value <@ daterange(effective_from,effective_to,'[)') AND approved_by_id IS NOT NULL AND approved_at IS NOT NULL;
 IF zone IS NULL THEN RAISE EXCEPTION 'BUSINESS_TIMEZONE_SOURCE_HOLD: approved settings required, no session fallback' USING ERRCODE='0A000'; END IF;
 RETURN zone;
END $$;
CREATE FUNCTION leave_policy_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE t leave_types; used boolean;
BEGIN
 PERFORM leave_begin_configuration_write();
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 IF TG_OP='UPDATE' AND NEW.record_mode IS DISTINCT FROM OLD.record_mode THEN RAISE EXCEPTION 'No automatic policy provenance conversion' USING ERRCODE='23514'; END IF;
 IF NEW.record_mode='V1' THEN
  SELECT * INTO t FROM leave_types WHERE id=NEW.leave_type_id FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Policy requires visible real Leave Type' USING ERRCODE='23503'; END IF;
  IF t.code<>'ANNUAL_LEAVE' OR t.unit<>'DAY' OR NOT t.uses_balance THEN RAISE EXCEPTION 'Annual V1 policy cannot accrue Compensatory/Unpaid/legacy type' USING ERRCODE='23514'; END IF;
  IF NEW.active OR NEW.policy_state IS DISTINCT FROM 'CONFIG' THEN RAISE EXCEPTION 'POLICY_CUTOVER_HOLD: keep V1 CONFIG and inactive for legacy reader safety' USING ERRCODE='0A000'; END IF;
  IF NEW.accrual_rule->>'method' IS DISTINCT FROM 'FIXED_MONTHLY' OR jsonb_typeof(NEW.accrual_rule->'amount') IS DISTINCT FROM 'number' THEN
   RAISE EXCEPTION 'Keep existing Java FixedRule shape, exact FIXED_MONTHLY amount' USING ERRCODE='23514'; END IF;
  IF (NEW.accrual_rule->>'amount')::numeric IS DISTINCT FROM NEW.monthly_accrual_days THEN RAISE EXCEPTION 'Accrual rule amount must equal exact typed monthly tier' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='UPDATE' THEN
  SELECT EXISTS(SELECT 1 FROM leave_entitlements WHERE policy_id=OLD.id) OR EXISTS(SELECT 1 FROM leave_policy_assignments WHERE policy_id=OLD.id)
   OR EXISTS(SELECT 1 FROM leave_requests q JOIN workflow_requests w ON w.id=q.workflow_request_id WHERE q.policy_snapshot #>> '{policy,id}'=OLD.id::text AND w.status<>'DRAFT') INTO used;
  IF used AND to_jsonb(OLD)-ARRAY['active','updated_at','updated_by','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['active','updated_at','updated_by','version'] THEN
   IF NOT(OLD.effective_to IS NULL AND NEW.effective_to IS NOT NULL AND
    to_jsonb(OLD)-ARRAY['effective_to','updated_at','updated_by','version']=to_jsonb(NEW)-ARRAY['effective_to','updated_at','updated_by','version'] AND
    NOT EXISTS(SELECT 1 FROM leave_policy_assignments a WHERE a.policy_id=OLD.id AND NOT(daterange(a.effective_from,a.effective_to_internal,'[)') <@ daterange(NEW.effective_from,NEW.effective_to,'[)'))) AND
    NOT EXISTS(SELECT 1 FROM leave_year_reservations r JOIN leave_entitlements e ON e.id=r.source_entitlement_id WHERE e.policy_id=OLD.id AND make_date(e.entitlement_year,12,31)>=NEW.effective_to) AND
    NOT EXISTS(SELECT 1 FROM leave_requests q WHERE q.policy_snapshot #>> '{policy,id}'=OLD.id::text AND q.end_date>=NEW.effective_to)) THEN
    RAISE EXCEPTION 'Used policy payload is historical; only a future closure retaining all actual sources is allowed' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER a0_leave_policy_source BEFORE INSERT OR UPDATE OR DELETE ON leave_policies FOR EACH ROW EXECUTE FUNCTION leave_policy_guard();
CREATE FUNCTION leave_assignment_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p leave_policies; prior leave_policy_assignments; zone text; month_start date; month_end date;
BEGIN
 PERFORM leave_begin_configuration_write();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Assignment history is retained' USING ERRCODE='23514'; END IF;
 SELECT * INTO p FROM leave_policies WHERE id=NEW.policy_id FOR SHARE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Assignment requires visible real Policy' USING ERRCODE='23503'; END IF;
 IF p.record_mode<>'V1' OR p.leave_type_id<>NEW.leave_type_id THEN RAISE EXCEPTION 'Assignment needs configured V1 Policy of same Leave Type' USING ERRCODE='23514'; END IF;
 IF NOT(daterange(NEW.effective_from,NEW.effective_to_internal,'[)') <@ daterange(p.effective_from,p.effective_to,'[)')) THEN
  RAISE EXCEPTION 'Assignment range must fit actual policy revision' USING ERRCODE='23514'; END IF;
 zone:=leave_business_timezone(NEW.effective_from);
 IF NEW.effective_from<(p.confirmed_at AT TIME ZONE zone)::date THEN RAISE EXCEPTION 'Do not synthesize assignment history before explicit source confirmation' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' AND NEW IS DISTINCT FROM OLD THEN
  IF OLD.effective_to_internal IS NOT NULL OR NEW.effective_to_internal IS NULL OR
   to_jsonb(OLD)-ARRAY['effective_to_internal','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['effective_to_internal','version'] OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'Replacement only closes an open range, retaining old identity and sources' USING ERRCODE='23514'; END IF;
  IF EXISTS(SELECT 1 FROM leave_accrual_runs r WHERE r.assignment_id=OLD.id AND
    NOT(daterange(make_date(r.leave_year,r.accrual_month,1),(make_date(r.leave_year,r.accrual_month,1)+interval '1 month')::date,'[)') && daterange(NEW.effective_from,NEW.effective_to_internal,'[)'))) THEN
   RAISE EXCEPTION 'Closure cannot remove an accrual source from its actual month' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.replaces_id IS NOT NULL THEN
  SELECT * INTO prior FROM leave_policy_assignments WHERE id=NEW.replaces_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Replacement predecessor must already exist' USING ERRCODE='23503'; END IF;
  IF prior.id=NEW.id OR ROW(prior.employee_id,prior.leave_type_id) IS DISTINCT FROM ROW(NEW.employee_id,NEW.leave_type_id)
    OR prior.effective_from>=NEW.effective_from OR prior.effective_to_internal IS DISTINCT FROM NEW.effective_from THEN
   RAISE EXCEPTION 'Replacement must follow same-owner older range at its exclusive end; no cycles' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER leave_assignment_source BEFORE INSERT OR UPDATE OR DELETE ON leave_policy_assignments FOR EACH ROW EXECUTE FUNCTION leave_assignment_guard();
CREATE FUNCTION leave_accrual_basis(aid bigint,y integer,m integer,evidence bigint) RETURNS jsonb LANGUAGE plpgsql SET timezone='UTC' SET datestyle='ISO,YMD' AS $$
DECLARE a leave_policy_assignments; lo date; hi date;
BEGIN
 SELECT * INTO a FROM leave_policy_assignments WHERE id=aid;
 IF NOT FOUND THEN RAISE EXCEPTION 'Accrual Assignment must be visible' USING ERRCODE='23503'; END IF;
 lo:=make_date(y,m,1);hi:=(lo+interval '1 month')::date;
 RETURN jsonb_build_object('period_start',lo,'period_end_exclusive',hi,'assignment',to_jsonb(a),
  'policy',(SELECT to_jsonb(p) FROM leave_policies p WHERE p.id=a.policy_id),
  'leave_type',(SELECT to_jsonb(t) FROM leave_types t WHERE t.id=a.leave_type_id),
  'evidence_asset',(SELECT to_jsonb(d) FROM document_assets d WHERE d.id=evidence),
  'known_assignments',(SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.effective_from,x.id),'[]'::jsonb) FROM leave_policy_assignments x
    WHERE x.employee_id=a.employee_id AND x.leave_type_id=a.leave_type_id AND daterange(x.effective_from,x.effective_to_internal,'[)') && daterange(lo,hi,'[)')),
  'known_status_periods',(SELECT COALESCE(jsonb_agg(to_jsonb(s) ORDER BY s.effective_from,s.id),'[]'::jsonb) FROM employee_status_periods s
    WHERE s.employee_id=a.employee_id AND daterange(s.effective_from,s.effective_to,'[)') && daterange(lo,hi,'[)')),
  'eligibility_complete',false,'operational_posting_hold',true);
END $$;
CREATE FUNCTION leave_accrual_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a leave_policy_assignments; p leave_policies; lo date; hi date; n integer; zone text;
BEGIN
 PERFORM leave_begin_configuration_write();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Accrual evidence history is retained' USING ERRCODE='23514'; END IF;
 IF NEW.state='POSTED' THEN RAISE EXCEPTION 'POLICY_CUTOVER_HOLD: no operational accrual posting or implicit GRANT in4A' USING ERRCODE='0A000'; END IF;
 IF TG_OP='UPDATE' THEN
  IF OLD.state='POSTED' OR EXISTS(SELECT 1 FROM leave_balance_transactions WHERE accrual_run_id=OLD.id)
    OR EXISTS(SELECT 1 FROM leave_issues WHERE accrual_run_id=OLD.id AND state='RESOLVED') THEN
   RAISE EXCEPTION 'Used/posted Accrual source is immutable' USING ERRCODE='23514'; END IF;
  IF to_jsonb(OLD)-ARRAY['eligible_days','normal_days','amount_days','evidence_asset_id','source_snapshot','version'] IS DISTINCT FROM
     to_jsonb(NEW)-ARRAY['eligible_days','normal_days','amount_days','evidence_asset_id','source_snapshot','version'] OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'DRAFT evidence edits retain month/owner/assignment identity and advance version' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.leave_year NOT BETWEEN 1900 AND 9998 OR NEW.accrual_month NOT BETWEEN 1 AND 12 THEN RAISE EXCEPTION 'Invalid accrual year/month' USING ERRCODE='23514'; END IF;
 SELECT * INTO a FROM leave_policy_assignments WHERE id=NEW.assignment_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Accrual needs actual visible Assignment' USING ERRCODE='23503'; END IF;
 SELECT * INTO p FROM leave_policies WHERE id=a.policy_id;
 lo:=make_date(NEW.leave_year,NEW.accrual_month,1);hi:=(lo+interval '1 month')::date;
 IF ROW(a.employee_id,a.leave_type_id) IS DISTINCT FROM ROW(NEW.employee_id,NEW.leave_type_id) OR
  NOT(daterange(a.effective_from,a.effective_to_internal,'[)') && daterange(lo,hi,'[)')) THEN
   RAISE EXCEPTION 'Accrual owner/type/month must match historical effective Assignment, not current Employee status' USING ERRCODE='23514'; END IF;
 IF NEW.source_snapshot->'basis' IS DISTINCT FROM leave_accrual_basis(NEW.assignment_id,NEW.leave_year,NEW.accrual_month,NEW.evidence_asset_id) THEN
   RAISE EXCEPTION 'Snapshot must identify actual typed source rows, never invented evidence' USING ERRCODE='23514'; END IF;
 SELECT count(DISTINCT policy_id) INTO n FROM leave_policy_assignments WHERE employee_id=a.employee_id AND leave_type_id=a.leave_type_id
  AND daterange(effective_from,effective_to_internal,'[)') && daterange(lo,hi,'[)');
 IF n>1 AND NEW.amount_days IS NOT NULL THEN RAISE EXCEPTION 'OD-06: mid-month policy conflict has no automatic first/last/max selection' USING ERRCODE='23514'; END IF;
 IF NEW.amount_days IS NOT NULL THEN
  zone:=leave_business_timezone(lo);
  IF hi>(CURRENT_TIMESTAMP AT TIME ZONE zone)::date OR NEW.evidence_asset_id IS NULL OR NEW.created_by_id IS NULL OR NEW.normal_days IS NULL OR NEW.eligible_days IS NULL
    OR NEW.eligible_days>NEW.normal_days OR NEW.normal_days>extract(day FROM hi-1) THEN
   RAISE EXCEPTION 'Candidate amount needs completed month, actual evidence/actor and bounded counts; no forecast' USING ERRCODE='23514'; END IF;
  IF NEW.normal_days=0 AND (NEW.eligible_days<>0 OR NEW.amount_days<>0) OR NEW.normal_days>0 AND
   (NEW.eligible_days*2>=NEW.normal_days AND NEW.amount_days IS DISTINCT FROM p.monthly_accrual_days OR
    NEW.eligible_days*2<NEW.normal_days AND NEW.amount_days<>0) THEN
   RAISE EXCEPTION 'At least50percent gives exact1/1.5/2 candidate once; otherwise0, never prorate' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
