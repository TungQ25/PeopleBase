CREATE FUNCTION leave_year_reservation_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE s leave_entitlements;d leave_entitlements;day_row leave_request_days;q leave_requests;w workflow_requests;p leave_policies;t leave_types;
BEGIN
 PERFORM leave_require_rc();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Reservation history cannot be erased' USING ERRCODE='23514'; END IF;
 SELECT * INTO day_row FROM leave_request_days WHERE id=NEW.leave_day_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Reservation needs actual visible Leave Day' USING ERRCODE='23503'; END IF;
 PERFORM leave_lock_request(day_row.request_id);PERFORM leave_lock_entitlements(ARRAY[NEW.source_entitlement_id,NEW.destination_entitlement_id]);
 SELECT * INTO s FROM leave_entitlements WHERE id=NEW.source_entitlement_id;SELECT * INTO d FROM leave_entitlements WHERE id=NEW.destination_entitlement_id;
 IF s.id IS NULL OR d.id IS NULL THEN RAISE EXCEPTION 'Both year funds must already exist; no safe-create at Submit' USING ERRCODE='23503'; END IF;
 SELECT * INTO q FROM leave_requests WHERE id=day_row.request_id;SELECT * INTO w FROM workflow_requests WHERE id=q.workflow_request_id;
 SELECT * INTO p FROM leave_policies WHERE id=s.policy_id FOR SHARE;SELECT * INTO t FROM leave_types WHERE id=s.leave_type_id;
 IF ROW(s.employee_id,s.leave_type_id) IS DISTINCT FROM ROW(d.employee_id,d.leave_type_id) OR s.unit<>'DAY' OR d.unit<>'DAY' OR d.entitlement_year<>s.entitlement_year+1
  OR extract(year FROM day_row.leave_date)<>s.entitlement_year OR day_row.entitlement_id IS DISTINCT FROM s.id
  OR w.target_employee_id<>s.employee_id OR q.leave_type_id IS DISTINCT FROM s.leave_type_id OR t.code NOT IN('ANNUAL','ANNUAL_LEAVE') OR NOT t.uses_balance
  OR NEW.reserved_days>day_row.balance_units THEN
  RAISE EXCEPTION 'Reservation must retain actual Annual Leave Day, same owner/type and adjacent years' USING ERRCODE='23514'; END IF;
 IF p.id IS NULL OR p.leave_type_id<>s.leave_type_id OR p.carry_forward_limit IS NULL OR
   NOT(make_date(s.entitlement_year,12,31) <@ daterange(p.effective_from,p.effective_to,'[)')) OR NEW.carry_cap_snapshot IS DISTINCT FROM p.carry_forward_limit THEN
  RAISE EXCEPTION 'CARRY_CAP_SOURCE_HOLD: no invented/ambiguous cap; actual source-year policy required' USING ERRCODE='23514'; END IF;
 IF d.prior_year_reserved_units IS NULL THEN RAISE EXCEPTION 'LEGACY_UNKNOWN_RESERVE_OPENING: do not guess destination opening state' USING ERRCODE='0A000'; END IF;
 IF TG_OP='INSERT' THEN
  IF NEW.consumed_days<>0 OR NEW.released_days<>0 OR NEW.created_by_id IS NULL OR w.status<>'PENDING' THEN
   RAISE EXCEPTION 'New reservation records real pending rights, not fabricated historical outcomes' USING ERRCODE='23514'; END IF;
 ELSE
  IF to_jsonb(OLD)-ARRAY['consumed_days','released_days','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['consumed_days','released_days','version']
   OR NEW.consumed_days<OLD.consumed_days OR NEW.released_days<OLD.released_days OR NEW.version<>OLD.version+1 THEN
   RAISE EXCEPTION 'Keep reservation source/cap/reserved fixed; outcome counters only advance with version' USING ERRCODE='23514'; END IF;
  IF NEW.consumed_days>OLD.consumed_days AND w.status NOT IN('APPROVED','COMPLETED') OR NEW.released_days>OLD.released_days AND w.status NOT IN('REJECTED','CANCELLED') THEN
   RAISE EXCEPTION 'Consumption/release needs actual approved or rejected/cancelled outcome; no auto approval' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER leave_year_reservation_source BEFORE INSERT OR UPDATE OR DELETE ON leave_year_reservations FOR EACH ROW EXECUTE FUNCTION leave_year_reservation_guard();
CREATE FUNCTION leave_assert_reservation(rid bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE r leave_year_reservations;s record;d record;pending numeric;needed numeric;cap numeric;credited numeric;base_carry numeric;released numeric;request_value bigint;
BEGIN
 SELECT * INTO r FROM leave_year_reservations WHERE id=rid;IF NOT FOUND THEN RETURN;END IF;
 SELECT COALESCE(sum(reserved_delta),0)pending,COALESCE(sum(used_delta),0)used INTO s FROM leave_balance_transactions WHERE year_reservation_id=rid AND entitlement_id=r.source_entitlement_id;
 SELECT COALESCE(sum(prior_reserve_delta),0)prior,COALESCE(sum(carried_delta),0)carry INTO d FROM leave_balance_transactions WHERE year_reservation_id=rid AND entitlement_id=r.destination_entitlement_id;
 IF s.pending IS DISTINCT FROM -(r.consumed_days+r.released_days) OR s.used IS DISTINCT FROM r.consumed_days OR d.prior IS DISTINCT FROM r.reserved_days-r.consumed_days-r.released_days THEN
  RAISE EXCEPTION 'Reservation/source/destination ledger outcomes must commit atomically; no unbacked counters' USING ERRCODE='23514'; END IF;
 SELECT COALESCE(sum(x.reserved_days-x.consumed_days-x.released_days),0) INTO needed FROM leave_year_reservations x WHERE x.source_entitlement_id=r.source_entitlement_id;
 SELECT reserved_units INTO pending FROM leave_entitlements WHERE id=r.source_entitlement_id;
 IF needed>pending THEN RAISE EXCEPTION 'Outstanding prior-year rights exceed recorded source Pending' USING ERRCODE='23514';END IF;
 SELECT request_id INTO request_value FROM leave_request_days WHERE id=r.leave_day_id;
 SELECT COALESCE(sum(x.reserved_days-x.consumed_days-x.released_days),0) INTO needed FROM leave_year_reservations x JOIN leave_request_days z ON z.id=x.leave_day_id
  WHERE x.source_entitlement_id=r.source_entitlement_id AND z.request_id=request_value;
 SELECT COALESCE(sum(reserved_delta),0) INTO pending FROM leave_balance_transactions WHERE entitlement_id=r.source_entitlement_id AND request_id=request_value;
 IF needed>pending THEN RAISE EXCEPTION 'Reservation cannot borrow Pending recorded for another Request' USING ERRCODE='23514';END IF;
 SELECT COALESCE(sum(x.reserved_days),0) INTO needed FROM leave_year_reservations x WHERE x.leave_day_id=r.leave_day_id AND x.source_entitlement_id=r.source_entitlement_id;
 IF needed>(SELECT balance_units FROM leave_request_days WHERE id=r.leave_day_id) THEN RAISE EXCEPTION 'Same Leave Day cannot be reserved twice across year mappings' USING ERRCODE='23514';END IF;
 SELECT min(carry_cap_snapshot),COALESCE(sum(released_days),0) INTO cap,released FROM leave_year_reservations WHERE destination_entitlement_id=r.destination_entitlement_id;
 SELECT COALESCE(sum(t.carried_delta),0) INTO credited FROM leave_balance_transactions t JOIN leave_year_reservations x ON x.id=t.year_reservation_id WHERE t.entitlement_id=r.destination_entitlement_id;
 SELECT carried_units-credited INTO base_carry FROM leave_entitlements WHERE id=r.destination_entitlement_id;
 IF base_carry<0 OR base_carry>cap OR credited IS DISTINCT FROM LEAST(released,GREATEST(cap-base_carry,0)) THEN
  RAISE EXCEPTION 'Released reserve credits only real remaining carry cap; cap applies across the destination fund' USING ERRCODE='23514';END IF;
END $$;
CREATE FUNCTION leave_reservation_constraint() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE rid bigint;BEGIN
 IF TG_TABLE_NAME='leave_year_reservations' THEN PERFORM leave_assert_reservation(NEW.id);
 ELSIF TG_TABLE_NAME='leave_balance_transactions' THEN
  IF NEW.year_reservation_id IS NOT NULL THEN PERFORM leave_assert_reservation(NEW.year_reservation_id);END IF;
  FOR rid IN SELECT id FROM leave_year_reservations WHERE source_entitlement_id=NEW.entitlement_id OR destination_entitlement_id=NEW.entitlement_id ORDER BY id LOOP PERFORM leave_assert_reservation(rid);END LOOP;
 ELSE
  FOR rid IN SELECT id FROM leave_year_reservations WHERE source_entitlement_id=NEW.id OR destination_entitlement_id=NEW.id ORDER BY id LOOP PERFORM leave_assert_reservation(rid);END LOOP;
 END IF;RETURN NULL;
END $$;
