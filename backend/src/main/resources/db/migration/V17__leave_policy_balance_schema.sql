CREATE FUNCTION leave_day_ledger_constraint() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE pending numeric;used numeric;amount numeric;BEGIN
 IF NEW.leave_day_id IS NULL OR NEW.year_reservation_id IS NOT NULL THEN RETURN NULL;END IF;
 SELECT COALESCE(sum(reserved_delta),0),COALESCE(sum(used_delta),0) INTO pending,used FROM leave_balance_transactions WHERE leave_day_id=NEW.leave_day_id AND year_reservation_id IS NULL;
 SELECT balance_units INTO amount FROM leave_request_days WHERE id=NEW.leave_day_id;
 IF pending<0 OR used<0 OR pending+used>amount THEN RAISE EXCEPTION 'Typed normal Day source cannot be double-reserved/used or released without its recorded source' USING ERRCODE='23514';END IF;
 RETURN NULL;
END $$;
