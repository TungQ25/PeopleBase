CREATE FUNCTION leave_source_pin() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE used boolean;BEGIN
 IF TG_TABLE_NAME='leave_request_days' THEN
  SELECT EXISTS(SELECT 1 FROM leave_balance_transactions WHERE leave_day_id=OLD.id) OR EXISTS(SELECT 1 FROM leave_year_reservations WHERE leave_day_id=OLD.id) INTO used;
 ELSIF TG_TABLE_NAME='leave_requests' THEN
  SELECT EXISTS(SELECT 1 FROM leave_balance_transactions WHERE request_id=OLD.id) OR EXISTS(SELECT 1 FROM leave_issues WHERE request_id=OLD.id)
   OR EXISTS(SELECT 1 FROM leave_request_days d JOIN leave_year_reservations r ON r.leave_day_id=d.id WHERE d.request_id=OLD.id) INTO used;
 ELSE
  IF OLD.request_type<>'LEAVE' THEN RETURN NEW;END IF;
  SELECT EXISTS(SELECT 1 FROM leave_requests q WHERE q.workflow_request_id=OLD.id AND
   (EXISTS(SELECT 1 FROM leave_balance_transactions WHERE request_id=q.id) OR EXISTS(SELECT 1 FROM leave_issues WHERE request_id=q.id))) INTO used;
  IF used AND ROW(NEW.target_employee_id,NEW.request_type) IS DISTINCT FROM ROW(OLD.target_employee_id,OLD.request_type) THEN
   RAISE EXCEPTION 'Fund history pins actual Leave Workflow owner/type' USING ERRCODE='23514';END IF;
  RETURN NEW;
 END IF;
 IF used AND (TG_OP='DELETE' OR to_jsonb(OLD)-ARRAY['updated_at','updated_by','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['updated_at','updated_by','version']) THEN
  RAISE EXCEPTION 'Fund/reservation source payload is historical; no Request/Day rewrite' USING ERRCODE='23514';END IF;
 IF TG_OP='DELETE' THEN RETURN OLD;END IF;RETURN NEW;
END $$;
CREATE TRIGGER a1_leave_foundation_day_pin BEFORE UPDATE OR DELETE ON leave_request_days FOR EACH ROW EXECUTE FUNCTION leave_source_pin();
