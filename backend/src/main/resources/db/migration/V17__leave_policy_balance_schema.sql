CREATE FUNCTION leave_issue_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE q leave_requests;w workflow_requests;a leave_accrual_runs;p leave_policies;e leave_entitlements;assig leave_policy_assignments;t leave_balance_transactions;
BEGIN
 PERFORM leave_require_rc();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Leave Issue history cannot be erased' USING ERRCODE='23514';END IF;
 IF TG_OP='UPDATE' AND OLD.state='RESOLVED' AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'Resolved Issue/audit is immutable' USING ERRCODE='23514';END IF;
 PERFORM leave_lock_request(NEW.request_id);
 IF NEW.request_id IS NOT NULL THEN SELECT * INTO q FROM leave_requests WHERE id=NEW.request_id;SELECT * INTO w FROM workflow_requests WHERE id=q.workflow_request_id;
  IF w.target_employee_id IS DISTINCT FROM NEW.employee_id THEN RAISE EXCEPTION 'Issue Request has different Employee' USING ERRCODE='23514';END IF;END IF;
 IF NEW.accrual_run_id IS NOT NULL THEN SELECT * INTO a FROM leave_accrual_runs WHERE id=NEW.accrual_run_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Accrual source must exist' USING ERRCODE='23503';END IF;
  IF a.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue Accrual has different Employee' USING ERRCODE='23514';END IF;END IF;
 IF NEW.policy_id IS NOT NULL THEN SELECT * INTO p FROM leave_policies WHERE id=NEW.policy_id FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Policy source must exist' USING ERRCODE='23503';END IF;END IF;
 IF NEW.entitlement_id IS NOT NULL THEN PERFORM leave_lock_entitlements(ARRAY[NEW.entitlement_id]);SELECT * INTO e FROM leave_entitlements WHERE id=NEW.entitlement_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue fund source must exist' USING ERRCODE='23503';END IF;
  IF e.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue fund has different Employee' USING ERRCODE='23514';END IF;END IF;
 IF NEW.assignment_id IS NOT NULL THEN SELECT * INTO assig FROM leave_policy_assignments WHERE id=NEW.assignment_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Assignment source must exist' USING ERRCODE='23503';END IF;
  IF assig.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue Assignment has different Employee' USING ERRCODE='23514';END IF;END IF;
 IF NEW.code LIKE 'BR-LEAVE-ACC-%' AND a.id IS NULL OR NEW.code LIKE 'BR-LEAVE-ASN-%' AND assig.id IS NULL
  OR NEW.code LIKE 'BR-LEAVE-POL-%' AND p.id IS NULL OR NEW.code LIKE 'BR-LEAVE-BAL-%' AND num_nonnulls(e.id,q.id,a.id)=0 THEN
  RAISE EXCEPTION 'Issue rule locator needs its actual typed source, never a fake Request/Run' USING ERRCODE='23514';END IF;
 IF NEW.state='RESOLVED' THEN
  IF NEW.code LIKE 'BR-LEAVE-ACC-%' THEN RAISE EXCEPTION 'ACCRUAL_RECONCILIATION_HOLD: DRAFT source is not completed accrual' USING ERRCODE='0A000';END IF;
  IF NEW.code LIKE 'BR-LEAVE-BAL-%' OR NEW.code LIKE 'BR-LEAVE-ADJ-%' THEN
   SELECT * INTO t FROM leave_balance_transactions WHERE id=NEW.resolution_transaction_id;
   IF NOT FOUND THEN RAISE EXCEPTION 'Balance resolution needs actual correcting Ledger FK' USING ERRCODE='23514';END IF;
   IF e.id IS NULL OR t.entitlement_id<>e.id OR t.actor_id IS DISTINCT FROM NEW.resolved_by_id OR t.reason IS DISTINCT FROM NEW.reason
     OR t.transaction_type NOT IN('ADJUST','REVERSE','RELEASE') THEN
    RAISE EXCEPTION 'Resolution must trace same fund and real correction actor/reason, never mutate totals' USING ERRCODE='23514';END IF;
  ELSIF NEW.code LIKE 'BR-LEAVE-POL-%' OR NEW.code LIKE 'BR-LEAVE-ASN-%' THEN
   IF p.id IS NULL AND assig.id IS NOT NULL THEN SELECT * INTO p FROM leave_policies WHERE id=assig.policy_id;END IF;
   IF p.record_mode IS DISTINCT FROM 'V1' OR p.policy_state IS DISTINCT FROM 'CONFIG' OR p.confirmed_by_id IS NULL OR p.evidence_asset_id IS NULL THEN
    RAISE EXCEPTION 'Policy configuration resolution needs actual confirmed metadata, not activation approval' USING ERRCODE='23514';END IF;
  ELSE RAISE EXCEPTION 'Resolution needs a reviewed typed source process' USING ERRCODE='0A000';END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER leave_issue_source BEFORE INSERT OR UPDATE OR DELETE ON leave_issues FOR EACH ROW EXECUTE FUNCTION leave_issue_guard();
