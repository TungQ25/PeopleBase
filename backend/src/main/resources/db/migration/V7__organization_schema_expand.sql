-- Phase 1A: additive storage only. No seed, history reconstruction or V1 activation.
-- Existing mapped columns (including timestamps/nullability) remain unchanged.
-- Integrity is installed by V8 in the same release, before any new writer is used.

CREATE TABLE organization_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    singleton_key SMALLINT NOT NULL,
    revision INTEGER NOT NULL,
    business_timezone VARCHAR(80) NOT NULL,
    email_domain VARCHAR(150),
    email_naming_rule JSONB,
    employee_code_format JSONB,
    effective_from DATE NOT NULL,
    effective_to DATE,
    approved_by_id BIGINT,
    approved_at TIMESTAMPTZ,
    max_advance_months SMALLINT,
    morning_cutoff TIME,
    afternoon_cutoff TIME,
    day_cutoff TIME,
    leave_registration_state VARCHAR(16) NOT NULL DEFAULT 'CONFIG',
    leave_cutoff_precision VARCHAR(24),
    leave_advance_basis VARCHAR(24)
);

CREATE TABLE document_assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_id BIGINT,
    version BIGINT NOT NULL DEFAULT 0,
    storage_key VARCHAR(500) NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL,
    classification VARCHAR(30) NOT NULL,
    uploaded_by_id BIGINT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE departments
    ADD COLUMN is_hr_department BOOLEAN,
    ADD COLUMN record_mode VARCHAR(40) NOT NULL DEFAULT 'LEGACY';

ALTER TABLE positions
    ADD COLUMN responsibilities TEXT,
    ADD COLUMN record_mode VARCHAR(40) NOT NULL DEFAULT 'LEGACY';

ALTER TABLE employee_assignments
    ADD COLUMN management_level VARCHAR(30),
    ADD COLUMN reporting_profile VARCHAR(30),
    ADD COLUMN observed_at TIMESTAMPTZ,
    ADD COLUMN provenance VARCHAR(40),
    ADD COLUMN record_mode VARCHAR(40) NOT NULL DEFAULT 'LEGACY';

ALTER TABLE manager_assignments
    ADD COLUMN management_level VARCHAR(30),
    ADD COLUMN record_mode VARCHAR(40) NOT NULL DEFAULT 'LEGACY';

COMMENT ON TABLE organization_settings IS
    'Versioned one-company configuration. Empty until explicit configuration; Leave remains CONFIG in Phase 1A.';
COMMENT ON TABLE document_assets IS
    'Immutable binary-version metadata; no public URL, object storage, upload or download authorization is implemented here.';
COMMENT ON COLUMN departments.is_hr_department IS
    'Explicit organization identity, NULL means unknown. Never inferred from name, role or manager.';
COMMENT ON COLUMN positions.responsibilities IS
    'Position responsibilities; legacy positions.level is not Management Level.';
COMMENT ON COLUMN employee_assignments.observed_at IS
    'Explicit evidence observation time, not an inferred effective/hire date. No automatic backfill.';
COMMENT ON COLUMN employee_assignments.provenance IS
    'Evidence/source classification reserved for a reviewed writer; NULL legacy unknown. Not a fabricated action ID.';
COMMENT ON COLUMN employee_assignments.management_level IS
    'Staged organization attribute; does not grant a role or activate a hierarchy.';
COMMENT ON COLUMN employee_assignments.reporting_profile IS
    'Staged reporting identity independent of authorization; vocabulary/activation remain HOLD.';
COMMENT ON COLUMN manager_assignments.management_level IS
    'Staged attribute; PRIMARY/ACTING/DEPUTY and all existing exclusions remain unchanged.';

