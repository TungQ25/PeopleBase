CREATE FUNCTION attendance_finalization_require_rc() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 IF current_setting('transaction_isolation')<>'read committed' THEN
  RAISE EXCEPTION 'Attendance period/source writes require READ COMMITTED' USING ERRCODE='0A000';
 END IF;
END $$;

-- Shared registry pins are per Employee/Schedule, never a global ingestion
-- mutex. Configuration callers must declare affected IDs before mixed DML.
-- Exclusive configuration reuses V14's existing global domain FIRST, then
-- Employee -> Schedule pins; source operations acquire only shared ID pins.
CREATE FUNCTION attendance_lock_registry(employees bigint[],schedules bigint[],exclusive boolean DEFAULT false) RETURNS void LANGUAGE plpgsql AS $$
DECLARE k bigint;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF exclusive THEN PERFORM pg_advisory_xact_lock(724113,14); END IF;
 FOR k IN SELECT DISTINCT x FROM unnest(employees)x WHERE x IS NOT NULL ORDER BY x LOOP
  IF exclusive THEN PERFORM pg_advisory_xact_lock(hashtextextended('attendance.registry.employee:'||k,0));
  ELSE PERFORM pg_advisory_xact_lock_shared(hashtextextended('attendance.registry.employee:'||k,0)); END IF;
 END LOOP;
 FOR k IN SELECT DISTINCT x FROM unnest(schedules)x WHERE x IS NOT NULL ORDER BY x LOOP
  IF exclusive THEN PERFORM pg_advisory_xact_lock(hashtextextended('attendance.registry.schedule:'||k,0));
  ELSE PERFORM pg_advisory_xact_lock_shared(hashtextextended('attendance.registry.schedule:'||k,0)); END IF;
 END LOOP;
END $$;
CREATE FUNCTION attendance_pin_source_registry(emp bigint,log_value bigint DEFAULT NULL,shift_value bigint DEFAULT NULL) RETURNS void LANGUAGE plpgsql AS $$
DECLARE schedules bigint[];
BEGIN
 PERFORM attendance_lock_registry(ARRAY[emp],ARRAY[]::bigint[],false);
 SELECT array_agg(DISTINCT schedule_id ORDER BY schedule_id) INTO schedules FROM(
  SELECT a.schedule_id FROM employee_schedule_assignments a WHERE a.employee_id=emp
  UNION SELECT a.schedule_id FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE o.id=shift_value
  UNION SELECT a.schedule_id FROM attendance_log_matches m JOIN scheduled_shifts o ON o.id=m.scheduled_shift_id JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id WHERE m.log_id=log_value
 )s;
 PERFORM attendance_lock_registry(ARRAY[]::bigint[],schedules,false);
END $$;
CREATE FUNCTION attendance_period_ids_for_shift(sid bigint) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(array_agg(DISTINCT p.id ORDER BY p.id),ARRAY[]::bigint[])
 FROM scheduled_shifts o JOIN employee_schedule_assignments a ON a.id=o.schedule_assignment_id
 JOIN attendance_cycle_schedules x ON x.schedule_id=a.schedule_id AND o.work_date <@ daterange(x.effective_from,x.effective_to,'[)')
 JOIN attendance_periods p ON p.cycle_id=x.cycle_id AND o.work_date BETWEEN p.start_date AND p.end_date WHERE o.id=sid
$$;
CREATE FUNCTION attendance_period_ids_for_event(emp bigint,instant timestamptz,log_value bigint DEFAULT NULL) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(array_agg(DISTINCT id ORDER BY id),ARRAY[]::bigint[]) FROM(
  SELECT p.id FROM employee_schedule_assignments a JOIN attendance_cycle_schedules x ON x.schedule_id=a.schedule_id
  JOIN attendance_cycles c ON c.id=x.cycle_id JOIN attendance_periods p ON p.cycle_id=c.id
  WHERE a.employee_id=emp AND (instant AT TIME ZONE c.timezone)::date <@ daterange(a.effective_from,a.effective_to,'[)')
   AND (instant AT TIME ZONE c.timezone)::date <@ daterange(x.effective_from,x.effective_to,'[)')
   AND (instant AT TIME ZONE c.timezone)::date BETWEEN p.start_date AND p.end_date
  UNION SELECT unnest(attendance_period_ids_for_shift(m.scheduled_shift_id)) FROM attendance_log_matches m WHERE m.log_id=log_value AND m.scheduled_shift_id IS NOT NULL
  UNION SELECT v.period_id FROM attendance_results r JOIN attendance_version_results m ON m.result_id=r.id JOIN attendance_period_versions v ON v.id=m.version_id
   WHERE r.effective_in_log_id=log_value OR r.effective_out_log_id=log_value
 )q
$$;
CREATE FUNCTION attendance_period_ids_for_assignment(aid bigint) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(array_agg(DISTINCT p.id ORDER BY p.id),ARRAY[]::bigint[])
 FROM employee_schedule_assignments a JOIN attendance_cycle_schedules x ON x.schedule_id=a.schedule_id
 JOIN attendance_periods p ON p.cycle_id=x.cycle_id
 WHERE a.id=aid AND daterange(a.effective_from,a.effective_to,'[)') && daterange(x.effective_from,x.effective_to,'[)')
  AND daterange(a.effective_from,a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')
  AND daterange(x.effective_from,x.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')
$$;
CREATE FUNCTION attendance_lock_periods(ids bigint[],write_mode boolean DEFAULT true) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF write_mode THEN PERFORM id FROM attendance_periods WHERE id=ANY(ids) ORDER BY id FOR NO KEY UPDATE;
 ELSE PERFORM id FROM attendance_periods WHERE id=ANY(ids) ORDER BY id FOR SHARE; END IF;
END $$;
CREATE FUNCTION attendance_assert_unfinalized(ids bigint[]) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM attendance_periods WHERE id=ANY(ids) AND state='FINALIZED') THEN
  RAISE EXCEPTION 'Known Attendance Period is FINALIZED; authorized REOPEN is required before source application/correction' USING ERRCODE='23514';
 END IF;
END $$;
CREATE FUNCTION attendance_begin_period_write(pid bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE schedules bigint[];
BEGIN
 SELECT array_agg(DISTINCT x.schedule_id ORDER BY x.schedule_id) INTO schedules FROM attendance_cycle_schedules x JOIN attendance_periods p ON p.cycle_id=x.cycle_id
  WHERE p.id=pid AND daterange(x.effective_from,x.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]');
 PERFORM attendance_lock_registry(ARRAY[]::bigint[],schedules,false);
 PERFORM attendance_lock_periods(ARRAY[pid],true);
END $$;

CREATE FUNCTION attendance_expected_period_end(start_value date,cycle_value bigint) RETURNS date LANGUAGE plpgsql STABLE AS $$
DECLARE c attendance_cycles; base date;
BEGIN
 SELECT * INTO c FROM attendance_cycles WHERE id=cycle_value;
 IF NOT FOUND OR extract(day FROM start_value)<>c.start_day THEN RETURN NULL; END IF;
 base:=date_trunc('month',start_value::timestamp)::date;
 IF c.month_end THEN RETURN (base+interval '1 month - 1 day')::date; END IF;
 IF c.end_day<c.start_day THEN base:=(base+interval '1 month')::date; END IF;
 -- No short-month clamping: invalid configured dates are rejected explicitly.
 RETURN make_date(extract(year FROM base)::integer,extract(month FROM base)::integer,c.end_day);
END $$;
CREATE FUNCTION attendance_check_cycle_links() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM attendance_cycle_schedules x JOIN attendance_cycles c ON c.id=x.cycle_id JOIN work_schedules s ON s.id=x.schedule_id
  WHERE NOT (daterange(x.effective_from,x.effective_to,'[)') <@ daterange(c.effective_from,c.effective_to,'[)'))
   OR NOT (daterange(x.effective_from,x.effective_to,'[)') <@ daterange(s.effective_from,s.effective_to,'[)'))) THEN
  RAISE EXCEPTION 'Cycle Schedule coverage must remain within real Cycle and WorkSchedule ranges' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE FUNCTION attendance_cycle_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 PERFORM attendance_finalization_require_rc();
 -- Share V14's configuration domain with link/WorkSchedule range writes so
 -- deferred cross-row coverage cannot validate two invisible concurrent changes.
 -- Mixed configuration commands predeclare this domain before their row DML.
 PERFORM pg_advisory_xact_lock(724113,14);
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_timezone_names WHERE name=NEW.timezone) OR NOT EXISTS(
  SELECT 1 FROM organization_settings s WHERE s.approved_at IS NOT NULL AND s.approved_by_id IS NOT NULL AND s.business_timezone=NEW.timezone
   AND NEW.effective_from <@ daterange(s.effective_from,s.effective_to,'[)')) THEN
  RAISE EXCEPTION 'Cycle needs an explicit configured approved business timezone; no server fallback' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' AND EXISTS(SELECT 1 FROM attendance_periods WHERE cycle_id=OLD.id) THEN
  IF NOT (OLD.effective_to IS NULL AND NEW.effective_to IS NOT NULL AND
   to_jsonb(OLD)-ARRAY['effective_to','version']=to_jsonb(NEW)-ARRAY['effective_to','version'] AND
   NOT EXISTS(SELECT 1 FROM attendance_periods WHERE cycle_id=OLD.id AND end_date>=NEW.effective_to)) AND NEW IS DISTINCT FROM OLD THEN
   RAISE EXCEPTION 'Used Cycle definition is immutable; create a revision' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_cycle_definition BEFORE INSERT OR UPDATE OR DELETE ON attendance_cycles FOR EACH ROW EXECUTE FUNCTION attendance_cycle_guard();
CREATE FUNCTION attendance_cycle_schedule_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; employees bigint[]; schedules bigint[]; last_end date;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_OP='INSERT' THEN schedules:=ARRAY[NEW.schedule_id]; ELSE schedules:=ARRAY[OLD.schedule_id]; END IF;
 IF TG_OP='UPDATE' THEN schedules:=schedules||NEW.schedule_id; END IF;
 SELECT array_agg(DISTINCT employee_id ORDER BY employee_id) INTO employees FROM employee_schedule_assignments WHERE schedule_id=ANY(schedules);
 PERFORM attendance_lock_registry(employees,schedules,true);
 SELECT array_agg(id ORDER BY id) INTO ids FROM attendance_periods p WHERE
  (TG_OP<>'INSERT' AND p.cycle_id=OLD.cycle_id AND daterange(p.start_date,p.end_date,'[]') && daterange(OLD.effective_from,OLD.effective_to,'[)')) OR
  (TG_OP<>'DELETE' AND p.cycle_id=NEW.cycle_id AND daterange(p.start_date,p.end_date,'[]') && daterange(NEW.effective_from,NEW.effective_to,'[)'));
 PERFORM attendance_lock_periods(ids,true);
 IF TG_OP='INSERT' THEN PERFORM attendance_assert_unfinalized(ids);
 ELSE
  SELECT max(p.end_date) INTO last_end FROM attendance_periods p WHERE id=ANY(ids) AND p.cycle_id=OLD.cycle_id
   AND EXISTS(SELECT 1 FROM attendance_period_versions v WHERE v.period_id=p.id AND v.sealed_at IS NOT NULL);
  IF last_end IS NOT NULL AND (TG_OP='DELETE' OR NEW IS DISTINCT FROM OLD AND NOT(
    OLD.effective_to IS NULL AND NEW.effective_to IS NOT NULL AND NEW.effective_to>last_end AND
    to_jsonb(OLD)-ARRAY['effective_to','version']=to_jsonb(NEW)-ARRAY['effective_to','version'])) THEN
   RAISE EXCEPTION 'Sealed Cycle Schedule provenance cannot move or disappear' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
