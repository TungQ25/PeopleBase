 IF EXISTS(SELECT 1 FROM leave_request_days d JOIN attendance_results r ON r.leave_day_id=d.id WHERE d.request_id=OLD.id) AND
  (TG_OP='DELETE' OR to_jsonb(OLD)-ARRAY['updated_at','updated_by','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['updated_at','updated_by','version']) THEN
