CREATE FUNCTION attendance_effective_input(log_value bigint,rev_value bigint,sid bigint,event_kind text,require_current boolean DEFAULT true) RETURNS timestamptz LANGUAGE plpgsql AS $$
DECLARE l attendance_logs; v attendance_log_revisions; o scheduled_shifts; s shifts; z organization_settings;
        latest bigint; instant timestamptz; recorded timestamptz; window_from timestamptz; window_to timestamptz;
BEGIN
 IF log_value IS NULL THEN RETURN NULL; END IF;
 SELECT * INTO l FROM attendance_logs WHERE id=log_value;
 IF NOT FOUND THEN RAISE EXCEPTION 'Effective raw log does not exist' USING ERRCODE='23503'; END IF;
 SELECT * INTO o FROM scheduled_shifts WHERE id=sid; SELECT * INTO s FROM shifts WHERE id=o.shift_id;
 SELECT * INTO z FROM organization_settings WHERE id=o.organization_settings_id;
 IF l.employee_id<>o.employee_id OR l.event_type<>event_kind THEN
  RAISE EXCEPTION 'Effective IN/OUT must have same Employee and correct event type' USING ERRCODE='23514'; END IF;
 instant:=l.event_at;recorded:=l.recorded_at;
 IF rev_value IS NOT NULL THEN
  SELECT * INTO v FROM attendance_log_revisions WHERE id=rev_value;
  IF NOT FOUND THEN RAISE EXCEPTION 'Effective correction does not exist' USING ERRCODE='23503'; END IF;
  IF v.log_id<>l.id OR v.is_voided OR l.source<>'MANUAL' THEN
   RAISE EXCEPTION 'Effective correction must belong to selected MANUAL log and cannot be VOID' USING ERRCODE='23514'; END IF;
  instant:=v.event_at;recorded:=v.recorded_at;
 END IF;
 IF require_current THEN
  SELECT id INTO latest FROM attendance_log_revisions WHERE log_id=l.id ORDER BY revision DESC LIMIT 1;
  IF latest IS DISTINCT FROM rev_value OR NOT EXISTS(SELECT 1 FROM attendance_current_log_matches m
   WHERE m.log_id=l.id AND m.log_revision_id IS NOT DISTINCT FROM rev_value AND m.scheduled_shift_id=o.id AND m.match_status='MATCHED') THEN
   RAISE EXCEPTION 'Effective input needs current non-void MATCHED source, not unresolved UNMATCHED history' USING ERRCODE='23514'; END IF;
 END IF;
 window_from:=(o.work_date+CASE WHEN event_kind='CHECK_IN' THEN s.checkin_from ELSE s.checkout_from END) AT TIME ZONE z.business_timezone;
 window_to:=(o.work_date+CASE WHEN event_kind='CHECK_IN' THEN s.checkin_to ELSE s.checkout_to END) AT TIME ZONE z.business_timezone;
 IF instant<window_from OR instant>window_to THEN
  RAISE EXCEPTION 'Selected normal source is outside its event-specific pinned Shift window' USING ERRCODE='23514'; END IF;
 RETURN instant;
END $$;
CREATE FUNCTION attendance_leave_covers(day_value bigint,sid bigint,require_approved boolean DEFAULT true) RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM leave_request_days d JOIN leave_requests r ON r.id=d.request_id JOIN workflow_requests w ON w.id=r.workflow_request_id
  CROSS JOIN scheduled_shifts o JOIN shifts s ON s.id=o.shift_id WHERE d.id=day_value AND o.id=sid
   AND w.target_employee_id=o.employee_id AND d.leave_date=o.work_date AND (NOT require_approved OR w.status IN('APPROVED','COMPLETED'))
   AND (d.segment='FULL_DAY' OR d.segment='AM' AND o.slot='MORNING_SHIFT' OR d.segment='PM' AND o.slot='AFTERNOON_SHIFT'
    OR d.segment='HOURS' AND d.start_time<=s.start_time AND d.end_time>=s.end_time))
$$;
CREATE FUNCTION attendance_assert_result(r attendance_results,require_current boolean DEFAULT true) RETURNS void LANGUAGE plpgsql AS $$
DECLARE o scheduled_shifts; p attendance_policy_versions; in_at timestamptz; out_at timestamptz; max_recorded timestamptz;
BEGIN
 SELECT * INTO o FROM scheduled_shifts WHERE id=r.scheduled_shift_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Result needs actual Scheduled Shift' USING ERRCODE='23503'; END IF;
 SELECT * INTO p FROM attendance_policy_versions WHERE id=r.policy_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Result needs actual approved policy' USING ERRCODE='23503'; END IF;
 IF NOT (o.work_date <@ daterange(p.effective_from,p.effective_to,'[)')) OR r.calculated_at<p.approved_at THEN
  RAISE EXCEPTION 'Result policy must apply on its real work_date' USING ERRCODE='23514'; END IF;
 in_at:=attendance_effective_input(r.effective_in_log_id,r.in_revision_id,o.id,'CHECK_IN',require_current);
 out_at:=attendance_effective_input(r.effective_out_log_id,r.out_revision_id,o.id,'CHECK_OUT',require_current);
 IF require_current AND EXISTS(SELECT 1 FROM attendance_current_log_matches m JOIN attendance_logs l ON l.id=m.log_id
  WHERE m.scheduled_shift_id=o.id AND m.match_status='MATCHED' AND
   (l.event_type='CHECK_IN' AND r.effective_in_log_id IS NULL OR l.event_type='CHECK_OUT' AND r.effective_out_log_id IS NULL)) THEN
  RAISE EXCEPTION 'Completion cannot omit a known current MATCHED IN/OUT; append a recalculated Result revision' USING ERRCODE='23514'; END IF;
 IF in_at IS NOT NULL AND out_at IS NOT NULL AND out_at<in_at THEN RAISE EXCEPTION 'Effective OUT precedes IN' USING ERRCODE='23514'; END IF;
 SELECT max(v) INTO max_recorded FROM(
  SELECT recorded_at v FROM attendance_logs WHERE id IN(r.effective_in_log_id,r.effective_out_log_id)
  UNION ALL SELECT recorded_at FROM attendance_log_revisions WHERE id IN(r.in_revision_id,r.out_revision_id)
 )q;
 IF r.calculated_at<max_recorded THEN RAISE EXCEPTION 'Calculation cannot precede its actual stored source recording' USING ERRCODE='23514'; END IF;
 IF r.presence='ATTENDED' AND (r.completion<>'COMPLETE' OR o.requirement<>'REQUIRED' OR r.leave_day_id IS NOT NULL) OR
    r.presence='ABSENT' AND (r.completion<>'NO_ATTENDANCE' OR o.requirement<>'REQUIRED' OR r.leave_day_id IS NOT NULL OR r.calculated_at<o.planned_end) OR
    r.presence='NOT_REQUIRED' AND o.requirement<>'NOT_REQUIRED' OR
    r.presence='INCOMPLETE' AND (r.completion<>'INCOMPLETE' OR o.requirement<>'REQUIRED') OR
    r.completion='INCOMPLETE' AND r.presence IN('ATTENDED','ABSENT') THEN
  RAISE EXCEPTION 'Completion, declared requirement and Presence are distinct and must agree' USING ERRCODE='23514'; END IF;
 IF r.leave_day_id IS NOT NULL AND NOT attendance_leave_covers(r.leave_day_id,o.id,require_current) THEN
  RAISE EXCEPTION 'Leave Day must belong to Employee/date/slot and be an approved actual source' USING ERRCODE='23514'; END IF;
 IF r.presence='EXCUSED_LEAVE' AND (r.completion<>'NO_ATTENDANCE' OR r.leave_day_id IS NULL) OR
    r.leave_day_id IS NOT NULL AND r.presence<>'EXCUSED_LEAVE' THEN
  RAISE EXCEPTION 'EXCUSED_LEAVE needs a covering source without silently overriding Attendance' USING ERRCODE='23514'; END IF;
END $$;
CREATE FUNCTION attendance_result_insert_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE o scheduled_shifts; l record; ids bigint[]; direct_ids bigint[]; n integer;
BEGIN
 PERFORM attendance_finalization_require_rc();SELECT * INTO o FROM scheduled_shifts WHERE id=NEW.scheduled_shift_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Result occurrence must already be visible before Period source gate' USING ERRCODE='23503'; END IF;
 PERFORM attendance_pin_source_registry(o.employee_id,NULL,o.id);
 direct_ids:=attendance_period_ids_for_shift(o.id);
 IF cardinality(direct_ids)<>1 THEN RAISE EXCEPTION 'Result needs one configured actual Cycle/Period; do not fabricate a Period' USING ERRCODE='23514'; END IF;
 ids:=direct_ids;
 FOR l IN SELECT id,employee_id,event_at FROM attendance_logs WHERE id IN(NEW.effective_in_log_id,NEW.effective_out_log_id) ORDER BY id LOOP
  ids:=ids||attendance_period_ids_for_event(l.employee_id,l.event_at,l.id);
 END LOOP;
 PERFORM attendance_lock_periods(ids,true);PERFORM attendance_assert_unfinalized(direct_ids);
 -- Parent-log SHARE serializes source selection against V15's per-log writes.
 PERFORM id FROM attendance_logs WHERE id IN(NEW.effective_in_log_id,NEW.effective_out_log_id) ORDER BY id FOR SHARE;
 SELECT COALESCE(max(revision),0)+1 INTO n FROM attendance_results WHERE scheduled_shift_id=o.id;
 IF NEW.revision<>n THEN RAISE EXCEPTION 'Result recalculation appends the next business revision' USING ERRCODE='23514'; END IF;
 PERFORM attendance_assert_result(NEW,true);
 IF NEW.accepted_incomplete_by_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM attendance_periods WHERE id=direct_ids[1] AND state='REVIEWING') THEN
  RAISE EXCEPTION 'Accept as Incomplete is available only in REVIEWING' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_result_source BEFORE INSERT ON attendance_results FOR EACH ROW EXECUTE FUNCTION attendance_result_insert_guard();

CREATE FUNCTION attendance_issue_period_ids(i attendance_issues) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(ARRAY[i.period_id],ARRAY[]::bigint[])||attendance_period_ids_for_shift(i.scheduled_shift_id)||
  attendance_period_ids_for_assignment(i.schedule_assignment_id)||attendance_period_ids_for_event(i.employee_id,l.event_at,i.log_id)
 FROM (SELECT (SELECT event_at FROM attendance_logs WHERE id=i.log_id)event_at)l
$$;
CREATE FUNCTION attendance_issue_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE ids bigint[]; old_ids bigint[]; o scheduled_shifts; l attendance_logs; r attendance_results; m missing_attendance_requests;
        owner_id bigint; wstate text; assig employee_schedule_assignments; target_period attendance_periods;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Issue history cannot be erased' USING ERRCODE='23514'; END IF;
 IF NEW.state='OPEN' AND NEW.code ~ '^(OT_|OVERTIME)' AND NOT NEW.blocking THEN
  RAISE EXCEPTION 'Unverified OT dependency remains blocking until its real module exists' USING ERRCODE='23514'; END IF;
 IF TG_OP='UPDATE' AND OLD.state='RESOLVED' AND NEW IS DISTINCT FROM OLD THEN
  RAISE EXCEPTION 'Resolved Issue/audit is immutable; record a new source issue' USING ERRCODE='23514'; END IF;
 PERFORM attendance_pin_source_registry(NEW.employee_id,NEW.log_id,NEW.scheduled_shift_id);
 ids:=attendance_issue_period_ids(NEW);
 IF TG_OP='UPDATE' THEN ids:=ids||attendance_issue_period_ids(OLD); END IF;
 PERFORM attendance_lock_periods(ids,true);
 -- New OPEN issues may record late evidence after close; this does not rewrite
 -- the old finalized version. Resolution/application still requires REOPEN.
 IF NEW.state='RESOLVED' OR TG_OP='UPDATE' AND NEW IS DISTINCT FROM OLD THEN PERFORM attendance_assert_unfinalized(ids); END IF;
 IF NEW.scheduled_shift_id IS NOT NULL THEN
  SELECT * INTO o FROM scheduled_shifts WHERE id=NEW.scheduled_shift_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue occurrence must already be visible' USING ERRCODE='23503'; END IF;
  IF o.id IS NOT NULL AND o.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue occurrence has different Employee' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.log_id IS NOT NULL THEN
  SELECT * INTO l FROM attendance_logs WHERE id=NEW.log_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue raw source must already be visible' USING ERRCODE='23503'; END IF;
  IF l.id IS NOT NULL AND l.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue log has different Employee' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.result_id IS NOT NULL THEN
  SELECT * INTO r FROM attendance_results WHERE id=NEW.result_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue exact Result must already be visible' USING ERRCODE='23503'; END IF;
  SELECT * INTO o FROM scheduled_shifts WHERE id=r.scheduled_shift_id;
  IF o.id IS NOT NULL AND (o.employee_id<>NEW.employee_id OR NEW.scheduled_shift_id IS NOT NULL AND NEW.scheduled_shift_id<>o.id) THEN
   RAISE EXCEPTION 'Issue Result must match actual Employee/occurrence' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.missing_request_id IS NOT NULL THEN
  SELECT * INTO m FROM missing_attendance_requests WHERE id=NEW.missing_request_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Missing source must already be visible' USING ERRCODE='23503'; END IF;
  SELECT target_employee_id,status INTO owner_id,wstate FROM workflow_requests WHERE id=m.workflow_request_id;
  IF owner_id IS NOT NULL AND (owner_id<>NEW.employee_id OR NEW.scheduled_shift_id IS NOT NULL AND NEW.scheduled_shift_id IS DISTINCT FROM m.scheduled_shift_id) THEN
   RAISE EXCEPTION 'Issue Missing source has different Employee/occurrence' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.schedule_assignment_id IS NOT NULL THEN
  SELECT * INTO assig FROM employee_schedule_assignments WHERE id=NEW.schedule_assignment_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Assignment must already be visible' USING ERRCODE='23503'; END IF;
  IF assig.id IS NOT NULL AND assig.employee_id<>NEW.employee_id THEN RAISE EXCEPTION 'Issue Assignment has different Employee' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.period_id IS NOT NULL THEN
  SELECT * INTO target_period FROM attendance_periods WHERE id=NEW.period_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Issue Period must already be visible' USING ERRCODE='23503'; END IF;
  IF o.id IS NOT NULL AND NOT (NEW.period_id=ANY(attendance_period_ids_for_shift(o.id))) THEN
   RAISE EXCEPTION 'Issue source does not belong to declared Cycle/Period' USING ERRCODE='23514'; END IF;
  IF l.id IS NOT NULL AND NOT (NEW.period_id=ANY(attendance_period_ids_for_event(NEW.employee_id,l.event_at,l.id))) THEN
   RAISE EXCEPTION 'Unscheduled Issue needs actual as-of Employee/Schedule/Cycle scope' USING ERRCODE='23514'; END IF;
  IF assig.id IS NOT NULL AND NOT (daterange(assig.effective_from,assig.effective_to,'[)') && daterange(target_period.start_date,target_period.end_date,'[]')) THEN
   RAISE EXCEPTION 'Configuration Issue Assignment must overlap actual Period' USING ERRCODE='23514'; END IF;
 END IF;
 IF NEW.code='INCOMPLETE' AND NEW.result_id IS NULL AND NEW.scheduled_shift_id IS NULL OR
    NEW.code='ATTENDANCE_CYCLE_CONFIGURATION_ISSUE' AND NEW.schedule_assignment_id IS NULL OR
    NEW.code='PENDING_MISSING_ATTENDANCE' AND NEW.missing_request_id IS NULL OR
    NEW.code IN('UNMATCHED_LOG','UNSCHEDULED_ATTENDANCE','PENDING_MANUAL_CORRECTION') AND NEW.log_id IS NULL THEN
  RAISE EXCEPTION 'Known Issue code requires its real typed source, no placeholder' USING ERRCODE='23514'; END IF;
 IF NEW.state='RESOLVED' THEN
  IF NEW.resolved_at<l.recorded_at OR NEW.resolved_at<r.calculated_at OR NEW.resolved_at<m.received_at THEN
   RAISE EXCEPTION 'Resolution timestamp cannot precede its actual recorded source' USING ERRCODE='23514'; END IF;
  IF NEW.resolution='MATCHED_TO_OVERTIME' OR NEW.code ~ '^(OT_|OVERTIME)' THEN
   RAISE EXCEPTION 'OVERTIME_DEPENDENCY: no real OT Detail/confirmation yet; matching does not clear OT blockers' USING ERRCODE='23514'; END IF;
  IF NEW.resolution='ACCEPTED_INCOMPLETE' THEN
   IF NEW.result_id IS NULL OR r.completion<>'INCOMPLETE' OR r.accepted_incomplete_by_id IS DISTINCT FROM NEW.resolved_by_id OR r.accept_reason IS DISTINCT FROM NEW.reason
    OR NEW.period_id IS NULL OR target_period.state<>'REVIEWING' OR NEW.resolved_at<r.calculated_at OR NEW.resolved_at<o.planned_end THEN
    RAISE EXCEPTION 'Accepted INCOMPLETE needs exact Result FK and real REVIEWING actor/time/reason audit' USING ERRCODE='23514'; END IF;
  ELSIF NEW.resolution='ACKNOWLEDGED_NO_ACTION' THEN
   IF NEW.code NOT IN('UNMATCHED_LOG','UNSCHEDULED_ATTENDANCE','LATE','EARLY_LEAVE','ABSENT') OR NEW.log_id IS NULL AND NEW.result_id IS NULL THEN
    RAISE EXCEPTION 'Acknowledgement needs an actual reviewable source, not a free pass' USING ERRCODE='23514'; END IF;
  ELSIF NEW.resolution='ATTENDANCE_CORRECTION' THEN
   IF NEW.result_id IS NULL THEN RAISE EXCEPTION 'Correction resolution needs exact recalculated Result' USING ERRCODE='23514'; END IF;
   PERFORM attendance_assert_result(r,true);
  ELSIF NEW.resolution='REQUEST_PROCESSED' THEN
   IF NEW.missing_request_id IS NULL OR NOT(wstate IN('REJECTED','CANCELLED') OR m.applied_at IS NOT NULL) THEN
    RAISE EXCEPTION 'Missing resolution requires actual workflow/application outcome' USING ERRCODE='23514'; END IF;
  ELSIF NEW.resolution='CONFIGURATION_FIXED' THEN
   IF assig.id IS NULL OR NOT (daterange(assig.effective_from,assig.effective_to,'[)') <@ COALESCE((
    SELECT range_agg(daterange(x.effective_from,x.effective_to,'[)')) FROM attendance_cycle_schedules x WHERE x.schedule_id=assig.schedule_id),'{}'::datemultirange)) THEN
    RAISE EXCEPTION 'Configuration resolution needs actual Schedule/Cycle coverage' USING ERRCODE='23514'; END IF;
  ELSIF NEW.resolution='LEAVE_SOURCE_CORRECTED' THEN
   IF NEW.result_id IS NULL THEN RAISE EXCEPTION 'Leave conflict needs an actual new Result/source outcome' USING ERRCODE='23514'; END IF;
   PERFORM attendance_assert_result(r,true);
   IF EXISTS(SELECT 1 FROM leave_request_days d WHERE attendance_leave_covers(d.id,o.id,true)) AND EXISTS(
    SELECT 1 FROM attendance_current_log_matches x WHERE x.scheduled_shift_id=o.id AND x.match_status='MATCHED') THEN
    RAISE EXCEPTION 'Leave/Attendance sources still conflict' USING ERRCODE='23514'; END IF;
  ELSE RAISE EXCEPTION 'Unsupported resolution requires a reviewed typed source rule' USING ERRCODE='23514';
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_issue_source BEFORE INSERT OR UPDATE OR DELETE ON attendance_issues FOR EACH ROW EXECUTE FUNCTION attendance_issue_guard();

CREATE FUNCTION attendance_check_result_acceptance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE rid bigint; r attendance_results;
BEGIN
 IF TG_TABLE_NAME='attendance_results' THEN rid:=NEW.id;
 ELSE rid:=NEW.result_id; END IF;
 SELECT * INTO r FROM attendance_results WHERE id=rid;
 IF r.accepted_incomplete_by_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM attendance_issues i WHERE i.result_id=r.id AND i.state='RESOLVED'
   AND i.resolution='ACCEPTED_INCOMPLETE' AND i.resolved_by_id=r.accepted_incomplete_by_id AND i.reason=r.accept_reason AND i.resolved_at IS NOT NULL) THEN
  RAISE EXCEPTION 'Accepted Result needs its immutable typed Issue decision timestamp, never calculated_at as a fake audit time' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER attendance_result_acceptance AFTER INSERT ON attendance_results DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION attendance_check_result_acceptance();
CREATE CONSTRAINT TRIGGER attendance_issue_acceptance AFTER INSERT OR UPDATE ON attendance_issues DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION attendance_check_result_acceptance();
CREATE VIEW attendance_result_acceptance_audit AS SELECT r.id AS result_id,r.scheduled_shift_id,r.revision,r.completion,r.accepted_incomplete_by_id,
 i.id AS acceptance_issue_id,i.resolved_at AS accepted_at,i.reason FROM attendance_results r JOIN attendance_issues i ON i.result_id=r.id
 WHERE i.state='RESOLVED' AND i.resolution='ACCEPTED_INCOMPLETE';

CREATE FUNCTION attendance_issue_ids_for_period(pid bigint) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(array_agg(DISTINCT i.id ORDER BY i.id),ARRAY[]::bigint[]) FROM attendance_issues i CROSS JOIN attendance_periods p
 WHERE p.id=pid AND (i.period_id=pid OR pid=ANY(attendance_issue_period_ids(i)) OR
  i.period_id IS NULL AND i.schedule_assignment_id IS NOT NULL AND EXISTS(
   SELECT 1 FROM employee_schedule_assignments a WHERE a.id=i.schedule_assignment_id
    AND daterange(a.effective_from,a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]'))
  AND EXISTS(SELECT 1 FROM employee_schedule_assignments a JOIN attendance_cycle_schedules x ON x.schedule_id=a.schedule_id
   WHERE a.employee_id=i.employee_id AND x.cycle_id=p.cycle_id AND daterange(a.effective_from,a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')
    AND daterange(x.effective_from,x.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')))
$$;
CREATE FUNCTION attendance_validate_member(m attendance_version_results,require_current boolean DEFAULT true) RETURNS void LANGUAGE plpgsql AS $$
DECLARE v attendance_period_versions; p attendance_periods; r attendance_results; o scheduled_shifts; c attendance_cycles; tz text;
BEGIN
 SELECT * INTO v FROM attendance_period_versions WHERE id=m.version_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Membership version does not exist' USING ERRCODE='23503'; END IF;
 SELECT * INTO p FROM attendance_periods WHERE id=v.period_id;SELECT * INTO c FROM attendance_cycles WHERE id=p.cycle_id;
 SELECT * INTO r FROM attendance_results WHERE id=m.result_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Membership must reference exact real Result revision' USING ERRCODE='23503'; END IF;
 SELECT * INTO o FROM scheduled_shifts WHERE id=r.scheduled_shift_id;
 SELECT business_timezone INTO tz FROM organization_settings WHERE id=o.organization_settings_id;
 IF ROW(m.employee_id,m.work_date,m.slot) IS DISTINCT FROM ROW(o.employee_id,o.work_date,o.slot) OR
  NOT (m.work_date BETWEEN p.start_date AND p.end_date) OR NOT(p.id=ANY(attendance_period_ids_for_shift(o.id))) OR tz IS DISTINCT FROM c.timezone THEN
  RAISE EXCEPTION 'Membership Employee/date/slot/Cycle/Period must match exact Result occurrence' USING ERRCODE='23514'; END IF;
 IF require_current THEN
  IF r.revision<>(SELECT max(revision) FROM attendance_results WHERE scheduled_shift_id=o.id) OR
    o.revision<>(SELECT max(revision) FROM scheduled_shifts WHERE employee_id=o.employee_id AND work_date=o.work_date AND slot=o.slot) THEN
   RAISE EXCEPTION 'New version must select current Result/occurrence revisions; unchanged prior latest Result may be reused' USING ERRCODE='23514'; END IF;
  PERFORM attendance_assert_result(r,true);
 END IF;
END $$;
CREATE FUNCTION attendance_membership_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v attendance_period_versions; old_v attendance_period_versions; roots bigint[]; pid bigint; schedules bigint[];
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_OP<>'INSERT' THEN SELECT * INTO old_v FROM attendance_period_versions WHERE id=OLD.version_id;roots:=array_append(roots,old_v.period_id); END IF;
 IF TG_OP<>'DELETE' THEN SELECT * INTO v FROM attendance_period_versions WHERE id=NEW.version_id;roots:=array_append(roots,v.period_id); END IF;
 SELECT array_agg(DISTINCT x.schedule_id ORDER BY x.schedule_id) INTO schedules
 FROM attendance_cycle_schedules x JOIN attendance_periods p ON p.cycle_id=x.cycle_id WHERE p.id=ANY(roots);
 PERFORM attendance_lock_registry(ARRAY[]::bigint[],schedules,false);
 PERFORM attendance_lock_periods(roots,true);
 IF TG_OP<>'INSERT' THEN
  SELECT * INTO old_v FROM attendance_period_versions WHERE id=OLD.version_id;
  IF old_v.sealed_at IS NOT NULL THEN RAISE EXCEPTION 'Sealed membership cannot change, move or disappear' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP<>'DELETE' THEN
  SELECT * INTO v FROM attendance_period_versions WHERE id=NEW.version_id;
  IF v.sealed_at IS NOT NULL OR NOT EXISTS(SELECT 1 FROM attendance_periods WHERE id=v.period_id AND state='REVIEWING') THEN
   RAISE EXCEPTION 'Attach membership only to BUILDING header in REVIEWING' USING ERRCODE='23514'; END IF;
  PERFORM attendance_validate_member(NEW,true);RETURN NEW;
 END IF;
 RETURN OLD;
END $$;
CREATE TRIGGER attendance_membership_source BEFORE INSERT OR UPDATE OR DELETE ON attendance_version_results FOR EACH ROW EXECUTE FUNCTION attendance_membership_guard();

CREATE FUNCTION attendance_validate_seal(vid bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE v attendance_period_versions; p attendance_periods; m attendance_version_results; issue_ids bigint[]; n integer;
BEGIN
 SELECT * INTO v FROM attendance_period_versions WHERE id=vid;SELECT * INTO p FROM attendance_periods WHERE id=v.period_id;
 IF p.state<>'REVIEWING' THEN RAISE EXCEPTION 'SEAL requires REVIEWING, including after REOPEN' USING ERRCODE='23514'; END IF;
 SELECT count(*) INTO n FROM attendance_version_results WHERE version_id=vid;
 IF n=0 THEN RAISE EXCEPTION 'Do not fabricate an empty finalized header without typed Result membership' USING ERRCODE='23514'; END IF;
 FOR m IN SELECT * FROM attendance_version_results WHERE version_id=vid ORDER BY employee_id,work_date,slot LOOP
  PERFORM attendance_validate_member(m,true);
 END LOOP;
 -- Covers every KNOWN stored latest occurrence. Expected work that has not
 -- been materialized still needs the Backend; this is not a roster generator.
 IF EXISTS(SELECT 1 FROM scheduled_shifts o WHERE o.work_date BETWEEN p.start_date AND p.end_date
  AND p.id=ANY(attendance_period_ids_for_shift(o.id))
  AND o.revision=(SELECT max(revision) FROM scheduled_shifts x WHERE x.employee_id=o.employee_id AND x.work_date=o.work_date AND x.slot=o.slot)
  AND NOT EXISTS(SELECT 1 FROM attendance_version_results z JOIN attendance_results r ON r.id=z.result_id WHERE z.version_id=vid AND r.scheduled_shift_id=o.id)) THEN
  RAISE EXCEPTION 'Known stored occurrence is missing from final membership' USING ERRCODE='23514'; END IF;
 issue_ids:=attendance_issue_ids_for_period(p.id);
 IF EXISTS(SELECT 1 FROM attendance_issues WHERE id=ANY(issue_ids) AND blocking AND state='OPEN') THEN
  RAISE EXCEPTION 'Unresolved blocking Attendance/OT Issue prevents structural finalization' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM attendance_version_results z JOIN attendance_results r ON r.id=z.result_id WHERE z.version_id=vid AND r.completion='INCOMPLETE' AND
  NOT EXISTS(SELECT 1 FROM attendance_issues i WHERE i.result_id=r.id AND i.state='RESOLVED' AND i.resolution='ACCEPTED_INCOMPLETE'
   AND i.resolved_by_id=r.accepted_incomplete_by_id AND i.reason=r.accept_reason)) THEN
  RAISE EXCEPTION 'Unprocessed INCOMPLETE is blocking even when no Issue was generated' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM missing_attendance_requests q JOIN workflow_requests w ON w.id=q.workflow_request_id
  WHERE p.id=ANY(attendance_period_ids_for_shift(q.scheduled_shift_id)) AND
   (w.status='PENDING' OR w.status IN('APPROVED','COMPLETED') AND q.applied_at IS NULL)) THEN
  RAISE EXCEPTION 'Pending Missing or approved-but-unapplied source must be processed before a new finalization' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM attendance_logs l JOIN attendance_effective_logs e ON e.log_id=l.id
  WHERE NOT e.is_voided AND p.id=ANY(attendance_period_ids_for_event(l.employee_id,e.effective_event_at,l.id))
   AND NOT EXISTS(SELECT 1 FROM attendance_current_log_matches x WHERE x.log_id=l.id AND x.match_status='MATCHED')
   AND NOT EXISTS(SELECT 1 FROM attendance_issues i WHERE i.id=ANY(issue_ids) AND i.log_id=l.id AND i.state='RESOLVED'
    AND i.resolution IN('ACKNOWLEDGED_NO_ACTION','ATTENDANCE_CORRECTION'))) THEN
  RAISE EXCEPTION 'Known active UNMATCHED/UNSCHEDULED evidence requires a real review resolution' USING ERRCODE='23514'; END IF;
 IF EXISTS(SELECT 1 FROM attendance_version_results z JOIN attendance_results r ON r.id=z.result_id
  WHERE z.version_id=vid AND EXISTS(SELECT 1 FROM leave_request_days d WHERE attendance_leave_covers(d.id,r.scheduled_shift_id,true))
   AND EXISTS(SELECT 1 FROM attendance_current_log_matches x WHERE x.scheduled_shift_id=r.scheduled_shift_id AND x.match_status='MATCHED')) THEN
  RAISE EXCEPTION 'Actual approved Leave and matched Attendance still conflict; do not silently override' USING ERRCODE='23514'; END IF;
 -- A known employee/schedule change with no cycle coverage cannot be omitted
 -- just because no occurrence/issue has yet been materialized for that change.
 IF EXISTS(SELECT 1 FROM employee_schedule_assignments a WHERE daterange(a.effective_from,a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')
  AND (EXISTS(SELECT 1 FROM attendance_version_results z WHERE z.version_id=vid AND z.employee_id=a.employee_id) OR
   EXISTS(SELECT 1 FROM employee_schedule_assignments prior_a JOIN attendance_cycle_schedules x ON x.schedule_id=prior_a.schedule_id
    WHERE prior_a.employee_id=a.employee_id AND x.cycle_id=p.cycle_id
     AND daterange(prior_a.effective_from,prior_a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')
     AND daterange(x.effective_from,x.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')))
  AND NOT ((daterange(a.effective_from,a.effective_to,'[)') * daterange(p.start_date,p.end_date,'[]')) <@ COALESCE((
   SELECT range_agg(daterange(x.effective_from,x.effective_to,'[)')) FROM attendance_cycle_schedules x WHERE x.schedule_id=a.schedule_id),'{}'::datemultirange))) THEN
  RAISE EXCEPTION 'Known Schedule coverage gap needs explicit configuration resolution; no automatic cycle inclusion' USING ERRCODE='23514'; END IF;
END $$;

-- Canonical snapshot of actual FK sources, not a client-supplied ID array or
-- attendance calculation. UTC is serialization only; business dates use Cycle/
-- OrganizationSettings explicitly. Sealed snapshots remain historical when a
-- later current revision/projection changes.
CREATE FUNCTION attendance_version_snapshot(vid bigint) RETURNS jsonb LANGUAGE plpgsql SET timezone='UTC' SET datestyle='ISO,YMD' AS $$
DECLARE v attendance_period_versions; p attendance_periods; c attendance_cycles; result_rows jsonb; issue_rows jsonb;
BEGIN
 SELECT * INTO v FROM attendance_period_versions WHERE id=vid;
 IF NOT FOUND THEN RAISE EXCEPTION 'Version does not exist' USING ERRCODE='23503'; END IF;
 IF v.sealed_at IS NOT NULL THEN RETURN v.summary->'source_snapshot'; END IF;
 PERFORM attendance_begin_period_write(v.period_id);
 SELECT * INTO v FROM attendance_period_versions WHERE id=vid;SELECT * INTO p FROM attendance_periods WHERE id=v.period_id;SELECT * INTO c FROM attendance_cycles WHERE id=p.cycle_id;
 SELECT COALESCE(jsonb_agg(jsonb_build_object('membership',to_jsonb(m),'result',to_jsonb(r),'occurrence',to_jsonb(o),
  'policy',(SELECT to_jsonb(x) FROM attendance_policy_versions x WHERE x.id=r.policy_id),
  'input_in',(SELECT to_jsonb(x) FROM attendance_logs x WHERE x.id=r.effective_in_log_id),
  'input_out',(SELECT to_jsonb(x) FROM attendance_logs x WHERE x.id=r.effective_out_log_id),
  'in_revision',(SELECT to_jsonb(x) FROM attendance_log_revisions x WHERE x.id=r.in_revision_id),
  'out_revision',(SELECT to_jsonb(x) FROM attendance_log_revisions x WHERE x.id=r.out_revision_id),
  'matching_evidence',(SELECT COALESCE(jsonb_agg(to_jsonb(x) ORDER BY x.id),'[]'::jsonb) FROM attendance_current_log_matches x
    WHERE x.scheduled_shift_id=o.id AND x.log_id IN(r.effective_in_log_id,r.effective_out_log_id) AND x.match_status='MATCHED'),
  'leave_source',(SELECT jsonb_build_object('day',to_jsonb(d),'request',to_jsonb(q),'workflow',to_jsonb(w)) FROM leave_request_days d JOIN leave_requests q ON q.id=d.request_id JOIN workflow_requests w ON w.id=q.workflow_request_id WHERE d.id=r.leave_day_id),
  'acceptance_audit',(SELECT to_jsonb(i) FROM attendance_issues i WHERE i.result_id=r.id AND i.resolution='ACCEPTED_INCOMPLETE' AND i.state='RESOLVED'))
  ORDER BY m.employee_id,m.work_date,m.slot),'[]'::jsonb) INTO result_rows
 FROM attendance_version_results m JOIN attendance_results r ON r.id=m.result_id JOIN scheduled_shifts o ON o.id=r.scheduled_shift_id WHERE m.version_id=vid;
 SELECT COALESCE(jsonb_agg(to_jsonb(i) ORDER BY i.id),'[]'::jsonb) INTO issue_rows FROM attendance_issues i WHERE i.id=ANY(attendance_issue_ids_for_period(p.id));
 RETURN jsonb_build_object('schemaVersion',1,'version_identity',jsonb_build_object('id',v.id,'period_id',v.period_id,'version_no',v.version_no,'policy_id',v.policy_id,'previous_version_id',v.previous_version_id),
  'period',jsonb_build_object('id',p.id,'cycle_id',p.cycle_id,'start_date',p.start_date,'end_date',p.end_date),
  'cycle',jsonb_build_object('id',c.id,'code',c.code,'revision',c.revision,'start_day',c.start_day,'end_day',c.end_day,'month_end',c.month_end,'timezone',c.timezone),
  'policy',(SELECT to_jsonb(x) FROM attendance_policy_versions x WHERE x.id=v.policy_id),
  'reopen',jsonb_build_object('actor_id',v.reopened_by_id,'at',v.reopened_at,'reason',v.reopen_reason),
  'results',result_rows,'issues',issue_rows);
END $$;
CREATE FUNCTION attendance_version_summary(vid bigint) RETURNS jsonb LANGUAGE plpgsql AS $$
DECLARE snap jsonb; completed jsonb; presence_counts jsonb;
BEGIN
 snap:=attendance_version_snapshot(vid);
 SELECT COALESCE(jsonb_object_agg(k,n),'{}'::jsonb) INTO completed FROM(SELECT x->'result'->>'completion' k,count(*)n FROM jsonb_array_elements(snap->'results')x GROUP BY 1)q;
 SELECT COALESCE(jsonb_object_agg(k,n),'{}'::jsonb) INTO presence_counts FROM(SELECT x->'result'->>'presence' k,count(*)n FROM jsonb_array_elements(snap->'results')x GROUP BY 1)q;
 RETURN jsonb_build_object('schemaVersion',1,'scope','DATABASE_STATE_AND_REFERENCES_ONLY','operational_finalization_hold',true,
  'result_count',jsonb_array_length(snap->'results'),'completion_counts',completed,'presence_counts',presence_counts,'source_snapshot',snap);
END $$;
CREATE FUNCTION attendance_version_source_hash(vid bigint) RETURNS varchar(64) LANGUAGE sql VOLATILE AS $$
 SELECT encode(sha256(convert_to(attendance_version_snapshot(vid)::text,'UTF8')),'hex')::varchar(64)
$$;
CREATE FUNCTION attendance_verify_version_hash(vid bigint) RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT sealed_at IS NOT NULL AND source_hash=encode(sha256(convert_to((summary->'source_snapshot')::text,'UTF8')),'hex')
 FROM attendance_period_versions WHERE id=vid
$$;

CREATE FUNCTION attendance_version_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE p attendance_periods; prior attendance_period_versions; n integer; required_summary jsonb; last_calc timestamptz; tz text;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_OP='INSERT' THEN PERFORM attendance_begin_period_write(NEW.period_id);ELSE PERFORM attendance_begin_period_write(OLD.period_id); END IF;
 IF TG_OP<>'INSERT' AND OLD.sealed_at IS NOT NULL THEN
  IF TG_OP='DELETE' OR NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'Sealed version header is immutable' USING ERRCODE='23514'; END IF;
  RETURN NEW;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 SELECT * INTO p FROM attendance_periods WHERE id=NEW.period_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Period must already be visible before version assembly gate' USING ERRCODE='23503'; END IF;
 IF p.state<>'REVIEWING' THEN RAISE EXCEPTION 'Build/seal versions only in REVIEWING' USING ERRCODE='23514'; END IF;
 IF NOT EXISTS(SELECT 1 FROM attendance_policy_versions a WHERE a.id=NEW.policy_id
  AND daterange(a.effective_from,a.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]')) THEN
  RAISE EXCEPTION 'Version policy must be a real policy applicable within this Period; selection across policy changes remains an orchestration HOLD' USING ERRCODE='23514'; END IF;
 IF TG_OP='INSERT' THEN
  SELECT COALESCE(max(version_no),0)+1 INTO n FROM attendance_period_versions WHERE period_id=p.id;
  IF NEW.version_no<>n OR NEW.previous_version_id IS DISTINCT FROM p.current_finalized_version_id OR NEW.sealed_at IS NOT NULL
   OR ROW(NEW.reopened_by_id,NEW.reopened_at,NEW.reopen_reason) IS DISTINCT FROM ROW(p.reopened_by_id,p.reopened_at,p.reopen_reason) THEN
   RAISE EXCEPTION 'BUILDING header needs next sequence, existing same-Period predecessor and exact explicit reopen evidence' USING ERRCODE='23514'; END IF;
  IF NEW.previous_version_id IS NOT NULL THEN
   SELECT * INTO prior FROM attendance_period_versions WHERE id=NEW.previous_version_id;
   IF prior.id IS NULL OR prior.period_id<>p.id OR prior.sealed_at IS NULL OR prior.version_no>=NEW.version_no THEN
    RAISE EXCEPTION 'Previous version must already be a lower sealed version of same Period; no forward/cyclic references' USING ERRCODE='23514'; END IF;
  END IF;
 ELSE
  IF to_jsonb(NEW)-ARRAY['finalized_by_id','finalized_at','sealed_at','source_hash','summary','version'] IS DISTINCT FROM
     to_jsonb(OLD)-ARRAY['finalized_by_id','finalized_at','sealed_at','source_hash','summary','version'] THEN
   RAISE EXCEPTION 'Version identity/policy/reopen source is fixed from BUILDING header' USING ERRCODE='23514'; END IF;
  IF NEW.sealed_at IS NOT NULL THEN
   PERFORM attendance_validate_seal(OLD.id);
   required_summary:=attendance_version_summary(OLD.id);
   IF NEW.summary IS DISTINCT FROM required_summary OR NEW.source_hash IS DISTINCT FROM attendance_version_source_hash(OLD.id) THEN
    RAISE EXCEPTION 'SEAL summary/hash must fingerprint actual typed source rows, never fabricated unknown snapshots' USING ERRCODE='23514'; END IF;
   SELECT max(r.calculated_at) INTO last_calc FROM attendance_version_results m JOIN attendance_results r ON r.id=m.result_id WHERE m.version_id=OLD.id;
   SELECT timezone INTO tz FROM attendance_cycles WHERE id=p.cycle_id;
   IF NEW.finalized_at<last_calc OR NEW.finalized_at<p.reopened_at OR NEW.finalized_at<((p.end_date+1)::timestamp AT TIME ZONE tz) OR
      EXISTS(SELECT 1 FROM attendance_issues i WHERE i.id=ANY(attendance_issue_ids_for_period(p.id)) AND i.resolved_at>NEW.finalized_at) THEN
    RAISE EXCEPTION 'Finalization evidence cannot precede its source/audit or configured Period end' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_version_assembly BEFORE INSERT OR UPDATE OR DELETE ON attendance_period_versions FOR EACH ROW EXECUTE FUNCTION attendance_version_guard();
CREATE FUNCTION attendance_seal_current_pair() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.sealed_at IS NOT NULL AND OLD.sealed_at IS NULL AND NOT EXISTS(SELECT 1 FROM attendance_periods p WHERE p.id=NEW.period_id AND p.state='FINALIZED' AND p.current_finalized_version_id=NEW.id) THEN
  RAISE EXCEPTION 'SEAL and same-Period current pointer/FINALIZED must complete atomically' USING ERRCODE='23514'; END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER attendance_seal_pair AFTER UPDATE ON attendance_period_versions DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION attendance_seal_current_pair();

CREATE FUNCTION attendance_legacy_mapping_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE a attendances; c attendance_closings; v attendance_period_versions; p attendance_periods;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF NEW.attendance_id IS NOT NULL THEN SELECT * INTO a FROM attendances WHERE id=NEW.attendance_id; END IF;
 IF NEW.closing_id IS NOT NULL THEN SELECT * INTO c FROM attendance_closings WHERE id=NEW.closing_id; END IF;
 IF a.id IS NOT NULL AND c.id IS NOT NULL AND a.closing_id IS DISTINCT FROM c.id THEN
  RAISE EXCEPTION 'Both legacy sources must have an actual existing closing relationship' USING ERRCODE='23514'; END IF;
 IF NEW.period_version_id IS NOT NULL THEN
  SELECT * INTO v FROM attendance_period_versions WHERE id=NEW.period_version_id;SELECT * INTO p FROM attendance_periods WHERE id=v.period_id;
  IF v.id IS NOT NULL AND (v.sealed_at IS NULL OR a.id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM attendance_version_results m WHERE m.version_id=v.id AND m.employee_id=a.employee_id AND m.work_date=a.work_date)
   OR c.id IS NOT NULL AND NOT (daterange(c.period_start,c.period_end,'[]') && daterange(p.start_date,p.end_date,'[]'))) THEN
   RAISE EXCEPTION 'Optional new link needs actual sealed source membership/overlap; legacy aggregate is never fabricated raw evidence' USING ERRCODE='23514'; END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_legacy_mapping_source BEFORE INSERT ON legacy_attendance_mappings FOR EACH ROW EXECUTE FUNCTION attendance_legacy_mapping_guard();
CREATE FUNCTION attendance_finalization_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN PERFORM attendance_finalization_require_rc();RAISE EXCEPTION '% history is immutable; append a typed revision/event',TG_TABLE_NAME USING ERRCODE='23514'; END $$;
DO $$ DECLARE t text;BEGIN
 FOREACH t IN ARRAY ARRAY['attendance_results','legacy_attendance_mappings'] LOOP
  EXECUTE format('CREATE TRIGGER attendance_finalization_append_only BEFORE UPDATE OR DELETE ON %I FOR EACH ROW EXECUTE FUNCTION attendance_finalization_immutable()',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['attendance_cycles','attendance_cycle_schedules','attendance_periods','attendance_period_versions','attendance_results','attendance_version_results','attendance_issues','legacy_attendance_mappings'] LOOP
  EXECUTE format('CREATE TRIGGER attendance_finalization_no_truncate BEFORE TRUNCATE ON %I FOR EACH STATEMENT EXECUTE FUNCTION attendance_finalization_immutable()',t);
 END LOOP;
END $$;
COMMENT ON TABLE attendance_period_versions IS 'Immutable source snapshots and typed Result memberships. Structural SEAL is not operational finalization approval: OPERATIONAL_FINALIZATION_HOLD until full expected-work/eligibility/OT/permission gates exist.';
COMMENT ON COLUMN attendance_period_versions.reopened_by_id IS 'Typed immutable copy of actual Period REOPEN event, paired with reopened_at/reopen_reason; preserves every reopen across refinalization.';
COMMENT ON COLUMN attendance_issues.result_id IS 'Exact Result revision for decision/audit, including Accepted INCOMPLETE timestamp stored in resolved_at; never invent from calculated_at.';
COMMENT ON COLUMN attendance_issues.missing_request_id IS 'Real typed pending/apply source, not a JSON ID or invented request.';
COMMENT ON COLUMN attendance_issues.schedule_assignment_id IS 'Real configuration-gap source even when no ScheduledShift/Cycle coverage exists.';
COMMENT ON TABLE legacy_attendance_mappings IS 'Historical aggregate identity observation only; no raw log synthesis, official OT, Payroll or fabricated finalized version.';

