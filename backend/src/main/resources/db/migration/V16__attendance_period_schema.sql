CREATE TRIGGER z_attendance_period_assignment BEFORE INSERT OR UPDATE OR DELETE ON employee_schedule_assignments FOR EACH ROW EXECUTE FUNCTION attendance_schedule_registry_guard();

CREATE FUNCTION attendance_leave_source_gate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE emp bigint; new_emp bigint; req bigint; ids bigint[]:=ARRAY[]::bigint[]; d record; is_applied boolean:=false; pinned boolean;
BEGIN
 IF TG_TABLE_NAME='workflow_requests' THEN
  IF OLD.request_type<>'LEAVE' AND NEW.request_type<>'LEAVE' THEN RETURN NEW; END IF;
  IF ROW(OLD.target_employee_id,OLD.status,OLD.request_type) IS NOT DISTINCT FROM ROW(NEW.target_employee_id,NEW.status,NEW.request_type) THEN RETURN NEW; END IF;
  emp:=OLD.target_employee_id;new_emp:=NEW.target_employee_id;
  PERFORM attendance_pin_source_registry(emp);IF new_emp IS DISTINCT FROM emp THEN PERFORM attendance_pin_source_registry(new_emp); END IF;
  FOR d IN SELECT x.* FROM leave_request_days x JOIN leave_requests r ON r.id=x.request_id WHERE r.workflow_request_id=OLD.id LOOP
   ids:=ids||attendance_period_ids_for_employee_date(emp,d.leave_date)||attendance_period_ids_for_employee_date(new_emp,d.leave_date);
  END LOOP;
  PERFORM attendance_lock_periods(ids,true);
  IF ROW(OLD.target_employee_id,OLD.request_type) IS DISTINCT FROM ROW(NEW.target_employee_id,NEW.request_type) AND EXISTS(
   SELECT 1 FROM attendance_results z JOIN leave_request_days x ON x.id=z.leave_day_id JOIN leave_requests r ON r.id=x.request_id WHERE r.workflow_request_id=OLD.id) THEN
   RAISE EXCEPTION 'Attendance Result pins its Leave Workflow owner/type' USING ERRCODE='23514'; END IF;
  IF OLD.status IN('APPROVED','COMPLETED') OR NEW.status IN('APPROVED','COMPLETED') THEN PERFORM attendance_assert_unfinalized(ids); END IF;
  RETURN NEW;
 END IF;
 IF TG_OP='INSERT' THEN req:=NEW.request_id;ELSE req:=OLD.request_id; END IF;
 SELECT w.target_employee_id,w.status IN('APPROVED','COMPLETED') INTO emp,is_applied FROM leave_requests r JOIN workflow_requests w ON w.id=r.workflow_request_id WHERE r.id=req;
 IF NOT FOUND THEN RAISE EXCEPTION 'Leave parent and Workflow must already be visible before source gate' USING ERRCODE='23503'; END IF;
 PERFORM attendance_pin_source_registry(emp);
 IF TG_OP<>'INSERT' THEN
  SELECT EXISTS(SELECT 1 FROM attendance_results WHERE leave_day_id=OLD.id) INTO pinned;
  IF pinned AND (TG_OP='DELETE' OR to_jsonb(OLD)-ARRAY['updated_at','updated_by','version'] IS DISTINCT FROM to_jsonb(NEW)-ARRAY['updated_at','updated_by','version']) THEN
   RAISE EXCEPTION 'Attendance-used Leave Day payload is historical; correction needs new domain provenance' USING ERRCODE='23514'; END IF;
  ids:=ids||attendance_period_ids_for_employee_date(emp,OLD.leave_date);
 END IF;
 IF TG_OP<>'DELETE' THEN ids:=ids||attendance_period_ids_for_employee_date(emp,NEW.leave_date); END IF;
 -- Identity/delete is rejected before waiting on period roots, avoiding a
 -- destructive FK-key lock -> Period -> FK-key lock cycle.
 IF cardinality(ids)>0 AND (TG_OP='DELETE' OR TG_OP='UPDATE' AND ROW(NEW.id,NEW.request_id,NEW.leave_date,NEW.segment) IS DISTINCT FROM ROW(OLD.id,OLD.request_id,OLD.leave_date,OLD.segment)) THEN
  RAISE EXCEPTION 'Known-period Leave Day identity cannot be erased/reparented' USING ERRCODE='23514'; END IF;
 PERFORM attendance_lock_periods(ids,true);
 IF is_applied THEN PERFORM attendance_assert_unfinalized(ids); END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER a0_attendance_leave_day_gate BEFORE INSERT OR UPDATE OR DELETE ON leave_request_days FOR EACH ROW EXECUTE FUNCTION attendance_leave_source_gate();
CREATE TRIGGER a0_attendance_leave_workflow_gate BEFORE UPDATE ON workflow_requests FOR EACH ROW EXECUTE FUNCTION attendance_leave_source_gate();
