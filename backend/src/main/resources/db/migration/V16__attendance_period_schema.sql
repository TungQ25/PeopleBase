-- Attendance Period, Results and immutable Finalized Version foundation.
-- No calculation/approval/matching/OT engine, no seeds, no historical backfill.
-- V1-V15 stay unchanged. OPERATIONAL_FINALIZATION_HOLD remains explicit.
-- Six typed audit/source metadata additions are documented in design_decisions.json.

