CREATE FUNCTION attendance_period_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE c attendance_cycles; v attendance_period_versions; schedules bigint[]; employees bigint[];
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Attendance Period history is retained' USING ERRCODE='23514'; END IF;
 IF TG_OP='INSERT' THEN
  SELECT array_agg(DISTINCT schedule_id ORDER BY schedule_id) INTO schedules FROM attendance_cycle_schedules WHERE cycle_id=NEW.cycle_id;
  SELECT array_agg(DISTINCT employee_id ORDER BY employee_id) INTO employees FROM employee_schedule_assignments WHERE schedule_id=ANY(schedules);
  PERFORM attendance_lock_registry(employees,schedules,true);
  SELECT * INTO c FROM attendance_cycles WHERE id=NEW.cycle_id FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Cycle must already be visible before Period configuration gate' USING ERRCODE='23503'; END IF;
  IF NEW.state<>'OPEN' OR NEW.current_finalized_version_id IS NOT NULL OR NEW.reopened_by_id IS NOT NULL OR NEW.reopened_at IS NOT NULL OR NEW.reopen_reason IS NOT NULL THEN
   RAISE EXCEPTION 'New Period starts OPEN without fake finalized/reopen pointers' USING ERRCODE='23514'; END IF;
  IF NEW.end_date IS DISTINCT FROM attendance_expected_period_end(NEW.start_date,NEW.cycle_id) OR
   NOT (daterange(NEW.start_date,NEW.end_date,'[]') <@ daterange(c.effective_from,c.effective_to,'[)')) THEN
   RAISE EXCEPTION 'Period dates must match its effective Cycle configuration' USING ERRCODE='23514'; END IF;
  IF NOT (daterange(NEW.start_date,NEW.end_date,'[]') <@ COALESCE((SELECT range_agg(daterange(s.effective_from,s.effective_to,'[)'))
    FROM organization_settings s WHERE s.approved_at IS NOT NULL AND s.approved_by_id IS NOT NULL AND s.business_timezone=c.timezone),'{}'::datemultirange)) THEN
   RAISE EXCEPTION 'Period needs approved business timezone coverage, not session timezone' USING ERRCODE='23514'; END IF;
 ELSE
  IF to_jsonb(OLD)-ARRAY['state','current_finalized_version_id','reopened_by_id','reopened_at','reopen_reason','version']
    IS DISTINCT FROM to_jsonb(NEW)-ARRAY['state','current_finalized_version_id','reopened_by_id','reopened_at','reopen_reason','version'] THEN
   RAISE EXCEPTION 'Period identity/dates are immutable' USING ERRCODE='23514'; END IF;
  IF NEW.state IS DISTINCT FROM OLD.state AND NOT(
   OLD.state='OPEN' AND NEW.state='REVIEWING' OR OLD.state='REVIEWING' AND NEW.state='FINALIZED' OR
   OLD.state='FINALIZED' AND NEW.state='REOPENED' OR OLD.state='REOPENED' AND NEW.state='REVIEWING') THEN
   RAISE EXCEPTION 'Invalid Attendance Period transition' USING ERRCODE='23514'; END IF;
  IF OLD.state='FINALIZED' AND NEW.state='REOPENED' THEN
   SELECT * INTO v FROM attendance_period_versions WHERE id=OLD.current_finalized_version_id;
   IF NEW.reopened_by_id IS NULL OR NEW.reopened_at IS NULL OR NEW.reopen_reason IS NULL OR btrim(NEW.reopen_reason)=''
    OR NEW.reopened_at<v.finalized_at OR (OLD.reopened_at IS NOT NULL AND NEW.reopened_at<=OLD.reopened_at) THEN
    RAISE EXCEPTION 'REOPEN needs a new explicit actor/time/reason after the prior finalize event' USING ERRCODE='23514'; END IF;
  ELSIF ROW(NEW.reopened_by_id,NEW.reopened_at,NEW.reopen_reason) IS DISTINCT FROM ROW(OLD.reopened_by_id,OLD.reopened_at,OLD.reopen_reason) THEN
   RAISE EXCEPTION 'Reopen evidence changes only on FINALIZED to REOPENED' USING ERRCODE='23514'; END IF;
  IF NEW.current_finalized_version_id IS DISTINCT FROM OLD.current_finalized_version_id AND NOT(OLD.state='REVIEWING' AND NEW.state='FINALIZED') THEN
   RAISE EXCEPTION 'Current version changes only with a new FINALIZED transition' USING ERRCODE='23514'; END IF;
  IF OLD.state='REVIEWING' AND NEW.state='FINALIZED' THEN
   SELECT * INTO v FROM attendance_period_versions WHERE id=NEW.current_finalized_version_id;
   IF NOT FOUND OR v.period_id<>NEW.id OR v.sealed_at IS NULL OR NEW.current_finalized_version_id IS NOT DISTINCT FROM OLD.current_finalized_version_id
    OR v.previous_version_id IS DISTINCT FROM OLD.current_finalized_version_id THEN
    RAISE EXCEPTION 'FINALIZED needs a newly sealed same-Period version linked to the previous current version' USING ERRCODE='23514'; END IF;
  END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER attendance_period_state BEFORE INSERT OR UPDATE OR DELETE ON attendance_periods FOR EACH ROW EXECUTE FUNCTION attendance_period_guard();

CREATE FUNCTION attendance_period_ids_for_employee_date(emp bigint,day_value date) RETURNS bigint[] LANGUAGE sql STABLE AS $$
 SELECT COALESCE(array_agg(DISTINCT p.id ORDER BY p.id),ARRAY[]::bigint[])
 FROM employee_schedule_assignments a JOIN attendance_cycle_schedules x ON x.schedule_id=a.schedule_id
 JOIN attendance_periods p ON p.cycle_id=x.cycle_id WHERE a.employee_id=emp
  AND day_value <@ daterange(a.effective_from,a.effective_to,'[)') AND day_value <@ daterange(x.effective_from,x.effective_to,'[)')
  AND day_value BETWEEN p.start_date AND p.end_date
$$;

-- Runs BEFORE V15 source/parent-log locks. Ordinary raw collection takes only
-- compatible SHARE locks and remains allowed in FINALIZED. Missing application,
-- correction and matching take root write locks and must REOPEN known closed scope.
CREATE FUNCTION attendance_period_source_gate() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE emp bigint; lid bigint; sid bigint; instant timestamptz; original_at timestamptz; effective_at timestamptz;
        ids bigint[]:=ARRAY[]::bigint[]; write_mode boolean:=true;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_TABLE_NAME='attendance_logs' THEN
  emp:=NEW.employee_id; instant:=NEW.event_at; write_mode:=NEW.missing_request_id IS NOT NULL;
  IF NEW.missing_request_id IS NOT NULL THEN
   SELECT scheduled_shift_id INTO sid FROM missing_attendance_requests WHERE id=NEW.missing_request_id;
   IF NOT FOUND THEN RAISE EXCEPTION 'Missing application source must already be visible' USING ERRCODE='23503'; END IF;
  END IF;
 ELSIF TG_TABLE_NAME='attendance_log_revisions' THEN
  lid:=NEW.log_id; instant:=NEW.event_at;
 ELSIF TG_TABLE_NAME='attendance_log_matches' THEN
  lid:=NEW.log_id; sid:=NEW.scheduled_shift_id;
 ELSE
  IF TG_OP='UPDATE' AND NEW.applied_at IS NOT DISTINCT FROM OLD.applied_at OR NEW.applied_at IS NULL THEN RETURN NEW; END IF;
  sid:=NEW.scheduled_shift_id; instant:=NEW.proposed_event_at;
  SELECT target_employee_id INTO emp FROM workflow_requests WHERE id=NEW.workflow_request_id;
 END IF;
 IF lid IS NOT NULL THEN
  SELECT employee_id,event_at INTO emp,original_at FROM attendance_logs WHERE id=lid;
  IF NOT FOUND THEN RAISE EXCEPTION 'Raw parent must already be visible before Period source gate' USING ERRCODE='23503'; END IF;
  SELECT effective_event_at INTO effective_at FROM attendance_effective_logs WHERE log_id=lid;
 END IF;
 PERFORM attendance_pin_source_registry(emp,lid,sid);
 ids:=attendance_period_ids_for_event(emp,instant,lid)||attendance_period_ids_for_event(emp,original_at,lid)||
      attendance_period_ids_for_event(emp,effective_at,lid)||attendance_period_ids_for_shift(sid);
 PERFORM attendance_lock_periods(ids,write_mode);
 IF write_mode THEN PERFORM attendance_assert_unfinalized(ids); END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER a0_attendance_period_raw_gate BEFORE INSERT ON attendance_logs FOR EACH ROW EXECUTE FUNCTION attendance_period_source_gate();
CREATE TRIGGER a0_attendance_period_revision_gate BEFORE INSERT ON attendance_log_revisions FOR EACH ROW EXECUTE FUNCTION attendance_period_source_gate();
CREATE TRIGGER a0_attendance_period_matching_gate BEFORE INSERT ON attendance_log_matches FOR EACH ROW EXECUTE FUNCTION attendance_period_source_gate();
CREATE TRIGGER a0_attendance_period_missing_gate BEFORE INSERT OR UPDATE ON missing_attendance_requests FOR EACH ROW EXECUTE FUNCTION attendance_period_source_gate();

CREATE FUNCTION attendance_schedule_registry_guard() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE emp_ids bigint[]; schedule_ids bigint[]; ids bigint[]; last_end date; row_id bigint;
BEGIN
 PERFORM attendance_finalization_require_rc();
 IF TG_TABLE_NAME='scheduled_shifts' THEN
  SELECT schedule_id INTO row_id FROM employee_schedule_assignments WHERE id=NEW.schedule_assignment_id;
  PERFORM attendance_lock_registry(ARRAY[NEW.employee_id],ARRAY[row_id],true);
  -- The new row is not visible through its id yet: resolve directly from its
  -- real assignment's schedule and supplied work_date, not a fake occurrence.
  SELECT array_agg(DISTINCT p.id ORDER BY p.id) INTO ids FROM attendance_cycle_schedules x JOIN attendance_periods p ON p.cycle_id=x.cycle_id
   WHERE x.schedule_id=row_id AND NEW.work_date <@ daterange(x.effective_from,x.effective_to,'[)') AND NEW.work_date BETWEEN p.start_date AND p.end_date;
  PERFORM attendance_lock_periods(ids,true);PERFORM attendance_assert_unfinalized(ids);RETURN NEW;
 END IF;
 IF TG_OP='INSERT' THEN emp_ids:=ARRAY[NEW.employee_id];schedule_ids:=ARRAY[NEW.schedule_id];
 ELSE emp_ids:=ARRAY[OLD.employee_id];schedule_ids:=ARRAY[OLD.schedule_id]; END IF;
 IF TG_OP='UPDATE' THEN emp_ids:=emp_ids||NEW.employee_id;schedule_ids:=schedule_ids||NEW.schedule_id; END IF;
 PERFORM attendance_lock_registry(emp_ids,schedule_ids,true);
 IF TG_OP<>'INSERT' THEN ids:=attendance_period_ids_for_assignment(OLD.id); END IF;
 IF TG_OP<>'DELETE' THEN
  SELECT COALESCE(ids,ARRAY[]::bigint[])||COALESCE(array_agg(DISTINCT p.id ORDER BY p.id),ARRAY[]::bigint[]) INTO ids
   FROM attendance_cycle_schedules x JOIN attendance_periods p ON p.cycle_id=x.cycle_id WHERE x.schedule_id=NEW.schedule_id
    AND daterange(NEW.effective_from,NEW.effective_to,'[)') && daterange(x.effective_from,x.effective_to,'[)')
    AND daterange(NEW.effective_from,NEW.effective_to,'[)') && daterange(p.start_date,p.end_date,'[]');
 END IF;
 PERFORM attendance_lock_periods(ids,true);
 IF TG_OP='INSERT' THEN PERFORM attendance_assert_unfinalized(ids);
 ELSE
  SELECT max(end_date) INTO last_end FROM attendance_periods p WHERE id=ANY(ids) AND EXISTS(
   SELECT 1 FROM attendance_period_versions v WHERE v.period_id=p.id AND v.sealed_at IS NOT NULL);
  IF TG_OP='UPDATE' AND EXISTS(SELECT 1 FROM attendance_issues WHERE schedule_assignment_id=OLD.id AND employee_id IS DISTINCT FROM NEW.employee_id) THEN
   RAISE EXCEPTION 'Configuration Issue pins its Assignment Employee' USING ERRCODE='23514'; END IF;
  IF last_end IS NOT NULL AND (TG_OP='DELETE' OR NEW IS DISTINCT FROM OLD AND NOT(
   OLD.effective_to IS NULL AND NEW.effective_to IS NOT NULL AND NEW.effective_to>last_end AND
   to_jsonb(OLD)-ARRAY['effective_to','updated_at','updated_by','version']=to_jsonb(NEW)-ARRAY['effective_to','updated_at','updated_by','version'])) THEN
   RAISE EXCEPTION 'Sealed as-of Assignment/Cycle provenance must be preserved' USING ERRCODE='23514'; END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
